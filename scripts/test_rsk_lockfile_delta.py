from __future__ import annotations

import json
from pathlib import Path
import sys
import unittest

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import rsk_lockfile_delta as delta

BASE = '''# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "hex"\nversion = "0.4.3"\nsource = "registry+x"\nchecksum = "a"\n\n[[package]]\nname = "serde_json"\nversion = "1.0.0"\nsource = "registry+x"\nchecksum = "b"\n\n[[package]]\nname = "sha2"\nversion = "0.10.9"\nsource = "registry+x"\nchecksum = "c"\n\n[[package]]\nname = "other"\nversion = "1.2.3"\nsource = "registry+x"\nchecksum = "d"\ndependencies = ["hex"]\n'''

RSK = '''\n[[package]]\nname = "symthaea-replicator-ledger"\nversion = "0.1.0"\ndependencies = ["symthaea-replicator-safety"]\n\n[[package]]\nname = "symthaea-replicator-safety"\nversion = "0.1.0"\ndependencies = ["hex", "serde_json", "sha2", "symthaea-replicator-semantics"]\n\n[[package]]\nname = "symthaea-replicator-semantics"\nversion = "0.1.0"\n'''

FEATURE_BASE = BASE + '''\n[[package]]\nname = "digest"\nversion = "0.10.7"\nsource = "registry+x"\nchecksum = "digest-checksum"\n\n[[package]]\nname = "const-oid"\nversion = "0.9.6"\nsource = "registry+x"\nchecksum = "const-oid-checksum"\n'''

FEATURE_AFTER = FEATURE_BASE.replace(
    'name = "digest"\nversion = "0.10.7"\nsource = "registry+x"\nchecksum = "digest-checksum"',
    'name = "digest"\nversion = "0.10.7"\nsource = "registry+x"\nchecksum = "digest-checksum"\ndependencies = ["const-oid 0.9.6"]',
) + RSK


def metadata(*, digest_to_const_oid: bool = True) -> bytes:
    ids = {
        "ledger": "path+ledger#0.1.0",
        "safety": "path+safety#0.1.0",
        "semantics": "path+semantics#0.1.0",
        "sha2": "registry+x#sha2@0.10.9",
        "digest": "registry+x#digest@0.10.7",
        "const_oid": "registry+x#const-oid@0.9.6",
        "hex": "registry+x#hex@0.4.3",
        "serde_json": "registry+x#serde_json@1.0.0",
        "other": "registry+x#other@1.2.3",
    }
    packages = [
        {"id": ids["ledger"], "name": "symthaea-replicator-ledger", "version": "0.1.0", "source": None},
        {"id": ids["safety"], "name": "symthaea-replicator-safety", "version": "0.1.0", "source": None},
        {"id": ids["semantics"], "name": "symthaea-replicator-semantics", "version": "0.1.0", "source": None},
        {"id": ids["sha2"], "name": "sha2", "version": "0.10.9", "source": "registry+x"},
        {"id": ids["digest"], "name": "digest", "version": "0.10.7", "source": "registry+x"},
        {"id": ids["const_oid"], "name": "const-oid", "version": "0.9.6", "source": "registry+x"},
        {"id": ids["hex"], "name": "hex", "version": "0.4.3", "source": "registry+x"},
        {"id": ids["serde_json"], "name": "serde_json", "version": "1.0.0", "source": "registry+x"},
        {"id": ids["other"], "name": "other", "version": "1.2.3", "source": "registry+x"},
    ]

    def dep(target: str) -> dict:
        return {"name": target, "pkg": ids[target], "dep_kinds": [{"kind": None, "target": None}]}

    nodes = [
        {"id": ids["ledger"], "deps": [dep("safety")]},
        {"id": ids["safety"], "deps": [dep("sha2"), dep("semantics"), dep("hex"), dep("serde_json")]},
        {"id": ids["semantics"], "deps": []},
        {"id": ids["sha2"], "deps": [dep("digest")]},
        {"id": ids["digest"], "deps": [dep("const_oid")] if digest_to_const_oid else []},
        {"id": ids["const_oid"], "deps": []},
        {"id": ids["hex"], "deps": []},
        {"id": ids["serde_json"], "deps": []},
        {"id": ids["other"], "deps": [dep("hex")]},
    ]
    return json.dumps({"packages": packages, "resolve": {"nodes": nodes}}).encode()


def q(before: str, after: str, cargo_metadata: bytes | None = None) -> dict:
    return delta.qualify_lockfile_delta(
        before.encode(), after.encode(), cargo_metadata
    )


class LockfileDeltaTests(unittest.TestCase):
    def test_accepts_only_expected_rsk_path_records(self) -> None:
        report = q(BASE, BASE + RSK)
        self.assertEqual(report["status"], "rsk-path-records-added")
        self.assertEqual(
            report["added_rsk_packages"],
            [
                "symthaea-replicator-ledger",
                "symthaea-replicator-safety",
                "symthaea-replicator-semantics",
            ],
        )
        self.assertEqual(report["allowed_preexisting_dependency_edge_additions"], [])

    def test_accepts_observed_feature_unification_edge_with_metadata_proof(self) -> None:
        report = q(FEATURE_BASE, FEATURE_AFTER, metadata())
        self.assertEqual(
            report["status"], "rsk-path-records-and-proved-feature-edges-added"
        )
        edges = report["allowed_preexisting_dependency_edge_additions"]
        self.assertEqual(len(edges), 1)
        self.assertEqual(edges[0]["source"], "digest 0.10.7 (registry+x)")
        self.assertEqual(edges[0]["target"], "const-oid 0.9.6 (registry+x)")
        self.assertEqual(
            edges[0]["proof_path"],
            [
                "symthaea-replicator-safety 0.1.0",
                "sha2 0.10.9 (registry+x)",
                "digest 0.10.7 (registry+x)",
                "const-oid 0.9.6 (registry+x)",
            ],
        )

    def test_feature_edge_requires_metadata(self) -> None:
        with self.assertRaisesRegex(delta.LockfileDeltaError, "metadata proof is required"):
            q(FEATURE_BASE, FEATURE_AFTER)

    def test_feature_edge_must_exist_in_metadata(self) -> None:
        with self.assertRaisesRegex(delta.LockfileDeltaError, "metadata lacks edge"):
            q(FEATURE_BASE, FEATURE_AFTER, metadata(digest_to_const_oid=False))

    def test_rejects_dependency_edge_outside_rsk_closure(self) -> None:
        candidate = (FEATURE_BASE + RSK).replace(
            'name = "other"\nversion = "1.2.3"\nsource = "registry+x"\nchecksum = "d"\ndependencies = ["hex"]',
            'name = "other"\nversion = "1.2.3"\nsource = "registry+x"\nchecksum = "d"\ndependencies = ["hex", "const-oid 0.9.6"]',
        )
        with self.assertRaisesRegex(delta.LockfileDeltaError, "not reachable from an RSK"):
            q(FEATURE_BASE, candidate, metadata())

    def test_rejects_dependency_edge_deletion(self) -> None:
        before = FEATURE_AFTER
        after = FEATURE_BASE + RSK
        with self.assertRaisesRegex(delta.LockfileDeltaError, "removed dependency edges"):
            q(before, after, metadata())

    def test_rejects_target_not_already_pinned(self) -> None:
        candidate = FEATURE_AFTER.replace(
            'dependencies = ["const-oid 0.9.6"]',
            'dependencies = ["surprise 1.0.0"]',
        ) + '\n[[package]]\nname = "surprise"\nversion = "1.0.0"\nsource = "registry+x"\nchecksum = "x"\n'
        with self.assertRaisesRegex(delta.LockfileDeltaError, "non-RSK package graph drift"):
            q(FEATURE_BASE, candidate, metadata())

    def test_already_repaired_is_idempotent(self) -> None:
        report = q(BASE + RSK, BASE + RSK)
        self.assertEqual(report["status"], "already-qualified-no-rsk-delta")
        self.assertEqual(report["added_rsk_packages"], [])

    def test_rejects_unrelated_version_checksum_or_dependency_drift(self) -> None:
        cases = [
            (BASE + RSK).replace('version = "1.2.3"', 'version = "1.2.4"'),
            (BASE + RSK).replace('checksum = "d"', 'checksum = "e"'),
            (BASE + RSK).replace('dependencies = ["hex"]', 'dependencies = ["sha2"]'),
        ]
        for candidate in cases:
            with self.subTest(candidate=candidate):
                with self.assertRaisesRegex(delta.LockfileDeltaError, "non-RSK package graph drift"):
                    q(BASE, candidate)

    def test_rejects_unrelated_new_or_removed_package(self) -> None:
        added = BASE + RSK + '\n[[package]]\nname = "surprise"\nversion = "9.9.9"\n'
        with self.assertRaisesRegex(delta.LockfileDeltaError, "non-RSK package graph drift"):
            q(BASE, added)

        removed = (BASE + RSK).replace(
            '[[package]]\nname = "other"\nversion = "1.2.3"\nsource = "registry+x"\nchecksum = "d"\ndependencies = ["hex"]\n',
            '',
        )
        with self.assertRaisesRegex(delta.LockfileDeltaError, "non-RSK package graph drift"):
            q(BASE, removed)

    def test_rejects_missing_duplicate_or_wrong_rsk_edges(self) -> None:
        with self.assertRaisesRegex(delta.LockfileDeltaError, "exactly one package record"):
            q(BASE, BASE + RSK.replace(
                '[[package]]\nname = "symthaea-replicator-semantics"\nversion = "0.1.0"\n',
                '',
            ))

        duplicate = BASE + RSK + '\n[[package]]\nname = "symthaea-replicator-semantics"\nversion = "0.1.0"\n'
        with self.assertRaisesRegex(delta.LockfileDeltaError, "exactly one package record"):
            q(BASE, duplicate)

        wrong = (BASE + RSK).replace(
            'dependencies = ["symthaea-replicator-safety"]',
            'dependencies = ["hex"]',
        )
        with self.assertRaisesRegex(delta.LockfileDeltaError, "dependency set mismatch"):
            q(BASE, wrong)

    def test_rejects_registry_identity_on_workspace_path_package(self) -> None:
        wrong = (BASE + RSK).replace(
            'name = "symthaea-replicator-semantics"\nversion = "0.1.0"',
            'name = "symthaea-replicator-semantics"\nversion = "0.1.0"\nsource = "registry+x"\nchecksum = "bad"',
        )
        with self.assertRaisesRegex(delta.LockfileDeltaError, "must not have source/checksum"):
            q(BASE, wrong)

    def test_rejects_preexisting_rsk_record_mutation(self) -> None:
        before = BASE + RSK
        after = before.replace(
            'dependencies = ["hex", "serde_json", "sha2", "symthaea-replicator-semantics"]',
            'dependencies = ["hex", "serde_json", "symthaea-replicator-semantics"]',
        )
        with self.assertRaises(delta.LockfileDeltaError):
            q(before, after)


if __name__ == "__main__":
    unittest.main()
