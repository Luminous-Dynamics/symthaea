#!/usr/bin/env python3
"""Audit Muse catalog coverage against executable Style definitions.

This dependency-free tool measures declared catalog and routing coverage. It
does not claim that a routed style is musically distinct, well-rendered, or
culturally authentic.

Commands:
  python3 scripts/muse_style_coverage.py --check
  python3 scripts/muse_style_coverage.py --report
  python3 scripts/muse_style_coverage.py --write-baseline
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

SCHEMA = "muse-style-genre-coverage-baseline-v1"
FROZEN_KIND = "frozen_source_inventory_not_a_runtime_report"
CATALOG_RELATIVE = Path("crates/domains/symthaea-muse-protocol/src/catalog.rs")
STYLE_RELATIVE = Path("crates/domains/symthaea-music-theory/src/style.rs")
BASELINE_RELATIVE = Path(
    "crates/domains/symthaea-muse/style-genre-coverage-baseline-v1.json"
)
STATUSES = {
    "Foundation", "Developing", "Research",
    "ResearchExpertReviewRequired", "ExpertReviewRequired",
}
UNROUTED_STATUSES = {"Research", "ResearchExpertReviewRequired"}
SOURCE_NOTE = (
    "Generated by parsing the explicit style! registry entries and declared "
    "Style::ALL length. This file is a frozen baseline; it does not prove the "
    "routed implementations are musically distinct or acoustically available."
)


class CoverageError(ValueError):
    """Source or baseline violated the stated coverage contract."""


def git_blob_sha(content: bytes) -> str:
    """Return the standard SHA-1 Git blob object ID for the provided bytes."""
    header = f"blob {len(content)}\0".encode("ascii")
    return hashlib.sha1(header + content).hexdigest()


def _skip_string(source: str, start: int) -> int:
    """Return the offset immediately after a normal Rust quoted string."""
    index = start + 1
    while index < len(source):
        if source[index] == "\\":
            index += 2
        elif source[index] == '"':
            return index + 1
        else:
            index += 1
    raise CoverageError(f"Unterminated Rust string starting at byte offset {start}")


def _skip_block_comment(source: str, start: int) -> int:
    """Skip a Rust block comment, supporting nested block comments."""
    depth = 1
    index = start + 2
    while index < len(source) and depth:
        if source.startswith("/*", index):
            depth += 1
            index += 2
        elif source.startswith("*/", index):
            depth -= 1
            index += 2
        else:
            index += 1
    if depth:
        raise CoverageError(f"Unterminated Rust block comment at byte offset {start}")
    return index


def _extract_style_macro_bodies(source: str) -> list[str]:
    """Extract style!(...) calls while ignoring comments and string literals."""
    bodies: list[str] = []
    index = 0
    while index < len(source):
        if source.startswith("//", index):
            newline = source.find("\n", index + 2)
            index = len(source) if newline < 0 else newline + 1
            continue
        if source.startswith("/*", index):
            index = _skip_block_comment(source, index)
            continue
        if source[index] == '"':
            index = _skip_string(source, index)
            continue

        boundary = index == 0 or not (
            source[index - 1].isalnum() or source[index - 1] == "_"
        )
        if boundary and source.startswith("style!", index):
            opening = index + len("style!")
            while opening < len(source) and source[opening].isspace():
                opening += 1
            if opening < len(source) and source[opening] == "(":
                depth = 1
                cursor = opening + 1
                while cursor < len(source) and depth:
                    if source.startswith("//", cursor):
                        newline = source.find("\n", cursor + 2)
                        cursor = len(source) if newline < 0 else newline + 1
                        continue
                    if source.startswith("/*", cursor):
                        cursor = _skip_block_comment(source, cursor)
                        continue
                    if source[cursor] == '"':
                        cursor = _skip_string(source, cursor)
                        continue
                    if source[cursor] == "(":
                        depth += 1
                    elif source[cursor] == ")":
                        depth -= 1
                        if depth == 0:
                            bodies.append(source[opening + 1 : cursor])
                            index = cursor + 1
                            break
                    cursor += 1
                else:
                    raise CoverageError(
                        f"Unterminated style! macro at byte offset {index}"
                    )
                continue
        index += 1
    return bodies


def _split_macro_arguments(body: str) -> list[str]:
    """Split macro arguments on commas outside strings and nested delimiters."""
    arguments: list[str] = []
    start = 0
    index = 0
    depth = 0
    while index < len(body):
        if body.startswith("//", index):
            newline = body.find("\n", index + 2)
            index = len(body) if newline < 0 else newline + 1
            continue
        if body.startswith("/*", index):
            index = _skip_block_comment(body, index)
            continue
        if body[index] == '"':
            index = _skip_string(body, index)
            continue
        character = body[index]
        if character in "([{":
            depth += 1
        elif character in ")]}":
            depth -= 1
            if depth < 0:
                raise CoverageError("Unbalanced delimiter in style! macro")
        elif character == "," and depth == 0:
            arguments.append(body[start:index].strip())
            start = index + 1
        index += 1
    if depth != 0:
        raise CoverageError("Unbalanced delimiter in style! macro")
    tail = body[start:].strip()
    if tail:
        arguments.append(tail)
    return arguments


def _rust_string(token: str, context: str) -> str:
    token = token.strip()
    if len(token) < 2 or token[0] != '"' or token[-1] != '"':
        raise CoverageError(f"Expected a quoted Rust string for {context}: {token!r}")
    try:
        value = json.loads(token)
    except json.JSONDecodeError as exc:
        raise CoverageError(f"Unsupported Rust string syntax for {context}: {token}") from exc
    if not isinstance(value, str):
        raise CoverageError(f"Expected string value for {context}")
    return value


def parse_catalog(source: str) -> list[dict[str, Any]]:
    """Parse supported style! macro forms from catalog.rs."""
    entries: list[dict[str, Any]] = []
    for body in _extract_style_macro_bodies(source):
        args = _split_macro_arguments(body)
        if len(args) not in {3, 4, 5, 6}:
            raise CoverageError(
                "Unexpected style! macro shape; expected 3, 4, 5, or 6 arguments: "
                + ", ".join(args)
            )

        try:
            catalog_id = int(args[0], 10)
        except ValueError as exc:
            raise CoverageError(f"Style catalog ID is not an integer: {args[0]!r}") from exc
        if catalog_id <= 0:
            raise CoverageError(f"Style catalog ID must be positive: {catalog_id}")

        name = _rust_string(args[1], "style name")
        if len(args) == 3:
            display_name = name
            constellation = args[2]
            composer_style = None
            status = "Research"
        elif len(args) == 4:
            display_name = name
            constellation = args[2]
            composer_style = None
            status = args[3]
        elif len(args) == 5:
            display_name = name
            constellation = args[2]
            composer_style = _rust_string(args[3], "composer style")
            status = args[4]
        else:
            display_name = _rust_string(args[2], "display name")
            constellation = args[3]
            composer_style = _rust_string(args[4], "composer style")
            status = args[5]

        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", constellation):
            raise CoverageError(
                f"Style {catalog_id} has invalid constellation token: {constellation!r}"
            )
        if status not in STATUSES:
            raise CoverageError(f"Style {catalog_id} has unknown status: {status!r}")
        if not name.strip() or not display_name.strip():
            raise CoverageError(f"Style {catalog_id} has an empty name")

        entries.append(
            {
                "id": catalog_id,
                "name": name,
                "display_name": display_name,
                "constellation": constellation,
                "composer_style": composer_style,
                "status": status,
                "requires_expert_review": status in {
                    "ExpertReviewRequired", "ResearchExpertReviewRequired"
                },
            }
        )

    if not entries:
        raise CoverageError("No style! catalog entries were found")
    ids = [entry["id"] for entry in entries]
    duplicates = sorted({item for item in ids if ids.count(item) > 1})
    if duplicates:
        raise CoverageError(f"Duplicate style catalog IDs: {duplicates}")
    if sorted(ids) != list(range(1, len(ids) + 1)):
        raise CoverageError(
            "Catalog IDs must remain contiguous from 1; found gaps or reordered IDs"
        )
    return sorted(entries, key=lambda entry: entry["id"])


def _extract_braced_body(source: str, declaration: str) -> str:
    marker = re.search(declaration + r"\s*\{", source)
    if marker is None:
        raise CoverageError(f"Could not find Rust declaration matching {declaration!r}")
    start = marker.end()
    # Style is a fieldless enum with a column-zero closing brace. The comment
    # and variant contents may contain prose braces, so find the declaration's
    # own closing line instead of counting prose punctuation.
    end = source.find("\n}", start)
    if end < 0:
        raise CoverageError(f"Could not find closing brace for {declaration!r}")
    return source[start:end]


def parse_style_contract(source: str) -> tuple[list[str], list[str], int]:
    """Return the Style enum variants, Style::ALL names, and declared ALL count."""
    enum_body = _extract_braced_body(source, r"pub\s+enum\s+Style")
    enum_variants = re.findall(
        r"^\s{4}([A-Z][A-Za-z0-9_]*)\s*,\s*(?://.*)?$",
        enum_body,
        flags=re.MULTILINE,
    )
    if not enum_variants:
        raise CoverageError("No fieldless variants were parsed from pub enum Style")

    array_match = re.search(
        r"pub\s+const\s+ALL\s*:\s*\[Style;\s*(\d+)\s*\]\s*=\s*\[(.*?)\n\s*\];",
        source,
        flags=re.DOTALL,
    )
    if array_match is None:
        raise CoverageError("Could not find Style::ALL declaration")
    declared_count = int(array_match.group(1))
    all_names = re.findall(r"\bStyle::([A-Z][A-Za-z0-9_]*)", array_match.group(2))

    if declared_count != len(all_names):
        raise CoverageError(
            f"Style::ALL declares {declared_count} items but contains {len(all_names)}"
        )
    if len(set(all_names)) != len(all_names):
        raise CoverageError("Style::ALL contains duplicate variants")
    if enum_variants != all_names:
        missing = sorted(set(enum_variants) - set(all_names))
        unknown = sorted(set(all_names) - set(enum_variants))
        raise CoverageError(
            "Style::ALL must match enum variants in declaration order; "
            f"missing={missing}, unknown={unknown}"
        )
    return enum_variants, all_names, declared_count


def build_coverage_analysis(
    entries: list[dict[str, Any]], executable_styles: list[str]
) -> dict[str, Any]:
    """Summarize both catalog-to-runtime and runtime-to-catalog coverage."""
    grouped: dict[str, list[dict[str, Any]]] = {}
    for entry in entries:
        grouped.setdefault(entry["constellation"], []).append(entry)

    by_constellation: list[dict[str, Any]] = []
    for constellation in sorted(grouped):
        rows = grouped[constellation]
        routed = [entry for entry in rows if entry["composer_style"] is not None]
        unrouted = [entry for entry in rows if entry["composer_style"] is None]
        by_constellation.append(
            {
                "constellation": constellation,
                "catalog_entries": len(rows),
                "composer_routed_entries": len(routed),
                "unrouted_entries": len(unrouted),
                "routed_catalog_ids": [entry["id"] for entry in routed],
                "unrouted_catalog_ids": [entry["id"] for entry in unrouted],
                "composer_routes": [entry["composer_style"] for entry in routed],
            }
        )

    routed_styles = {
        entry["composer_style"]
        for entry in entries
        if entry["composer_style"] is not None
    }
    unreferenced_executable_styles = sorted(set(executable_styles) - routed_styles)

    return {
        "interpretation": (
            "Routing completeness only; not evidence of musical distinctness, "
            "rendering quality, or cultural authenticity."
        ),
        "unreferenced_executable_styles": unreferenced_executable_styles,
        "by_constellation": by_constellation,
        "zero_route_constellations": [
            item["constellation"]
            for item in by_constellation
            if item["composer_routed_entries"] == 0
        ],
        "partial_route_constellations": [
            item["constellation"]
            for item in by_constellation
            if 0 < item["composer_routed_entries"] < item["catalog_entries"]
        ],
        "fully_routed_constellations": [
            item["constellation"]
            for item in by_constellation
            if item["composer_routed_entries"] == item["catalog_entries"]
        ],
    }


def build_current_report(root: Path) -> dict[str, Any]:
    catalog_path = root / CATALOG_RELATIVE
    style_path = root / STYLE_RELATIVE
    if not catalog_path.is_file() or not style_path.is_file():
        raise CoverageError(
            "Run from a repository checkout containing "
            f"{CATALOG_RELATIVE} and {STYLE_RELATIVE}"
        )
    catalog_bytes = catalog_path.read_bytes()
    style_bytes = style_path.read_bytes()
    try:
        catalog_source = catalog_bytes.decode("utf-8")
        style_source = style_bytes.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise CoverageError(f"Rust source is not UTF-8: {exc}") from exc

    entries = parse_catalog(catalog_source)
    enum_variants, all_names, declared_count = parse_style_contract(style_source)
    variants_set = set(enum_variants)
    routes = [entry["composer_style"] for entry in entries if entry["composer_style"]]
    duplicate_routes = sorted({route for route in routes if routes.count(route) > 1})
    unknown_routes = sorted(set(routes) - variants_set)
    if duplicate_routes:
        raise CoverageError(
            f"Multiple catalog entries map to the same composer route: {duplicate_routes}"
        )
    if unknown_routes:
        raise CoverageError(
            f"Catalog references composer routes missing from Style::ALL: {unknown_routes}"
        )

    blocked_but_routed = [
        entry["id"]
        for entry in entries
        if entry["status"] in UNROUTED_STATUSES and entry["composer_style"] is not None
    ]
    developed_but_unrouted = [
        entry["id"]
        for entry in entries
        if entry["status"] not in UNROUTED_STATUSES and entry["composer_style"] is None
    ]
    if blocked_but_routed:
        raise CoverageError(
            "Research entries unexpectedly route directly to composer styles: "
            f"{blocked_but_routed}"
        )
    if developed_but_unrouted:
        raise CoverageError(
            "Non-research catalog entries have no composer route: "
            f"{developed_but_unrouted}"
        )

    status_counts = dict(Counter(entry["status"] for entry in entries))
    route_names = set(routes)
    return {
        "schema": SCHEMA,
        "kind": "live_source_report",
        "source": {
            "catalog_path": CATALOG_RELATIVE.as_posix(),
            "catalog_blob_sha": git_blob_sha(catalog_bytes),
            "executable_style_path": STYLE_RELATIVE.as_posix(),
            "executable_style_blob_sha": git_blob_sha(style_bytes),
            "executable_style_variant_count": declared_count,
            "note": SOURCE_NOTE,
        },
        "summary": {
            "catalog_entries": len(entries),
            "constellations": len({entry["constellation"] for entry in entries}),
            "composer_routed_entries": len(routes),
            "unique_composer_routes": len(route_names),
            "unrouted_catalog_entries": sum(
                entry["composer_style"] is None for entry in entries
            ),
            "executable_styles_without_catalog_route": len(
                set(all_names) - route_names
            ),
            "status_counts": status_counts,
            "foundation_entries": status_counts.get("Foundation", 0),
            "routed_does_not_mean_distinct": True,
        },
        "coverage_analysis": build_coverage_analysis(entries, all_names),
        "entries": entries,
    }


def frozen_baseline(report: dict[str, Any], generated_on: str) -> dict[str, Any]:
    return {
        "schema": report["schema"],
        "kind": FROZEN_KIND,
        "generated_on": generated_on,
        "source": report["source"],
        "summary": report["summary"],
        "entries": report["entries"],
    }


def _comparison_payload(document: dict[str, Any]) -> dict[str, Any]:
    return {key: document.get(key) for key in ("schema", "source", "summary", "entries")}


def check_baseline(root: Path, baseline_path: Path) -> dict[str, Any]:
    current = build_current_report(root)
    try:
        baseline = json.loads(baseline_path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise CoverageError(f"Baseline file not found: {baseline_path}") from exc
    except json.JSONDecodeError as exc:
        raise CoverageError(f"Baseline JSON is invalid: {exc}") from exc
    if _comparison_payload(current) != _comparison_payload(baseline):
        mismatches = [
            key
            for key in ("schema", "source", "summary", "entries")
            if current.get(key) != baseline.get(key)
        ]
        raise CoverageError(
            "Frozen baseline is stale relative to current source; changed fields: "
            + ", ".join(mismatches)
            + ". Inspect --report, then explicitly refresh with --write-baseline."
        )
    return current


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--check", action="store_true", help="verify the frozen baseline (default)")
    modes.add_argument("--report", action="store_true", help="print the live source-derived JSON report")
    modes.add_argument(
        "--write-baseline",
        action="store_true",
        help="explicitly refresh the checked-in frozen baseline",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="repository root (default: parent of the scripts directory)",
    )
    parser.add_argument(
        "--baseline",
        type=Path,
        default=None,
        help="override baseline path (default: repository baseline)",
    )
    args = parser.parse_args(argv)
    root = args.root.resolve()
    baseline_path = (
        args.baseline.resolve() if args.baseline else root / BASELINE_RELATIVE
    )

    try:
        if args.report:
            report = build_current_report(root)
            print(json.dumps(report, indent=2, ensure_ascii=False))
            return 0
        if args.write_baseline:
            report = build_current_report(root)
            date = datetime.now(timezone.utc).date().isoformat()
            baseline_path.write_text(
                json.dumps(frozen_baseline(report, date), indent=2, ensure_ascii=False)
                + "\n",
                encoding="utf-8",
            )
            print(f"Wrote {baseline_path}")
            print_summary(report)
            return 0

        report = check_baseline(root, baseline_path)
        print("PASS: frozen style-coverage baseline matches source blobs, routes, IDs, and statuses.")
        print_summary(report)
        return 0
    except (CoverageError, OSError) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1


def print_summary(report: dict[str, Any]) -> None:
    summary = report["summary"]
    print(
        "Catalog: {catalog_entries}; constellations: {constellations}; "
        "routed: {composer_routed_entries}; unrouted: {unrouted_catalog_entries}".format(
            **summary
        )
    )
    print(f"Status counts: {json.dumps(summary['status_counts'], sort_keys=True)}")

    analysis = report.get("coverage_analysis")
    if analysis is not None:
        print("Per-constellation routing (routed/catalog; inventory IDs only):")
        for item in analysis["by_constellation"]:
            missing_ids = ", ".join(
                str(catalog_id) for catalog_id in item["unrouted_catalog_ids"]
            ) or "none"
            print(
                f"  {item['constellation']}: "
                f"{item['composer_routed_entries']}/{item['catalog_entries']} routed; "
                f"unrouted catalog IDs: {missing_ids}"
            )
        print(
            "Zero-route constellations: "
            + (", ".join(analysis["zero_route_constellations"]) or "none")
        )
        print(
            "Partial-route constellations: "
            + (", ".join(analysis["partial_route_constellations"]) or "none")
        )
        print(
            "Executable Style variants without catalog route: "
            + (", ".join(analysis["unreferenced_executable_styles"]) or "none")
        )

    print(
        "Interpretation: route/status coverage only; no claim about musical "
        "distinctness, rendering quality, or cultural authenticity."
    )


if __name__ == "__main__":
    raise SystemExit(main())
