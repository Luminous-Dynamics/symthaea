#!/usr/bin/env python3
"""Exact witnesses for non-identifiability under Huber contamination.

This is a population-level teaching/benchmark artifact. It demonstrates that
one observed Bernoulli distribution can be generated by distinct clean means
under different contamination levels. It does not attempt to estimate the
actual contamination rate from the contaminated observations.
"""
from __future__ import annotations

import hashlib
import json
import math
import platform
from pathlib import Path

SCHEMA = "symthaea-huber-identifiability-frontier-v1"


def _probability(name: str, value: float) -> float:
    if not math.isfinite(value) or not 0.0 <= value <= 1.0:
        raise ValueError(f"{name} must be a finite probability in [0, 1]")
    return value


def observed_bernoulli_mean(clean_mean: float, rho: float,
                            contaminant_mean: float) -> float:
    """Mean q of Q=(1-rho)P+rho R when P,R are Bernoulli distributions."""
    p = _probability("clean_mean", clean_mean)
    r = _probability("rho", rho)
    c = _probability("contaminant_mean", contaminant_mean)
    if r >= 1.0:
        raise ValueError("rho must be less than 1")
    return (1.0 - r) * p + r * c


def clean_mean_envelope(observed_mean: float,
                        rho_upper: float) -> tuple[float, float]:
    """Identified set for clean Bernoulli mean with q and rho <= rho_upper.

    For q=(1-rho)p+rho*r with r in [0,1], the sharp envelope is
    [max(0,(q-rho_upper)/(1-rho_upper)), min(1,q/(1-rho_upper))].
    """
    q = _probability("observed_mean", observed_mean)
    rho = _probability("rho_upper", rho_upper)
    if rho >= 1.0:
        raise ValueError("rho_upper must be less than 1")
    denom = 1.0 - rho
    return max(0.0, (q - rho) / denom), min(1.0, q / denom)


def error_envelope(model_mean: float, clean_interval: tuple[float, float]
                   ) -> tuple[float, float]:
    """Minimum and maximum absolute model error over a clean-mean interval."""
    m = _probability("model_mean", model_mean)
    lo, hi = clean_interval
    if not (math.isfinite(lo) and math.isfinite(hi) and 0.0 <= lo <= hi <= 1.0):
        raise ValueError("clean_interval must be an ordered interval within [0, 1]")
    minimum = 0.0 if lo <= m <= hi else min(abs(m - lo), abs(m - hi))
    maximum = max(abs(m - lo), abs(m - hi))
    return minimum, maximum


def classify_certificate(model_mean: float, clean_interval: tuple[float, float],
                         tolerance: float) -> str:
    """Admit/reject only if every/none of the identified clean means is safe."""
    if not math.isfinite(tolerance) or tolerance < 0.0:
        raise ValueError("tolerance must be finite and nonnegative")
    error_min, error_max = error_envelope(model_mean, clean_interval)
    if error_max <= tolerance:
        return "admit"
    if error_min > tolerance:
        return "reject"
    return "refuse_unresolved"


def evaluate_claim(*, observed_mean: float, model_mean: float,
                   tolerance: float, rho_upper: float | None,
                   provenance_valid: bool, scope_valid: bool = True,
                   attestation_confidence: float | None = None,
                   alpha_statistical: float = 0.05) -> dict:
    """Evaluate preflight, separating authenticity/scope from bound validity.

    `provenance_valid` and `scope_valid` are explicit inputs, not inferred from
    the observations. If absent, refuse before inference. `attestation_confidence`
    represents a claimed probability that the external process really bounds
    contamination; its validity cannot be established by this function.
    """
    q = _probability("observed_mean", observed_mean)
    m = _probability("model_mean", model_mean)
    if not math.isfinite(tolerance) or tolerance < 0.0:
        raise ValueError("tolerance must be finite and nonnegative")
    if not (0.0 < alpha_statistical < 1.0):
        raise ValueError("alpha_statistical must be in (0, 1)")
    if rho_upper is None or not provenance_valid or not scope_valid:
        reason = "missing_bound" if rho_upper is None else (
            "invalid_provenance" if not provenance_valid else "scope_mismatch")
        return {
            "status": "refuse_unresolved", "reason": reason,
            "observations_used_for_certificate": 0,
            "identified_clean_mean_interval": None,
            "statistical_alpha": alpha_statistical,
            "assumption_failure_probability": None,
            "composed_failure_budget": None,
            "warning": "Preflight failure is not repaired by observing more contaminated samples.",
        }
    rho = _probability("rho_upper", rho_upper)
    if rho >= 1.0:
        raise ValueError("rho_upper must be less than 1")
    if attestation_confidence is not None and not (0.0 < attestation_confidence <= 1.0):
        raise ValueError("attestation_confidence must be in (0, 1]")
    interval = clean_mean_envelope(q, rho)
    status = classify_certificate(m, interval, tolerance)
    delta_bound = None if attestation_confidence is None else 1.0 - attestation_confidence
    # A union bound is available only if both component guarantees are justified.
    composed = None if delta_bound is None else min(1.0, alpha_statistical + delta_bound)
    return {
        "status": status,
        "reason": "population_envelope_classification",
        "observations_used_for_certificate": 0,
        "identified_clean_mean_interval": list(interval),
        "min_possible_model_error": error_envelope(m, interval)[0],
        "max_possible_model_error": error_envelope(m, interval)[1],
        "statistical_alpha": alpha_statistical,
        "assumption_failure_probability": delta_bound,
        "composed_failure_budget": composed,
        "attestation_confidence_is_not_verified_here": attestation_confidence is not None,
        "warning": "Signature/provenance does not prove the claimed contamination bound is true.",
    }


def build_witness() -> dict:
    model, tolerance, q = 0.37, 0.05, 0.37
    unsafe_clean = 0.43
    unsafe_rho = 1.0 - q / unsafe_clean
    safe_q = observed_bernoulli_mean(0.37, 0.0, 0.0)
    unsafe_q = observed_bernoulli_mean(unsafe_clean, unsafe_rho, 0.0)
    understated = clean_mean_envelope(q, 0.05)
    honest = clean_mean_envelope(q, 0.15)
    return {
        "schema": SCHEMA,
        "status": "EXACT_POPULATION_IDENTIFIABILITY_WITNESS_NOT_DEPLOYMENT_EVIDENCE",
        "claim": "The same observed Bernoulli law is compatible with a safe and an unsafe clean mean.",
        "parameters": {
            "model_mean": model, "allowed_absolute_error": tolerance,
            "observed_mean": q, "unsafe_clean_mean": unsafe_clean,
            "unsafe_actual_contamination": unsafe_rho,
            "contaminant_mean": 0.0,
        },
        "world_safe": {
            "clean_mean": 0.37, "actual_contamination": 0.0,
            "observed_mean": safe_q, "true_model_error": abs(model - 0.37),
            "safe": abs(model - 0.37) <= tolerance,
        },
        "world_unsafe": {
            "clean_mean": unsafe_clean, "actual_contamination": unsafe_rho,
            "observed_mean": unsafe_q, "true_model_error": abs(model - unsafe_clean),
            "safe": abs(model - unsafe_clean) <= tolerance,
        },
        "same_observed_distribution": math.isclose(safe_q, unsafe_q, rel_tol=0.0, abs_tol=1e-15),
        "understated_bound_5pct": {
            "declared_upper_bound": 0.05,
            "identified_interval": list(understated),
            "certificate_status": classify_certificate(model, understated, tolerance),
            "true_unsafe_mean_excluded": not (understated[0] <= unsafe_clean <= understated[1]),
        },
        "valid_bound_15pct": {
            "declared_upper_bound": 0.15,
            "identified_interval": list(honest),
            "certificate_status": classify_certificate(model, honest, tolerance),
            "true_unsafe_mean_included": honest[0] <= unsafe_clean <= honest[1],
        },
        "provenance_negative_control": evaluate_claim(
            observed_mean=q, model_mean=model, tolerance=tolerance, rho_upper=0.05,
            provenance_valid=False, scope_valid=True,
        ),
        "authenticated_but_understated_bound": evaluate_claim(
            observed_mean=q, model_mean=model, tolerance=tolerance, rho_upper=0.05,
            provenance_valid=True, scope_valid=True, attestation_confidence=0.99,
            alpha_statistical=0.05,
        ),
        "composition_example": evaluate_claim(
            observed_mean=q, model_mean=model, tolerance=tolerance, rho_upper=0.15,
            provenance_valid=True, scope_valid=True, attestation_confidence=0.99,
            alpha_statistical=0.05,
        ),
        "limitations": [
            "This is an exact population-mean Bernoulli witness, not a finite-sample coverage experiment.",
            "The observed law cannot distinguish the two worlds; arbitrary contamination is not detected from these samples alone.",
            "Provenance/authenticity and truth/calibration of the contamination bound are separate questions.",
            "The illustrative attestation confidence is an input, not validated evidence.",
            "An adaptive or sequential implementation still needs its own theorem and matched tests.",
        ],
    }


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = build_witness()
    raw = (json.dumps(result, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n").encode()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(raw)
    print(json.dumps({
        "output": str(args.output), "bytes": len(raw),
        "sha256": hashlib.sha256(raw).hexdigest(),
        "same_observed_distribution": result["same_observed_distribution"],
        "understated_bound_status": result["understated_bound_5pct"]["certificate_status"],
        "valid_bound_status": result["valid_bound_15pct"]["certificate_status"],
        "python": platform.python_version(),
    }, indent=2))
