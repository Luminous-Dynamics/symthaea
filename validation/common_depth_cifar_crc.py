#!/usr/bin/env python3
"""Exact common-depth CIFAR-100 CRC controller and equal-share recertification.

Implements Appendix B.7 common-depth family from Bai & Ramdas (2026),
arXiv:2610.35821. Error types:
  0: correct fine label
  1: fine label wrong, but true label in predicted superclass
  2: true label outside predicted superclass
Depth a in [0,2] has loss:
  ell_0(a)=0
  ell_1(a)=0.5*max(a-1,0)
  ell_2(a)=0.5*a

The controller is a table on 3-type calibration count vectors. The code
enumerates multisets, not permutations, and verifies all augmented states.
No CIFAR model outputs or split results are generated by this module.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
import platform
import time
from pathlib import Path
import numpy as np

SCHEMA = "symthaea-common-depth-cifar-crc-v1"
TYPE_NAMES = ("fine_correct", "superclass_correct", "superclass_wrong")


def count_vectors(total: int, types: int = 3) -> list[tuple[int, ...]]:
    if total < 0 or types < 1:
        raise ValueError("invalid count-vector dimensions")
    if types == 1:
        return [(total,)]
    out = []
    for first in range(total + 1):
        for tail in count_vectors(total - first, types - 1):
            out.append((first,) + tail)
    return out


def add_type(h: tuple[int, ...], z: int) -> tuple[int, ...]:
    x = list(h)
    x[z] += 1
    return tuple(x)


def remove_type(q: tuple[int, ...], z: int) -> tuple[int, ...]:
    x = list(q)
    if x[z] <= 0:
        raise ValueError("cannot remove absent type")
    x[z] -= 1
    return tuple(x)


def loss(z: int, depth: float) -> float:
    if not 0 <= z <= 2:
        raise IndexError("error type must be 0, 1 or 2")
    if not math.isfinite(depth) or not 0.0 <= depth <= 2.0:
        raise ValueError("depth must lie in [0,2]")
    if z == 0:
        return 0.0
    if z == 1:
        return 0.5 * max(depth - 1.0, 0.0)
    return 0.5 * depth


def largest_piecewise_linear_feasible(
    h1: int, h2: int, budget: float, envelope: bool
) -> float:
    """Largest a in [0,2] satisfying common-depth CRC/envelope constraint.

    CRC:       h1*(a-1)_+ + h2*a/2 + 1 <= budget
    Envelope:  h1*(a-1)_+ + h2*a/2 + a/2 <= budget
    Closed-form inversion over the two linear pieces [0,1], [1,2].
    """
    if h1 < 0 or h2 < 0 or not math.isfinite(budget):
        raise ValueError("invalid counts or budget")
    intercept0 = 1.0 if not envelope else 0.0
    slope0 = 0.5 * h2 + (0.5 if envelope else 0.0)
    if intercept0 > budget + 1e-12:
        return 0.0
    if slope0 > 0:
        a0 = min(1.0, max(0.0, (budget - intercept0) / slope0))
    else:
        a0 = 1.0
    if a0 < 1.0 - 1e-12:
        return a0
    value_at_one = intercept0 + slope0
    slope1 = slope0 + 0.5 * h1
    intercept1 = value_at_one - slope1
    if slope1 <= 0:
        return 2.0
    a1 = (budget - intercept1) / slope1
    if a1 >= 2.0:
        return 2.0
    return min(2.0, max(1.0, a1))


class CommonDepthCIFARCRC:
    def __init__(self, n_calibration: int, alpha: float):
        if n_calibration < 1:
            raise ValueError("n_calibration must be positive")
        if not math.isfinite(alpha) or not 0 < alpha < 1:
            raise ValueError("alpha must be in (0,1)")
        self.n = int(n_calibration)
        self.alpha = float(alpha)
        self.budget = (self.n + 1) * self.alpha
        self.states = count_vectors(self.n, 3)
        self.augmented = count_vectors(self.n + 1, 3)

    def baseline(self, kind: str = "envelope") -> dict[tuple[int, ...], float]:
        if kind not in {"crc", "envelope"}:
            raise ValueError("kind must be 'crc' or 'envelope'")
        envelope = kind == "envelope"
        result = {}
        for h in self.states:
            result[h] = largest_piecewise_linear_feasible(
                h[1], h[2], self.budget, envelope
            )
        report = self.validity_report(result)
        if not report["valid"]:
            raise ArithmeticError(f"{kind} baseline is not valid: {report}")
        return result

    def heldout_total(self, controller: dict[tuple[int, ...], float],
                      q: tuple[int, ...]) -> float:
        if sum(q) != self.n + 1:
            raise ValueError("augmented count vector must have n+1 observations")
        total = 0.0
        for z, multiplicity in enumerate(q):
            if multiplicity:
                h = remove_type(q, z)
                total += multiplicity * loss(z, controller[h])
        return total

    def validity_report(self, controller: dict[tuple[int, ...], float],
                        tolerance: float = 1e-10) -> dict:
        if set(controller) != set(self.states):
            raise ValueError("controller must define every calibration multiset")
        if any(not math.isfinite(a) or not 0 <= a <= 2 for a in controller.values()):
            raise ValueError("controller depth must be finite and in [0,2]")
        totals = {q: self.heldout_total(controller, q) for q in self.augmented}
        worst_q, worst_total = max(totals.items(), key=lambda item: item[1])
        excess = worst_total - self.budget
        return {
            "valid": bool(excess <= tolerance),
            "max_budget_excess": float(excess),
            "worst_augmented_count": worst_q,
            "worst_augmented_total": float(worst_total),
            "budget": float(self.budget),
            "number_augmented_states": len(totals),
            "all_totals": {",".join(map(str, q)): v for q, v in totals.items()},
        }

    def equal_share_round(self, controller: dict[tuple[int, ...], float]) -> dict:
        """Apply Appendix B.7 common-depth update (B.6) to every table entry."""
        if not self.validity_report(controller)["valid"]:
            raise ValueError("starting controller must be valid")
        updated = {}
        for h in self.states:
            a = controller[h]
            q1 = add_type(h, 1)
            q2 = add_type(h, 2)
            slack1 = self.alpha - self.heldout_total(controller, q1) / (self.n + 1)
            slack2 = self.alpha - self.heldout_total(controller, q2) / (self.n + 1)
            if slack1 < -1e-9 or slack2 < -1e-9:
                raise ArithmeticError("negative unused budget in hypothetical label state")
            # Invert ell_2(a') <= ell_2(a)+slack2.
            upper2 = a + 2.0 * max(0.0, slack2)
            # Invert ell_1(a') <= ell_1(a)+slack1.
            upper1 = 1.0 + max(a - 1.0, 0.0) + 2.0 * max(0.0, slack1)
            updated[h] = min(2.0, upper1, upper2)
        report = self.validity_report(updated)
        if not report["valid"]:
            raise ArithmeticError(f"equal-share update broke validity: {report}")
        if any(updated[h] + 1e-12 < controller[h] for h in self.states):
            raise ArithmeticError("equal-share update became more conservative")
        return updated

    def recertify(self, controller: dict[tuple[int, ...], float],
                  rounds: int = 500, tolerance: float = 1e-10) -> tuple[dict, list[dict]]:
        if rounds < 0 or tolerance <= 0:
            raise ValueError("invalid rounds or tolerance")
        current = dict(controller)
        history = [dict(current)]
        for _ in range(rounds):
            new = self.equal_share_round(current)
            history.append(new)
            difference = max(abs(new[h] - current[h]) for h in self.states)
            current = new
            if difference <= tolerance:
                break
        return current, history

    def expected_metrics(self, depth: float, error_type: int) -> dict[str, float]:
        """Metrics averaged over the method's randomized prediction node."""
        a = min(2.0, max(0.0, depth))
        pi_root = max(1.0 - a, 0.0)
        pi_super = 1.0 - abs(a - 1.0)
        pi_leaf = max(a - 1.0, 0.0)
        risk = loss(error_type, a)
        node_size = 100.0 * pi_root + 5.0 * pi_super + pi_leaf
        specificity = (
            (math.log(20.0) / math.log(100.0)) * pi_super * (1.0 if error_type != 2 else 0.0)
            + pi_leaf * (1.0 if error_type == 0 else 0.0)
        )
        return {"risk": risk, "expected_node_size": node_size,
                "correct_specificity": specificity}

    def aggregate_test_metrics(self, controller: dict[tuple[int, ...], float],
                               calibration_counts: tuple[int, int, int],
                               test_counts: tuple[int, int, int]) -> dict[str, float]:
        if calibration_counts not in controller or sum(calibration_counts) != self.n:
            raise ValueError("invalid calibration count vector")
        if sum(test_counts) <= 0 or any(c < 0 for c in test_counts):
            raise ValueError("test counts must be nonnegative and sum positive")
        depth = controller[calibration_counts]
        total = float(sum(test_counts))
        accum = {"risk": 0.0, "expected_node_size": 0.0, "correct_specificity": 0.0}
        for z, count in enumerate(test_counts):
            if count == 0:
                continue
            metric = self.expected_metrics(depth, z)
            for key in accum:
                accum[key] += count * metric[key] / total
        return accum


def controller_summary(engine: CommonDepthCIFARCRC,
                       controller: dict[tuple[int, ...], float]) -> dict:
    return {
        "number_states": len(controller),
        "min_depth": min(controller.values()),
        "max_depth": max(controller.values()),
        "mean_depth_unweighted_over_count_states": float(np.mean(list(controller.values()))),
        "validity": engine.validity_report(controller),
    }


def run_table(n: int, alpha: float, rounds: tuple[int, ...] = (0, 1, 3, 10, 20, 50, 100, 200, 500)) -> dict:
    engine = CommonDepthCIFARCRC(n, alpha)
    baseline = engine.baseline("envelope")
    current = dict(baseline)
    wanted = set(rounds)
    snapshots = {}
    if 0 in wanted:
        snapshots[0] = dict(current)
    previous = dict(current)
    last_step_change = 0.0
    for k in range(1, max(rounds) + 1):
        current = engine.equal_share_round(current)
        last_step_change = max(abs(current[h] - previous[h]) for h in engine.states)
        previous = dict(current)
        if k in wanted:
            snapshots[k] = dict(current)
    summaries = {}
    for k, table in snapshots.items():
        summaries[str(k)] = {
            "min_depth": min(table.values()),
            "max_depth": max(table.values()),
            "mean_depth_over_count_vectors": float(np.mean(list(table.values()))),
            "valid": engine.validity_report(table)["valid"],
            "max_budget_excess": engine.validity_report(table)["max_budget_excess"],
        }
    return {
        "n": n, "alpha": alpha,
        "calibration_states": len(engine.states),
        "augmented_states": len(engine.augmented),
        "rounds": summaries,
        "last_step_max_abs_change": float(last_step_change),
        "validity_all_rounds": True,
    }


def _sample_finite_population_splits(
    pool_counts: tuple[int, int, int], n_calibration: int, n_test: int,
    n_splits: int, seed: int
) -> list[tuple[tuple[int, int, int], tuple[int, int, int]]]:
    """Sample calibration/test subsets without replacement within each split.

    The common-depth controller depends on the frozen image pool only through
    the three error-type counts. Thus the actual image IDs/prediction vectors
    are not needed for this family once pool_counts are known. These are new
    paired split draws, not the paper's original split manifest.
    """
    if len(pool_counts) != 3 or any(x < 0 for x in pool_counts) or sum(pool_counts) <= n_calibration+n_test:
        raise ValueError("invalid finite population counts or split sizes")
    if n_splits < 1:
        raise ValueError("n_splits must be positive")
    population = np.repeat(np.arange(3, dtype=np.int64), pool_counts)
    rng = np.random.default_rng(seed)
    splits = []
    for _ in range(n_splits):
        chosen = rng.choice(population.size, size=n_calibration+n_test, replace=False)
        labels = population[chosen]
        cal = tuple(int(x) for x in np.bincount(labels[:n_calibration], minlength=3))
        test = tuple(int(x) for x in np.bincount(labels[n_calibration:], minlength=3))
        splits.append((cal,test))
    return splits


def _metric_summary(values: list[float]) -> dict:
    x=np.asarray(values,dtype=np.float64)
    mean=float(x.mean())
    se=float(x.std(ddof=1)/math.sqrt(x.size)) if x.size>1 else 0.0
    return {"mean":mean,"se":se,"ci95":[mean-1.96*se,mean+1.96*se]}


def run_pool_count_benchmark(
    alphas: tuple[float,...]=(0.02,0.05,0.10,0.15),
    pool_counts: tuple[int,int,int]=(7300,969,1731),
    n_calibration: int=50, n_test: int=16, n_splits: int=300,
    seed: int=20261031, rounds: tuple[int,...]=(0,1,3,10,20,50,100,200,500)
) -> dict:
    """Reproduce the common-depth *type-count* split experiment.

    This reproduces the common-depth method and exact finite-population
    sampling distribution at the type-count level using the published pool
    counts. It cannot reproduce the original split IDs or confidence-adaptive
    family, whose per-image confidence breakpoints are required.
    """
    splits=_sample_finite_population_splits(pool_counts,n_calibration,n_test,n_splits,seed)
    all_results=[]
    for alpha in alphas:
        engine=CommonDepthCIFARCRC(n_calibration,alpha)
        started=time.perf_counter()
        crc_baseline=engine.baseline("crc")
        baseline=engine.baseline("envelope")
        controller=dict(baseline)
        snapshots={0:dict(controller)}
        for k in range(1,max(rounds)+1):
            controller=engine.equal_share_round(controller)
            if k in rounds:
                snapshots[k]=dict(controller)
        build_seconds=time.perf_counter()-started
        method_rows={}
        comparison_tables={"CRC":crc_baseline,**{f"envelope_round_{k}":v for k,v in snapshots.items()}}
        for label,table in comparison_tables.items():
            split_metrics=[]
            for cal,test in splits:
                split_metrics.append(engine.aggregate_test_metrics(table,cal,test))
            method_rows[label]={
                key:_metric_summary([row[key] for row in split_metrics])
                for key in ("risk","expected_node_size","correct_specificity")
            }
        baseline_cs=np.asarray([engine.aggregate_test_metrics(baseline,cal,test)["correct_specificity"] for cal,test in splits])
        deltas={}
        for k,table in snapshots.items():
            cs=np.asarray([engine.aggregate_test_metrics(table,cal,test)["correct_specificity"] for cal,test in splits])
            deltas[str(k)]=_metric_summary((cs-baseline_cs).tolist())
        crc_cs=np.asarray([engine.aggregate_test_metrics(crc_baseline,cal,test)["correct_specificity"] for cal,test in splits])
        recert500_cs=split_rows[max(rounds)][:,2]
        delta_crc=(recert500_cs-crc_cs)*100
        se_crc=delta_crc.std(ddof=1)/math.sqrt(len(delta_crc))
        all_results.append({
            "alpha":alpha,"calibration_states":len(engine.states),
            "augmented_states":len(engine.augmented),
            "build_0_to_500_seconds":build_seconds,
            "methods":method_rows,"paired_specificity_gain_vs_envelope":deltas,
            "recert500_gain_vs_crc":{
                "mean_gain_pp":float(delta_crc.mean()),"se_pp":float(se_crc),
                "ci95_pp":[float(delta_crc.mean()-1.96*se_crc),float(delta_crc.mean()+1.96*se_crc)]
            },
            "all_rounds_valid":True
        })
    return {
        "protocol":{
            "pool_counts_by_error_type":list(pool_counts),
            "n_calibration":n_calibration,"n_test":n_test,"n_splits":n_splits,
            "seed":seed,"within_split_sampling":"uniform without replacement from the 10,000-type finite population",
            "same_splits_for_all_alphas_and_methods":True,
            "data_provenance":"type-count reproduction using Appendix B.7 published pool totals; new seed and new split draws, not original image IDs",
        },
        "results":all_results,
        "limitations":[
            "common-depth family only; no confidence-adaptive per-image confidence breakpoints",
            "not the paper's exact original split manifest, though the finite-population type-level draw law is the same",
            "no cached per-image scores needed for common-depth because the method depends only on type counts",
            "not a reproduction of paper Table 2 because exact original 300 splits are unavailable",
            "finite exchangeability guarantee only; shift experiments are outside the guarantee"
        ]
    }

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True)
    parser.add_argument("--mode", choices=("table", "pool"), default="pool")
    parser.add_argument("--n", type=int, default=50)
    parser.add_argument("--alpha", type=float, nargs="+", default=[.02, .05, .10, .15])
    parser.add_argument("--splits", type=int, default=300)
    parser.add_argument("--seed", type=int, default=20261031)
    args = parser.parse_args()
    started = time.perf_counter()
    if args.mode == "table":
        result = {
            "schema": SCHEMA,
            "status": "COMMON_DEPTH_TABLE_REPRODUCTION_ONLY_NOT_CIFAR_RESULT_REPRODUCTION",
            "reference": "Bai & Ramdas (2026), arXiv:2610.35821, Appendix B.7",
            "tables": [run_table(args.n, alpha) for alpha in args.alpha],
        }
    else:
        result = {
            "schema": SCHEMA,
            "status": "NEW_SEEDED_TYPE_COUNT_REPRODUCTION_NOT_ORIGINAL_SPLIT_MANIFEST",
            "reference": "Bai & Ramdas (2026), arXiv:2610.35821, Appendix B.7",
            "benchmark": run_pool_count_benchmark(
                alphas=tuple(args.alpha), n_calibration=args.n,
                n_splits=args.splits, seed=args.seed
            ),
        }
    result["runtime_seconds"] = time.perf_counter() - started
    result["environment"] = {"python": platform.python_version(), "numpy": np.__version__}
    raw = (json.dumps(result, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n").encode()
    Path(args.output).write_bytes(raw)
    print(json.dumps({
        "output": args.output, "bytes": len(raw),
        "sha256": hashlib.sha256(raw).hexdigest(),
        "runtime_seconds": result["runtime_seconds"],
        "mode": args.mode,
    }, indent=2))


if __name__ == "__main__":
    main()
