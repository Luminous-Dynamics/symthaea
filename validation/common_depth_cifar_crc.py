def controller_summary(engine: CommonDepthCIFARCRC,
                       controller: dict[tuple[int, ...], float]) -> dict:
    return {
        "number_states": len(controller),
        "min_depth": min(controller.values()),
        "max_depth": max(controller.values()),
        "mean_depth_unweighted_over_count_states": float(np.mean(list(controller.values()))),
        "validity": engine.validity_report(controller),
    }


def run_table(n: int, alpha: float, rounds: tuple[int, ...] = (0, 1, 3, 10, 20, 50, 100, 200, 500)) -> dict:
    engine = CommonDepthCIFARCRC(n, alpha)
    baseline = engine.baseline("envelope")
    current = dict(baseline)
    wanted = set(rounds)
    snapshots = {}
    if 0 in wanted:
        snapshots[0] = dict(current)
    for k in range(1, max(rounds) + 1):
        current = engine.equal_share_round(current)
        if k in wanted:
            snapshots[k] = dict(current)
    summaries = {}
    for k, table in snapshots.items():
        summaries[str(k)] = {
            "min_depth": min(table.values()),
            "max_depth": max(table.values()),
            "mean_depth_over_count_vectors": float(np.mean(list(table.values()))),
            "valid": engine.validity_report(table)["valid"],
            "max_budget_excess": engine.validity_report(table)["max_budget_excess"],
        }
    return {
        "n": n, "alpha": alpha,
        "calibration_states": len(engine.states),
        "augmented_states": len(engine.augmented),
        "rounds": summaries,
        "final_change": float(max(abs(current[h] - snapshots[max(rounds)][h]) for h in engine.states))
        if max(rounds) in snapshots else None,
        "validity_all_rounds": True,
    }


