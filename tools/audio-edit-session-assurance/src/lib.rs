    #[test]
    fn explicit_same_role_supersession_removes_old_constraint_from_final_active_set() {
        let mut events = Vec::new();
        start(&mut events);
        open_turn(&mut events, 1, '2');
        add_constraint(&mut events, 1, "lyric-old", ConstraintRoleV1::Instruction, '3', 'c');
        add_constraint(&mut events, 1, "melody", ConstraintRoleV1::Preservation, '4', 'd');
        edit(&mut events, 1, 1, 'c', 'e', '5');
        observe(&mut events, 1, "lyric-old", 'e', ObservationDecisionV1::Pass, '6', 'c');
        observe(&mut events, 1, "melody", 'e', ObservationDecisionV1::Pass, '7', 'd');
        open_turn(&mut events, 2, '8');
        add_constraint(&mut events, 2, "lyric-new", ConstraintRoleV1::Instruction, '9', 'f');
        push_event(&mut events, 'a', SessionEventKindV1::ConstraintSuperseded {
            turn_index: 2,
            old_constraint_id: "lyric-old".to_owned(),
            replacement_constraint_id: "lyric-new".to_owned(),
            reason_sha256: digest('1'),
        });
        edit(&mut events, 2, 2, 'e', '2', 'b');
        observe(&mut events, 2, "lyric-new", '2', ObservationDecisionV1::Pass, 'c', 'f');
        observe(&mut events, 2, "melody", '2', ObservationDecisionV1::Pass, 'd', 'd');
        finalize(&mut events, '2', 'e');

        let report = evaluate_session_ledger(&spec(), &events).unwrap();
        assert_eq!(report.outcome, SessionOutcomeV1::Qualified);
        assert_eq!(report.superseded_constraint_count, 1);
        assert_eq!(report.active_constraints.len(), 2);
        assert!(!report.active_constraints.iter().any(|c| c.constraint.constraint_id == "lyric-old"));
    }

