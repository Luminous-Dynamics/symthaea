    fn push_event(
        events: &mut Vec<SessionEventV1>,
        event_character: char,
        kind: SessionEventKindV1,
    ) {
        let previous_event_sha256 = events.last().map(|event| event.event_sha256.clone());
        events.push(SessionEventV1 {
            event_index: events.len() as u64,
            previous_event_sha256,
            event_sha256: digest(event_character),
            kind,
        });
    }

    fn start(events: &mut Vec<SessionEventV1>) {
        let spec = spec();
        push_event(
            events,
            '1',
            SessionEventKindV1::SessionStarted {
                session_id: spec.session_id,
                initial_input_manifest_sha256: spec.initial_input_manifest_sha256,
                frozen_context_sha256: spec.frozen_context_sha256,
                initial_output_sha256: spec.initial_output_sha256,
            },
        );
    }

    fn open_turn(events: &mut Vec<SessionEventV1>, turn: u64, event: char) {
        push_event(
            events,
            event,
            SessionEventKindV1::UserTurnOpened {
                turn_index: turn,
                instruction_batch_sha256: digest('d'),
            },
        );
    }

    fn add_constraint(
        events: &mut Vec<SessionEventV1>,
        turn: u64,
        id: &str,
        role: ConstraintRoleV1,
        event: char,
        profile: char,
    ) {
        push_event(
            events,
            event,
            SessionEventKindV1::ConstraintAdded {
                turn_index: turn,
                constraint_id: id.to_owned(),
                role,
                instruction_sha256: digest('e'),
                scope_sha256: digest('f'),
                rubric_profile_sha256: digest(profile),
            },
        );
    }

    fn edit(
        events: &mut Vec<SessionEventV1>,
        turn: u64,
        step: u64,
        parent: char,
        output: char,
        event: char,
    ) {
        push_event(
            events,
            event,
            SessionEventKindV1::EditExecuted {
                turn_index: turn,
                step_index: step,
                parent_output_sha256: digest(parent),
                output_audio_sha256: digest(output),
                action_sha256: digest('7'),
                system_artifact_sha256: digest('8'),
            },
        );
    }

    fn observe(
        events: &mut Vec<SessionEventV1>,
        turn: u64,
        constraint: &str,
        output: char,
        decision: ObservationDecisionV1,
        event: char,
        profile: char,
    ) {
        push_event(
            events,
            event,
            SessionEventKindV1::ObservationAttached {
                turn_index: turn,
                constraint_id: constraint.to_owned(),
                output_audio_sha256: digest(output),
                decision,
                rubric_profile_sha256: digest(profile),
                evaluator_artifact_sha256: digest('9'),
                evidence_receipt_sha256: digest('a'),
            },
        );
    }

    fn finalize(events: &mut Vec<SessionEventV1>, output: char, event: char) {
        let mut active_ids = BTreeSet::new();
        for existing in events.iter() {
            match &existing.kind {
                SessionEventKindV1::ConstraintAdded { constraint_id, .. } => {
                    active_ids.insert(constraint_id.clone());
                }
                SessionEventKindV1::ConstraintSuperseded {
                    old_constraint_id, ..
                } => {
                    active_ids.remove(old_constraint_id);
                }
                _ => {}
            }
        }
        push_event(
            events,
            event,
            SessionEventKindV1::SessionFinalized {
                final_output_sha256: digest(output),
                active_ledger_sha256: digest('b'),
                active_constraint_ids: active_ids.into_iter().collect(),
            },
        );
    }

    fn valid_two_turn_session() -> Vec<SessionEventV1> {
        let mut events = Vec::new();
        start(&mut events);
        open_turn(&mut events, 1, '2');
        add_constraint(&mut events, 1, "lyric-a", ConstraintRoleV1::Instruction, '3', 'c');
        add_constraint(&mut events, 1, "preserve-melody", ConstraintRoleV1::Preservation, '4', 'd');
        edit(&mut events, 1, 1, 'c', 'e', '5');
        observe(&mut events, 1, "lyric-a", 'e', ObservationDecisionV1::Pass, '6', 'c');
        observe(&mut events, 1, "preserve-melody", 'e', ObservationDecisionV1::Pass, '7', 'd');
        open_turn(&mut events, 2, '8');
        add_constraint(&mut events, 2, "lyric-b", ConstraintRoleV1::Instruction, '9', 'e');
        edit(&mut events, 2, 2, 'e', 'f', 'a');
        observe(&mut events, 2, "lyric-a", 'f', ObservationDecisionV1::Pass, 'b', 'c');
        observe(&mut events, 2, "preserve-melody", 'f', ObservationDecisionV1::Pass, 'c', 'd');
        observe(&mut events, 2, "lyric-b", 'f', ObservationDecisionV1::Pass, 'd', 'e');
        finalize(&mut events, 'f', 'e');
        events
    }

    #[test]
    fn valid_multiturn_multihop_session_qualifies() {
        let report = evaluate_session_ledger(&spec(), &valid_two_turn_session()).unwrap();
        assert_eq!(report.outcome, SessionOutcomeV1::Qualified);
        assert_eq!(report.turn_count, 2);
        assert_eq!(report.edit_count, 2);
        assert_eq!(report.active_constraints.len(), 3);
        assert_eq!(report.final_output_sha256, Some(digest('f')));
        assert_eq!(report.active_constraints.iter().filter(|c| {
            c.final_decision == Some(ObservationDecisionV1::Pass)
        }).count(), 3);
    }

