//! Event-sourced assurance for multi-turn audio-editing sessions.
//!
//! This crate validates a supplied append-only event stream and its
//! independently generated observation receipts. It does not infer user
//! intent, route tools, edit audio, or run perceptual evaluators.
//!
//! A later turn cannot erase an earlier constraint implicitly. Constraints
//! remain active until an explicit same-role supersession event is recorded.
//! Finalization requires current-output evidence for every active constraint.

use std::collections::{BTreeMap, BTreeSet};
use std::error::Error;
use std::fmt::{Display, Formatter};

pub const SESSION_LEDGER_SCHEMA_V1: &str = "audio-edit-session-ledger/v1";

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LedgerError {
    pub message: String,
}

impl LedgerError {
    fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
        }
    }
}

impl Display for LedgerError {
    fn fmt(&self, formatter: &mut Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(&self.message)
    }
}

impl Error for LedgerError {}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SessionSpecV1 {
    pub session_id: String,
    /// The manifest can commit to multiple source audio inputs and their roles.
    pub initial_input_manifest_sha256: String,
    pub frozen_context_sha256: String,
    pub initial_output_sha256: String,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ConstraintRoleV1 {
    Instruction,
    Preservation,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum AttemptStatusV1 {
    Failed,
    Unsupported,
    Abstained,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ObservationDecisionV1 {
    Pass,
    Fail,
    Indeterminate,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum SessionEventKindV1 {
    SessionStarted {
        session_id: String,
        initial_input_manifest_sha256: String,
        frozen_context_sha256: String,
        initial_output_sha256: String,
    },
    UserTurnOpened {
        turn_index: u64,
        instruction_batch_sha256: String,
    },
    ConstraintAdded {
        turn_index: u64,
        constraint_id: String,
        role: ConstraintRoleV1,
        instruction_sha256: String,
        scope_sha256: String,
        rubric_profile_sha256: String,
    },
    ConstraintSuperseded {
        turn_index: u64,
        old_constraint_id: String,
        replacement_constraint_id: String,
        reason_sha256: String,
    },
    EditExecuted {
        turn_index: u64,
        step_index: u64,
        parent_output_sha256: String,
        output_audio_sha256: String,
        action_sha256: String,
        system_artifact_sha256: String,
    },
    ExecutionAttemptFailed {
        turn_index: u64,
        status: AttemptStatusV1,
        action_sha256: String,
        failure_receipt_sha256: String,
    },
    ObservationAttached {
        turn_index: u64,
        constraint_id: String,
        output_audio_sha256: String,
        decision: ObservationDecisionV1,
        rubric_profile_sha256: String,
        evaluator_artifact_sha256: String,
        evidence_receipt_sha256: String,
    },
    SessionFinalized {
        final_output_sha256: String,
        active_ledger_sha256: String,
        /// Canonically sorted IDs of every active instruction and preservation
        /// constraint. Replay checks this exact set against derived state.
        active_constraint_ids: Vec<String>,
    },
}

/// Event digests and previous-event links are generated by a canonical,
/// versioned serializer outside this crate. This evaluator validates their
/// syntax, uniqueness and chain continuity; it does not recompute the hashes.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SessionEventV1 {
    pub event_index: u64,
    pub previous_event_sha256: Option<String>,
    pub event_sha256: String,
    pub kind: SessionEventKindV1,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ConstraintRecordV1 {
    pub constraint_id: String,
    pub role: ConstraintRoleV1,
    pub added_turn: u64,
    pub instruction_sha256: String,
    pub scope_sha256: String,
    pub rubric_profile_sha256: String,
    pub superseded_by: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FailedAttemptV1 {
    pub event_index: u64,
    pub turn_index: u64,
    pub status: AttemptStatusV1,
    pub action_sha256: String,
    pub failure_receipt_sha256: String,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct EditStepV1 {
    pub event_index: u64,
    pub turn_index: u64,
    pub step_index: u64,
    pub parent_output_sha256: String,
    pub output_audio_sha256: String,
    pub action_sha256: String,
    pub system_artifact_sha256: String,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ConstraintObservationV1 {
    pub event_index: u64,
    pub turn_index: u64,
    pub constraint_id: String,
    pub output_audio_sha256: String,
    pub decision: ObservationDecisionV1,
    pub rubric_profile_sha256: String,
    pub evaluator_artifact_sha256: String,
    pub evidence_receipt_sha256: String,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SessionOutcomeV1 {
    InProgress,
    Qualified,
    Noncompliant,
    Indeterminate,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ActiveConstraintResultV1 {
    pub constraint: ConstraintRecordV1,
    pub final_decision: Option<ObservationDecisionV1>,
    pub final_observation_event_index: Option<u64>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SessionLedgerReportV1 {
    pub schema: String,
    pub session_id: String,
    pub initial_input_manifest_sha256: String,
    pub frozen_context_sha256: String,
    pub initial_output_sha256: String,
    pub current_output_sha256: String,
    pub final_output_sha256: Option<String>,
    pub active_ledger_sha256: Option<String>,
    pub event_count: usize,
    pub last_event_sha256: String,
    pub turn_count: u64,
    pub edit_count: usize,
    pub failed_attempt_count: usize,
    pub superseded_constraint_count: usize,
    pub outcome: SessionOutcomeV1,
    pub active_constraints: Vec<ActiveConstraintResultV1>,
    pub superseded_constraints: Vec<ConstraintRecordV1>,
    pub edits: Vec<EditStepV1>,
    pub failed_attempts: Vec<FailedAttemptV1>,
    pub observations: Vec<ConstraintObservationV1>,
}

#[derive(Clone, Debug)]
struct FinalizationV1 {
    output_sha256: String,
    active_ledger_sha256: String,
}

fn validate_session_spec(spec: &SessionSpecV1) -> Result<(), LedgerError> {
    require_non_empty(&spec.session_id, "session_id")?;
    validate_digest(
        &spec.initial_input_manifest_sha256,
        "initial_input_manifest_sha256",
    )?;
    validate_digest(&spec.frozen_context_sha256, "frozen_context_sha256")?;
    validate_digest(&spec.initial_output_sha256, "initial_output_sha256")?;
    Ok(())
}

/// Validate and replay a complete or partial append-only session.
///
/// A partial session returns InProgress. A finalized session is Qualified only
/// when every active instruction and preservation constraint has a PASS
/// observation against the exact final output. A FAIL or INDETERMINATE
/// observation is retained as a terminal non-qualified outcome.
pub fn evaluate_session_ledger(
    spec: &SessionSpecV1,
    events: &[SessionEventV1],
) -> Result<SessionLedgerReportV1, LedgerError> {
    validate_session_spec(spec)?;
    if events.is_empty() {
        return Err(LedgerError::new(
            "session ledger must contain its SessionStarted event",
        ));
    }

    let mut started = false;
    let mut current_turn = 0u64;
    let mut current_output = String::new();
    let mut previous_event_digest: Option<&str> = None;
    let mut seen_event_digests = BTreeSet::new();
    let mut constraints: BTreeMap<String, ConstraintRecordV1> = BTreeMap::new();
    let mut superseded = BTreeSet::new();
    let mut edits = Vec::new();
    let mut failed_attempts = Vec::new();
    let mut observations = Vec::new();
    let mut observation_keys = BTreeSet::new();
    let mut finalization: Option<FinalizationV1> = None;

    for (expected_index, event) in events.iter().enumerate() {
        if finalization.is_some() {
            return Err(LedgerError::new(
                "events after SessionFinalized are forbidden; start a new session version",
            ));
        }

        if event.event_index != expected_index as u64 {
            return Err(LedgerError::new(format!(
                "expected event index {}, received {}",
                expected_index, event.event_index
            )));
        }
        validate_digest(&event.event_sha256, "event_sha256")?;
        if !seen_event_digests.insert(event.event_sha256.as_str()) {
            return Err(LedgerError::new(format!(
                "duplicate event digest at index {}",
                event.event_index
            )));
        }

        match (expected_index, event.previous_event_sha256.as_deref()) {
            (0, None) => {}
            (0, Some(_)) => {
                return Err(LedgerError::new(
                    "SessionStarted must not have a previous-event digest",
                ));
            }
            (_, Some(previous)) => {
                validate_digest(previous, "previous_event_sha256")?;
                if Some(previous) != previous_event_digest {
                    return Err(LedgerError::new(format!(
                        "previous-event digest mismatch at event {}",
                        event.event_index
                    )));
                }
            }
            (_, None) => {
                return Err(LedgerError::new(format!(
                    "event {} is missing its previous-event digest",
                    event.event_index
                )));
            }
        }

        if expected_index == 0
            && !matches!(&event.kind, SessionEventKindV1::SessionStarted { .. })
        {
            return Err(LedgerError::new(
                "the first event must be SessionStarted",
            ));
        }

        match &event.kind {
            SessionEventKindV1::SessionStarted {
                session_id,
                initial_input_manifest_sha256,
                frozen_context_sha256,
                initial_output_sha256,
            } => {
                if started || expected_index != 0 {
                    return Err(LedgerError::new(
                        "SessionStarted may occur exactly once at event zero",
                    ));
                }
                if session_id != &spec.session_id
                    || initial_input_manifest_sha256 != &spec.initial_input_manifest_sha256
                    || frozen_context_sha256 != &spec.frozen_context_sha256
                    || initial_output_sha256 != &spec.initial_output_sha256
                {
                    return Err(LedgerError::new(
                        "SessionStarted identities do not match the frozen session specification",
                    ));
                }
                current_output = spec.initial_output_sha256.clone();
                started = true;
            }
            SessionEventKindV1::UserTurnOpened {
                turn_index,
                instruction_batch_sha256,
            } => {
                require_started(started)?;
                validate_digest(instruction_batch_sha256, "instruction_batch_sha256")?;
                let expected_turn = current_turn
                    .checked_add(1)
                    .ok_or_else(|| LedgerError::new("user turn index overflow"))?;
                if *turn_index != expected_turn {
                    return Err(LedgerError::new(format!(
                        "expected user turn {}, received {}",
                        expected_turn, turn_index
                    )));
                }
                current_turn = *turn_index;
            }
            SessionEventKindV1::ConstraintAdded {
                turn_index,
                constraint_id,
                role,
                instruction_sha256,
                scope_sha256,
                rubric_profile_sha256,
            } => {
                require_current_turn(started, current_turn, *turn_index)?;
                require_non_empty(constraint_id, "constraint_id")?;
                validate_digest(instruction_sha256, "instruction_sha256")?;
                validate_digest(scope_sha256, "scope_sha256")?;
                validate_digest(rubric_profile_sha256, "rubric_profile_sha256")?;
                if constraints.contains_key(constraint_id) {
                    return Err(LedgerError::new(format!(
                        "duplicate constraint ID: {constraint_id}"
                    )));
                }
                constraints.insert(
                    constraint_id.clone(),
                    ConstraintRecordV1 {
                        constraint_id: constraint_id.clone(),
                        role: *role,
                        added_turn: *turn_index,
                        instruction_sha256: instruction_sha256.clone(),
                        scope_sha256: scope_sha256.clone(),
                        rubric_profile_sha256: rubric_profile_sha256.clone(),
                        superseded_by: None,
                    },
                );
            }
            SessionEventKindV1::ConstraintSuperseded {
                turn_index,
                old_constraint_id,
                replacement_constraint_id,
                reason_sha256,
            } => {
                require_current_turn(started, current_turn, *turn_index)?;
                validate_digest(reason_sha256, "supersession_reason_sha256")?;
                if old_constraint_id == replacement_constraint_id {
                    return Err(LedgerError::new(
                        "a constraint cannot supersede itself",
                    ));
                }
                let old = constraints.get(old_constraint_id).ok_or_else(|| {
                    LedgerError::new(format!(
                        "superseded constraint does not exist: {old_constraint_id}"
                    ))
                })?;
                if old.superseded_by.is_some() {
                    return Err(LedgerError::new(format!(
                        "constraint {old_constraint_id} is already superseded"
                    )));
                }
                let replacement = constraints
                    .get(replacement_constraint_id)
                    .ok_or_else(|| {
                        LedgerError::new(format!(
                            "replacement constraint does not exist: {replacement_constraint_id}"
                        ))
                    })?;
                if replacement.superseded_by.is_some() {
                    return Err(LedgerError::new(
                        "replacement constraint is not active",
                    ));
                }
                if old.role != replacement.role {
                    return Err(LedgerError::new(
                        "supersession must preserve the constraint role",
                    ));
                }
                if superseded.contains(replacement_constraint_id) {
                    return Err(LedgerError::new(
                        "supersession would create a cycle or target a superseded constraint",
                    ));
                }
                let old_mut = constraints
                    .get_mut(old_constraint_id)
                    .ok_or_else(|| LedgerError::new("supersession target disappeared"))?;
                old_mut.superseded_by = Some(replacement_constraint_id.clone());
                superseded.insert(old_constraint_id.clone());
            }
            SessionEventKindV1::EditExecuted {
                turn_index,
                step_index,
                parent_output_sha256,
                output_audio_sha256,
                action_sha256,
                system_artifact_sha256,
            } => {
                require_current_turn(started, current_turn, *turn_index)?;
                let expected_step = edits.len() as u64 + 1;
                if *step_index != expected_step {
                    return Err(LedgerError::new(format!(
                        "expected edit step {}, received {}",
                        expected_step, step_index
                    )));
                }
                validate_digest(parent_output_sha256, "parent_output_sha256")?;
                validate_digest(output_audio_sha256, "output_audio_sha256")?;
                validate_digest(action_sha256, "action_sha256")?;
                validate_digest(system_artifact_sha256, "system_artifact_sha256")?;
                if parent_output_sha256 != &current_output {
                    return Err(LedgerError::new(format!(
                        "edit step {} does not consume the current output digest",
                        step_index
                    )));
                }
                edits.push(EditStepV1 {
                    event_index: event.event_index,
                    turn_index: *turn_index,
                    step_index: *step_index,
                    parent_output_sha256: parent_output_sha256.clone(),
                    output_audio_sha256: output_audio_sha256.clone(),
                    action_sha256: action_sha256.clone(),
                    system_artifact_sha256: system_artifact_sha256.clone(),
                });
                current_output = output_audio_sha256.clone();
            }
            SessionEventKindV1::ExecutionAttemptFailed {
                turn_index,
                status,
                action_sha256,
                failure_receipt_sha256,
            } => {
                require_current_turn(started, current_turn, *turn_index)?;
                validate_digest(action_sha256, "failed_action_sha256")?;
                validate_digest(failure_receipt_sha256, "failure_receipt_sha256")?;
                failed_attempts.push(FailedAttemptV1 {
                    event_index: event.event_index,
                    turn_index: *turn_index,
                    status: *status,
                    action_sha256: action_sha256.clone(),
                    failure_receipt_sha256: failure_receipt_sha256.clone(),
                });
            }
            SessionEventKindV1::ObservationAttached {
                turn_index,
                constraint_id,
                output_audio_sha256,
                decision,
                rubric_profile_sha256,
                evaluator_artifact_sha256,
                evidence_receipt_sha256,
            } => {
                require_current_turn(started, current_turn, *turn_index)?;
                let constraint = constraints.get(constraint_id).ok_or_else(|| {
                    LedgerError::new(format!(
                        "observation references an unknown constraint: {constraint_id}"
                    ))
                })?;
                if constraint.superseded_by.is_some() {
                    return Err(LedgerError::new(format!(
                        "observation targets inactive constraint: {constraint_id}"
                    )));
                }
                validate_digest(output_audio_sha256, "observation_output_sha256")?;
                if output_audio_sha256 != &current_output {
                    return Err(LedgerError::new(
                        "observation must bind the exact current output digest",
                    ));
                }
                validate_digest(rubric_profile_sha256, "observation_rubric_profile_sha256")?;
                if rubric_profile_sha256 != &constraint.rubric_profile_sha256 {
                    return Err(LedgerError::new(
                        "observation rubric profile does not match the constraint profile",
                    ));
                }
                validate_digest(evaluator_artifact_sha256, "evaluator_artifact_sha256")?;
                validate_digest(evidence_receipt_sha256, "evidence_receipt_sha256")?;
                let key = (constraint_id.clone(), output_audio_sha256.clone());
                if !observation_keys.insert(key) {
                    return Err(LedgerError::new(format!(
                        "duplicate observation for constraint {constraint_id} and output"
                    )));
                }
                observations.push(ConstraintObservationV1 {
                    event_index: event.event_index,
                    turn_index: *turn_index,
                    constraint_id: constraint_id.clone(),
                    output_audio_sha256: output_audio_sha256.clone(),
                    decision: *decision,
                    rubric_profile_sha256: rubric_profile_sha256.clone(),
                    evaluator_artifact_sha256: evaluator_artifact_sha256.clone(),
                    evidence_receipt_sha256: evidence_receipt_sha256.clone(),
                });
            }
            SessionEventKindV1::SessionFinalized {
                final_output_sha256,
                active_ledger_sha256,
                active_constraint_ids,
            } => {
                require_started(started)?;
                if current_turn == 0 {
                    return Err(LedgerError::new(
                        "a session must contain at least one user turn before finalization",
                    ));
                }
                validate_digest(final_output_sha256, "final_output_sha256")?;
                validate_digest(active_ledger_sha256, "active_ledger_sha256")?;
                if final_output_sha256 != &current_output {
                    return Err(LedgerError::new(
                        "final output digest does not match the last successful edit output",
                    ));
                }
                let active: Vec<&ConstraintRecordV1> = constraints
                    .values()
                    .filter(|constraint| constraint.superseded_by.is_none())
                    .collect();
                let derived_active_ids: Vec<String> = active
                    .iter()
                    .map(|constraint| constraint.constraint_id.clone())
                    .collect();
                if active_constraint_ids != &derived_active_ids {
                    return Err(LedgerError::new(
                        "final active constraint IDs do not match replayed session state",
                    ));
                }
                if active.is_empty() {
                    return Err(LedgerError::new(
                        "cannot finalize a session with no active instruction or preservation constraints",
                    ));
                }
                for constraint in active {
                    let has_final_observation = observations.iter().any(|observation| {
                        observation.constraint_id == constraint.constraint_id
                            && observation.output_audio_sha256.as_str()
                                == final_output_sha256.as_str()
                    });
                    if !has_final_observation {
                        return Err(LedgerError::new(format!(
                            "active constraint {} has no observation against the final output",
                            constraint.constraint_id
                        )));
                    }
                }
                finalization = Some(FinalizationV1 {
                    output_sha256: final_output_sha256.clone(),
                    active_ledger_sha256: active_ledger_sha256.clone(),
                });
            }
        }

        previous_event_digest = Some(event.event_sha256.as_str());
    }

    if !started {
        return Err(LedgerError::new("session ledger did not start"));
    }

    let active_constraints: Vec<ActiveConstraintResultV1> = constraints
        .values()
        .filter(|constraint| constraint.superseded_by.is_none())
        .map(|constraint| {
            let final_observation = finalization.as_ref().and_then(|finalized| {
                observations.iter().find(|observation| {
                    observation.constraint_id == constraint.constraint_id
                        && observation.output_audio_sha256 == finalized.output_sha256
                })
            });
            ActiveConstraintResultV1 {
                constraint: constraint.clone(),
                final_decision: final_observation.map(|observation| observation.decision),
                final_observation_event_index: final_observation
                    .map(|observation| observation.event_index),
            }
        })
        .collect();

    let superseded_constraints: Vec<ConstraintRecordV1> = constraints
        .values()
        .filter(|constraint| constraint.superseded_by.is_some())
        .cloned()
        .collect();

    let outcome = match &finalization {
        None => SessionOutcomeV1::InProgress,
        Some(_) if active_constraints.iter().any(|constraint| {
            constraint.final_decision == Some(ObservationDecisionV1::Fail)
        }) => SessionOutcomeV1::Noncompliant,
        Some(_) if active_constraints.iter().any(|constraint| {
            constraint.final_decision == Some(ObservationDecisionV1::Indeterminate)
        }) => SessionOutcomeV1::Indeterminate,
        Some(_) => SessionOutcomeV1::Qualified,
    };

    let final_output_sha256 = finalization
        .as_ref()
        .map(|finalized| finalized.output_sha256.clone());
    let active_ledger_sha256 = finalization
        .as_ref()
        .map(|finalized| finalized.active_ledger_sha256.clone());
    let last_event_sha256 = previous_event_digest
        .ok_or_else(|| LedgerError::new("session ledger has no event digest"))?
        .to_owned();

    Ok(SessionLedgerReportV1 {
        schema: SESSION_LEDGER_SCHEMA_V1.to_owned(),
        session_id: spec.session_id.clone(),
        initial_input_manifest_sha256: spec.initial_input_manifest_sha256.clone(),
        frozen_context_sha256: spec.frozen_context_sha256.clone(),
        initial_output_sha256: spec.initial_output_sha256.clone(),
        current_output_sha256: current_output,
        final_output_sha256,
        active_ledger_sha256,
        event_count: events.len(),
        last_event_sha256,
        turn_count: current_turn,
        edit_count: edits.len(),
        failed_attempt_count: failed_attempts.len(),
        superseded_constraint_count: superseded_constraints.len(),
        outcome,
        active_constraints,
        superseded_constraints,
        edits,
        failed_attempts,
        observations,
    })
}

fn require_started(started: bool) -> Result<(), LedgerError> {
    if !started {
        Err(LedgerError::new("event occurred before SessionStarted"))
    } else {
        Ok(())
    }
}

fn require_current_turn(
    started: bool,
    current_turn: u64,
    event_turn: u64,
) -> Result<(), LedgerError> {
    require_started(started)?;
    if current_turn == 0 || event_turn != current_turn {
        return Err(LedgerError::new(format!(
            "event turn {event_turn} does not match current user turn {current_turn}"
        )));
    }
    Ok(())
}

fn validate_digest(value: &str, field: &str) -> Result<(), LedgerError> {
    let valid = value.strip_prefix("sha256:").is_some_and(|hex| {
        hex.len() == 64
            && hex.bytes().all(|byte| {
                byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte)
            })
    });
    if !valid {
        return Err(LedgerError::new(format!(
            "{field} must be sha256: followed by 64 lowercase hexadecimal characters"
        )));
    }
    Ok(())
}

fn require_non_empty(value: &str, field: &str) -> Result<(), LedgerError> {
    if value.trim().is_empty() {
        Err(LedgerError::new(format!("{field} must not be empty")))
    } else {
        Ok(())
    }
}

