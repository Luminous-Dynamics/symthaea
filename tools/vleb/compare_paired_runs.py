def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--expected-input-sha256", required=True)
    parser.add_argument("--expected-protocol-sha256", required=True)
    parser.add_argument("--expected-analyzer-sha256", required=True)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args(argv)

    try:
        raw = args.input.read_bytes()
        observed_input_sha256 = digest(raw)
        _require_digest(args.expected_input_sha256, "expected input SHA-256")
        if observed_input_sha256 != args.expected_input_sha256:
            raise ValueError("input manifest differs from externally supplied SHA-256")
        manifest = strict_json_loads(raw)
        result = analyze_manifest(
            manifest,
            input_sha256=observed_input_sha256,
            expected_protocol_sha256=args.expected_protocol_sha256,
            expected_analyzer_sha256=args.expected_analyzer_sha256,
        )
    except (OSError, UnicodeError, ValueError, json.JSONDecodeError) as exc:
        result = {
            "schema_version": "vleb-paired-comparison-report-v1",
            "analysis_only": True,
            "score_eligible": False,
            "valid": False,
            "issues": [{"code": "paired_comparison_rejected", "message": str(exc)}],
        }
        rendered = json.dumps(result, indent=2, sort_keys=True) + "\n"
        if args.output:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(rendered, encoding="utf-8")
        print(rendered, end="")
        return 1

    rendered = json.dumps(result, indent=2, sort_keys=True) + "\n"
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered, encoding="utf-8")
    print(rendered, end="")
    return 0


