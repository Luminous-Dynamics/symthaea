//! Pure, deterministic CEB causal-investigation ledger model.
//!
//! This crate validates record identity, task binding, evidence ancestry,
//! forecast/action/outcome ordering, authority ceilings, and repair/grade
//! linkage. It performs no I/O, hashing, signing, network access, process
//! execution, or candidate-code execution.
//!
//! `Digest` values are opaque commitments supplied by the caller. This crate
//! does not compute or authenticate them. A valid ledger is not proof that a
//! producer, runner, observation, grader, or causal claim is trustworthy.
//!
//! # Qualification boundary
//!
//! This is a standalone research tool crate, not a production dependency.
//! It does not emit or replace the CEB benchmark run receipt or DSSE envelope.
//! Hostile task execution remains blocked until the repository's OS-isolation
//! prerequisite is independently qualified.

use std::collections::{HashMap, HashSet};
use std::error::Error;
use std::fmt;

/// Opaque 32-byte digest supplied by an external, qualified digesting layer.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub struct Digest(pub [u8; 32]);

/// Exact task and source/configuration identity shared by every ledger record.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct TaskBinding {
    /// Stable benchmark task identifier.
    pub task_id: String,
    /// Immutable task-contract revision.
    pub task_revision: String,
    /// Source-tree digest for this task instance.
    pub source_tree_digest: Digest,
    /// Configuration-world digest (features, target, environment contract).
    pub configuration_digest: Digest,
}

/// Provenance ceiling for a referenced evidence item.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum EvidenceAuthority {
    /// Explicitly declared in source or configuration.
    SourceDeclared,
    /// Derived from syntax without compiler name/type resolution.
    SyntaxDerived,
    /// Established by a pinned compiler or language server.
    CompilerResolved,
    /// Measured during a named runtime execution.
    RuntimeObserved,
    /// Measured after a controlled intervention.
    InterventionObserved,
    /// Candidate inference; not an observation.
    Inferred,
    /// Generated by an exploratory dream/counterfactual heuristic.
    DreamDerived,
    /// Evidence is insufficient, conflicting, or unavailable.
    Unresolved,
}

/// One evidence reference and its immutable provenance linkage.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct EvidenceRecord {
    /// Stable evidence identifier.
    pub id: String,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Authority level; never inferred from a digest or summary.
    pub authority: EvidenceAuthority,
    /// Stable origin grouping used to avoid double-counting copies/derivations.
    pub origin_id: String,
    /// Parent evidence identifiers. Parents must precede this record.
    pub parent_ids: Vec<String>,
    /// Action that produced this evidence, when applicable.
    pub source_action_id: Option<String>,
    /// Append order within this ledger (not trusted wall-clock time).
    pub sequence: u64,
}

/// Epistemic state of a task-scoped fault hypothesis.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum HypothesisStatus {
    /// Proposed explanation; not yet supported by causal evidence.
    Candidate,
    /// Supported by observational association only.
    Correlational,
    /// Supported by at least one controlled intervention observation.
    InterventionSupported,
    /// Identified only under explicitly declared assumptions.
    IdentifiedUnderAssumptions,
    /// Contradicted by evidence.
    Falsified,
    /// Available evidence cannot distinguish competing explanations.
    NonIdentifiable,
    /// Current task/profile is outside the declared applicability domain.
    OutOfDomain,
    /// Evidence is missing or conflicting.
    Unresolved,
}

/// A hypothesis with explicit support and contradiction references.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct HypothesisRecord {
    /// Stable hypothesis identifier.
    pub id: String,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Exact causal or fault claim.
    pub claim: String,
    /// Declared domain in which this claim is intended to apply.
    pub applicability_domain: String,
    /// Explicit competing hypothesis identifiers, including null where relevant.
    pub competing_hypothesis_ids: Vec<String>,
    /// Assumptions required for an identification claim.
    pub identification_assumptions: Vec<String>,
    /// Evidence references supporting this hypothesis.
    pub supporting_evidence_ids: Vec<String>,
    /// Evidence references contradicting this hypothesis.
    pub contradicting_evidence_ids: Vec<String>,
    /// Current epistemic status.
    pub status: HypothesisStatus,
    /// Append order within this ledger.
    pub sequence: u64,
}

/// Distinct action classes; these must not be treated as interchangeable.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ActionKind {
    /// Read-only inspection of source, state, or telemetry.
    Observation,
    /// Hard intervention on a declared variable (do(X=x)).
    HardIntervention,
    /// Replacement of a declared structural mechanism.
    MechanismReplacement,
    /// Execution of a frozen task-specific test oracle.
    TestExecution,
    /// Controlled perturbation of a configuration factor.
    ConfigurationPerturbation,
    /// Allocation of internal compute or a tool budget.
    ToolAllocation,
}

impl ActionKind {
    fn requires_explicit_authorization(self) -> bool {
        !matches!(self, Self::Observation | Self::ToolAllocation)
    }

    fn is_intervention(self) -> bool {
        matches!(
            self,
            Self::HardIntervention
                | Self::MechanismReplacement
                | Self::ConfigurationPerturbation
        )
    }
}

/// Authorization state recorded for a proposed action.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Authorization {
    /// No external effect or privileged execution is requested.
    NotRequired,
    /// The relevant authority explicitly permitted this action.
    Granted,
    /// The relevant authority denied this action.
    Denied,
}

/// Predicted observation quality; unknown is not a numeric zero.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ForecastPrediction {
    /// Digest of a declared predicted observation distribution.
    Distribution(Digest),
    /// A forecast was made but has not been calibrated.
    Uncalibrated,
    /// No defensible prediction was available.
    Unknown,
}

/// Forecasted or measured metric, preserving missingness.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum MetricValue {
    /// Numeric estimate or observation.
    Value(f64),
    /// A value exists conceptually but cannot be measured.
    NotMeasurable,
    /// The relevant counterfactual was not observed.
    NotObserved,
    /// Measurement was censored by the protocol.
    Censored,
    /// Measurement was invalidated.
    Invalidated,
    /// Metric is not applicable to this action/task.
    NotApplicable,
    /// Estimate is explicitly uncalibrated.
    Uncalibrated,
    /// No estimate was made.
    Unknown,
}

impl MetricValue {
    fn is_missing(self) -> bool {
        !matches!(self, Self::Value(_))
    }
}

/// Immutable prospective forecast sealed before action/outcome exposure.
#[derive(Clone, Debug, PartialEq)]
pub struct ForecastRecord {
    /// Stable forecast identifier.
    pub id: String,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Action this forecast evaluates.
    pub action_id: String,
    /// Expected action semantics.
    pub action_kind: ActionKind,
    /// Digest of the competing hypothesis set used for this forecast.
    pub hypothesis_set_digest: Digest,
    /// Predicted observation state/distribution.
    pub predicted_observation: ForecastPrediction,
    /// Expected information gain (separate from decision value).
    pub information_gain: MetricValue,
    /// Expected change in task decision value.
    pub decision_value: MetricValue,
    /// Predicted reduction in task error.
    pub error_reduction: MetricValue,
    /// Predicted resource cost.
    pub cost: MetricValue,
    /// Predicted latency in milliseconds.
    pub latency_ms: MetricValue,
    /// Predicted risk in the declared [0, 1] scale.
    pub risk: MetricValue,
    /// Append order; must precede action and outcome records.
    pub sequence: u64,
}

/// Authorization and forecast binding for a candidate experiment.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ActionRecord {
    /// Stable action identifier.
    pub id: String,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Forecast that prospectively evaluated this action.
    pub forecast_id: String,
    /// Typed action semantics.
    pub kind: ActionKind,
    /// Authorization state.
    pub authorization: Authorization,
    /// Append order; must follow the forecast.
    pub sequence: u64,
}

/// Execution/result state. Missing outcomes remain explicit.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum OutcomeStatus {
    /// A result was observed and linked to evidence.
    Observed,
    /// The proposed action was not run.
    NotRun,
    /// The result could not be measured.
    NotMeasurable,
    /// The result was censored by the protocol.
    Censored,
    /// The result was invalidated.
    Invalidated,
    /// The outcome is not applicable.
    NotApplicable,
}

/// Realized outcome of an experiment; counterfactual absence is not zero.
#[derive(Clone, Debug, PartialEq)]
pub struct OutcomeRecord {
    /// Stable outcome identifier.
    pub id: String,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Forecast that must precede this outcome.
    pub forecast_id: String,
    /// Authorized action that produced, or would have produced, the outcome.
    pub action_id: String,
    /// Outcome state.
    pub status: OutcomeStatus,
    /// Evidence reference for an observed result.
    pub observation_evidence_id: Option<String>,
    /// Realized utility/value, retaining missingness.
    pub realized_utility: MetricValue,
    /// Append order; must follow the forecast and action.
    pub sequence: u64,
}

/// Causal-ablation role for matched policy comparisons.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AblationArm {
    /// Full mechanism is active.
    Intact,
    /// Mechanism is computed but cannot affect action selection.
    Lesion,
    /// Matched bookkeeping without the target mechanism.
    Sham,
    /// The specific disabled consumption edge is restored.
    Rescue,
    /// Random action selection under matched cost.
    RandomMatchedCost,
    /// Frozen simple/static policy baseline.
    StaticBaseline,
}

/// Identity of a matched causal-ablation run.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AblationRecord {
    /// Stable ablation record identifier.
    pub id: String,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Shared pairing group for matched comparisons.
    pub matched_group_id: String,
    /// Treatment arm.
    pub arm: AblationArm,
    /// Digest of the policy/scaffold under test.
    pub policy_digest: Digest,
    /// Digest of the frozen resource budget.
    pub budget_digest: Digest,
    /// Append order.
    pub sequence: u64,
}

/// Proposed repair tied to hypotheses and prior investigation records.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct RepairRecord {
    /// Stable repair identifier.
    pub id: String,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Candidate patch digest.
    pub patch_digest: Digest,
    /// Hypotheses considered by the repair.
    pub hypothesis_ids: Vec<String>,
    /// Outcomes used to justify the repair.
    pub outcome_ids: Vec<String>,
    /// Append order; must follow every referenced hypothesis/outcome.
    pub sequence: u64,
}

/// Grade disposition from an independently identified evaluator.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum GradeVerdict {
    /// All declared acceptance gates passed.
    Accepted,
    /// At least one required gate failed.
    Rejected,
    /// The evidence or grader result is incomplete.
    Unresolved,
}

/// Distinguishes primary grading from a pristine regrade.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum GradeKind {
    /// First independent task-level grade.
    Primary,
    /// Regrade from the declared pristine environment.
    PristineRegrade,
}

/// Grade record bound to the exact repair patch.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GradeRecord {
    /// Stable grade identifier.
    pub id: String,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Repair being graded.
    pub repair_id: String,
    /// Exact candidate patch digest graded.
    pub patch_digest: Digest,
    /// Grade role.
    pub kind: GradeKind,
    /// Distinct execution identity supplied by the grading layer.
    pub execution_id: String,
    /// Evaluator revision identifier.
    pub evaluator_revision: String,
    /// Grade disposition.
    pub verdict: GradeVerdict,
    /// Append order; must follow the repair.
    pub sequence: u64,
}

/// Complete inert ledger. Validation does not execute any referenced action.
#[derive(Clone, Debug, PartialEq)]
pub struct Ledger {
    /// Immutable identity shared by all records.
    pub binding: TaskBinding,
    /// Referenced evidence.
    pub evidence: Vec<EvidenceRecord>,
    /// Competing task-scoped hypotheses.
    pub hypotheses: Vec<HypothesisRecord>,
    /// Prospective forecasts.
    pub forecasts: Vec<ForecastRecord>,
    /// Proposed/authorized actions.
    pub actions: Vec<ActionRecord>,
    /// Realized or explicitly missing outcomes.
    pub outcomes: Vec<OutcomeRecord>,
    /// Matched scheduler/causal ablations.
    pub ablations: Vec<AblationRecord>,
    /// Repair proposals.
    pub repairs: Vec<RepairRecord>,
    /// Primary and pristine-regrade records.
    pub grades: Vec<GradeRecord>,
}

/// Deterministic structural validation failure.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum ValidationError {
    /// Two records of one kind reuse an identifier.
    DuplicateId(&'static str),
    /// Two records reuse a ledger sequence.
    DuplicateSequence,
    /// A record does not bind to the ledger's exact task snapshot.
    TaskBindingMismatch,
    /// A referenced record does not exist.
    MissingReference,
    /// An evidence parent does not precede its child.
    EvidenceParentOutOfOrder,
    /// A hypothesis double-counts evidence with the same origin.
    DuplicateEvidenceOrigin,
    /// A causal status is claimed without intervention evidence.
    CausalStatusWithoutIntervention,
    /// Intervention evidence has no matching controlled action/outcome.
    InterventionEvidenceWithoutAction,
    /// Forecast/action/outcome links disagree or are out of order.
    ForecastActionOutcomeOrder,
    /// An action requiring authorization is not explicitly granted.
    MissingAuthorization,
    /// A denied action is represented as executed.
    DeniedActionExecuted,
    /// Outcome evidence is missing, extra, or unrelated to the action.
    OutcomeEvidenceMismatch,
    /// A missing outcome is represented by a numeric utility value.
    MissingOutcomeCoercedToValue,
    /// A metric contains NaN/infinity or violates its declared range.
    InvalidMetric,
    /// A repair references a later or unrelated investigation record.
    RepairReferenceMismatch,
    /// A grade is not bound to the exact repair patch.
    GradePatchMismatch,
    /// An execution identity is reused across grade records.
    DuplicateExecutionIdentity,
}

impl fmt::Display for ValidationError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{self:?}")
    }
}

impl Error for ValidationError {}

fn ensure_unique<'a>(
    kind: &'static str,
    ids: impl IntoIterator<Item = &'a str>,
) -> Result<(), ValidationError> {
    let mut seen = HashSet::new();
    for id in ids {
        if !seen.insert(id) {
            return Err(ValidationError::DuplicateId(kind));
        }
    }
    Ok(())
}

fn valid_metric(value: MetricValue, minimum: Option<f64>, maximum: Option<f64>) -> bool {
    match value {
        MetricValue::Value(number) => {
            number.is_finite()
                && minimum.is_none_or(|min| number >= min)
                && maximum.is_none_or(|max| number <= max)
        }
        MetricValue::NotMeasurable
        | MetricValue::NotObserved
        | MetricValue::Censored
        | MetricValue::Invalidated
        | MetricValue::NotApplicable
        | MetricValue::Uncalibrated
        | MetricValue::Unknown => true,
    }
}

impl Ledger {
    /// Validate structural integrity and epistemic/ordering invariants.
    ///
    /// This function does not hash content, verify signatures, establish runner
    /// isolation, authenticate graders, or prove observation truth.
    pub fn validate(&self) -> Result<(), ValidationError> {
        ensure_unique("evidence", self.evidence.iter().map(|record| record.id.as_str()))?;
        ensure_unique(
            "hypothesis",
            self.hypotheses.iter().map(|record| record.id.as_str()),
        )?;
        ensure_unique("forecast", self.forecasts.iter().map(|record| record.id.as_str()))?;
        ensure_unique("action", self.actions.iter().map(|record| record.id.as_str()))?;
        ensure_unique("outcome", self.outcomes.iter().map(|record| record.id.as_str()))?;
        ensure_unique("ablation", self.ablations.iter().map(|record| record.id.as_str()))?;
        ensure_unique("repair", self.repairs.iter().map(|record| record.id.as_str()))?;
        ensure_unique("grade", self.grades.iter().map(|record| record.id.as_str()))?;
        ensure_unique(
            "execution",
            self.grades.iter().map(|record| record.execution_id.as_str()),
        )?;

        let sequences = self
            .evidence
            .iter()
            .map(|record| record.sequence)
            .chain(self.hypotheses.iter().map(|record| record.sequence))
            .chain(self.forecasts.iter().map(|record| record.sequence))
            .chain(self.actions.iter().map(|record| record.sequence))
            .chain(self.outcomes.iter().map(|record| record.sequence))
            .chain(self.ablations.iter().map(|record| record.sequence))
            .chain(self.repairs.iter().map(|record| record.sequence))
            .chain(self.grades.iter().map(|record| record.sequence));
        let mut seen_sequences = HashSet::new();
        if sequences.into_iter().any(|sequence| !seen_sequences.insert(sequence)) {
            return Err(ValidationError::DuplicateSequence);
        }

        for record in &self.evidence {
            if record.binding != self.binding {
                return Err(ValidationError::TaskBindingMismatch);
            }
        }
        for record in &self.hypotheses {
            if record.binding != self.binding {
                return Err(ValidationError::TaskBindingMismatch);
            }
        }
        for record in &self.forecasts {
            if record.binding != self.binding {
                return Err(ValidationError::TaskBindingMismatch);
            }
            if !valid_metric(record.information_gain, Some(0.0), None)
                || !valid_metric(record.decision_value, None, None)
                || !valid_metric(record.error_reduction, None, None)
                || !valid_metric(record.cost, Some(0.0), None)
                || !valid_metric(record.latency_ms, Some(0.0), None)
                || !valid_metric(record.risk, Some(0.0), Some(1.0))
            {
                return Err(ValidationError::InvalidMetric);
            }
        }
        for record in &self.actions {
            if record.binding != self.binding {
                return Err(ValidationError::TaskBindingMismatch);
            }
            if record.kind.requires_explicit_authorization()
                && record.authorization == Authorization::NotRequired
            {
                return Err(ValidationError::MissingAuthorization);
            }
        }
        for record in &self.outcomes {
            if record.binding != self.binding {
                return Err(ValidationError::TaskBindingMismatch);
            }
            if let MetricValue::Value(value) = record.realized_utility {
                if !value.is_finite() {
                    return Err(ValidationError::InvalidMetric);
                }
            }
        }
        for record in &self.ablations {
            if record.binding != self.binding {
                return Err(ValidationError::TaskBindingMismatch);
            }
        }
        for record in &self.repairs {
            if record.binding != self.binding {
                return Err(ValidationError::TaskBindingMismatch);
            }
        }
        for record in &self.grades {
            if record.binding != self.binding {
                return Err(ValidationError::TaskBindingMismatch);
            }
        }

        let evidence_by_id: HashMap<&str, &EvidenceRecord> = self
            .evidence
            .iter()
            .map(|record| (record.id.as_str(), record))
            .collect();
        let hypotheses_by_id: HashMap<&str, &HypothesisRecord> = self
            .hypotheses
            .iter()
            .map(|record| (record.id.as_str(), record))
            .collect();
        let forecasts_by_id: HashMap<&str, &ForecastRecord> = self
            .forecasts
            .iter()
            .map(|record| (record.id.as_str(), record))
            .collect();
        let actions_by_id: HashMap<&str, &ActionRecord> = self
            .actions
            .iter()
            .map(|record| (record.id.as_str(), record))
            .collect();
        let outcomes_by_id: HashMap<&str, &OutcomeRecord> = self
            .outcomes
            .iter()
            .map(|record| (record.id.as_str(), record))
            .collect();
        let repairs_by_id: HashMap<&str, &RepairRecord> = self
            .repairs
            .iter()
            .map(|record| (record.id.as_str(), record))
            .collect();

        for record in &self.evidence {
            for parent_id in &record.parent_ids {
                let parent = evidence_by_id
                    .get(parent_id.as_str())
                    .ok_or(ValidationError::MissingReference)?;
                if parent.sequence >= record.sequence {
                    return Err(ValidationError::EvidenceParentOutOfOrder);
                }
            }
        }

        for hypothesis in &self.hypotheses {
            let mut origins = HashSet::new();
            let mut has_intervention_support = false;
            for evidence_id in &hypothesis.supporting_evidence_ids {
                let evidence = evidence_by_id
                    .get(evidence_id.as_str())
                    .ok_or(ValidationError::MissingReference)?;
                if evidence.sequence >= hypothesis.sequence {
                    return Err(ValidationError::EvidenceParentOutOfOrder);
                }
                if !origins.insert(evidence.origin_id.as_str()) {
                    return Err(ValidationError::DuplicateEvidenceOrigin);
                }
                has_intervention_support |=
                    evidence.authority == EvidenceAuthority::InterventionObserved;
            }
            for evidence_id in &hypothesis.contradicting_evidence_ids {
                let evidence = evidence_by_id
                    .get(evidence_id.as_str())
                    .ok_or(ValidationError::MissingReference)?;
                if evidence.sequence >= hypothesis.sequence {
                    return Err(ValidationError::EvidenceParentOutOfOrder);
                }
            }
            for competing_id in &hypothesis.competing_hypothesis_ids {
                if competing_id == &hypothesis.id
                    || !hypotheses_by_id.contains_key(competing_id.as_str())
                {
                    return Err(ValidationError::MissingReference);
                }
            }
            if hypothesis.applicability_domain.trim().is_empty() {
                return Err(ValidationError::MissingReference);
            }
            if matches!(
                hypothesis.status,
                HypothesisStatus::InterventionSupported
                    | HypothesisStatus::IdentifiedUnderAssumptions
            ) && !has_intervention_support
            {
                return Err(ValidationError::CausalStatusWithoutIntervention);
            }
            if hypothesis.status == HypothesisStatus::IdentifiedUnderAssumptions
                && hypothesis.identification_assumptions.is_empty()
            {
                return Err(ValidationError::CausalStatusWithoutIntervention);
            }
        }

        let mut forecast_action_ids = HashSet::new();
        for action in &self.actions {
            let forecast = forecasts_by_id
                .get(action.forecast_id.as_str())
                .ok_or(ValidationError::MissingReference)?;
            if forecast.action_id != action.id
                || forecast.action_kind != action.kind
                || forecast.sequence >= action.sequence
                || !forecast_action_ids.insert(forecast.id.as_str())
            {
                return Err(ValidationError::ForecastActionOutcomeOrder);
            }
        }

        for outcome in &self.outcomes {
            let action = actions_by_id
                .get(outcome.action_id.as_str())
                .ok_or(ValidationError::MissingReference)?;
            let forecast = forecasts_by_id
                .get(outcome.forecast_id.as_str())
                .ok_or(ValidationError::MissingReference)?;
            if action.forecast_id != forecast.id
                || forecast.action_id != action.id
                || forecast.sequence >= action.sequence
                || action.sequence >= outcome.sequence
                || action.authorization == Authorization::Denied
                    && outcome.status == OutcomeStatus::Observed
            {
                return Err(if action.authorization == Authorization::Denied {
                    ValidationError::DeniedActionExecuted
                } else {
                    ValidationError::ForecastActionOutcomeOrder
                });
            }

            match outcome.status {
                OutcomeStatus::Observed => {
                    let evidence_id = outcome
                        .observation_evidence_id
                        .as_deref()
                        .ok_or(ValidationError::OutcomeEvidenceMismatch)?;
                    let evidence = evidence_by_id
                        .get(evidence_id)
                        .ok_or(ValidationError::MissingReference)?;
                    if evidence.source_action_id.as_deref() != Some(action.id.as_str())
                        || evidence.sequence <= action.sequence
                        || evidence.sequence >= outcome.sequence
                    {
                        return Err(ValidationError::OutcomeEvidenceMismatch);
                    }
                }
                OutcomeStatus::NotRun
                | OutcomeStatus::NotMeasurable
                | OutcomeStatus::Censored
                | OutcomeStatus::Invalidated
                | OutcomeStatus::NotApplicable => {
                    if outcome.observation_evidence_id.is_some()
                        || !outcome.realized_utility.is_missing()
                    {
                        return Err(ValidationError::MissingOutcomeCoercedToValue);
                    }
                }
            }
        }

        for evidence in &self.evidence {
            if evidence.authority == EvidenceAuthority::InterventionObserved {
                let action_id = evidence
                    .source_action_id
                    .as_deref()
                    .ok_or(ValidationError::InterventionEvidenceWithoutAction)?;
                let action = actions_by_id
                    .get(action_id)
                    .ok_or(ValidationError::MissingReference)?;
                let has_observed_outcome = self.outcomes.iter().any(|outcome| {
                    outcome.action_id == action.id
                        && outcome.status == OutcomeStatus::Observed
                        && outcome.observation_evidence_id.as_deref() == Some(evidence.id.as_str())
                        && outcome.sequence > evidence.sequence
                });
                if !action.kind.is_intervention()
                    || action.authorization != Authorization::Granted
                    || !has_observed_outcome
                {
                    return Err(ValidationError::InterventionEvidenceWithoutAction);
                }
            }
        }

        for repair in &self.repairs {
            for hypothesis_id in &repair.hypothesis_ids {
                let hypothesis = hypotheses_by_id
                    .get(hypothesis_id.as_str())
                    .ok_or(ValidationError::RepairReferenceMismatch)?;
                if hypothesis.sequence >= repair.sequence {
                    return Err(ValidationError::RepairReferenceMismatch);
                }
            }
            for outcome_id in &repair.outcome_ids {
                let outcome = outcomes_by_id
                    .get(outcome_id.as_str())
                    .ok_or(ValidationError::RepairReferenceMismatch)?;
                if outcome.sequence >= repair.sequence {
                    return Err(ValidationError::RepairReferenceMismatch);
                }
            }
        }

        for grade in &self.grades {
            let repair = repairs_by_id
                .get(grade.repair_id.as_str())
                .ok_or(ValidationError::MissingReference)?;
            if grade.sequence <= repair.sequence || grade.patch_digest != repair.patch_digest {
                return Err(ValidationError::GradePatchMismatch);
            }
        }

        Ok(())
    }
}

