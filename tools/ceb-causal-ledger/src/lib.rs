//! Pure, deterministic CEB causal-investigation ledger model.
//!
//! This crate validates record identity, task binding, evidence ancestry,
//! forecast/action/outcome ordering, authority ceilings, and repair/grade
//! linkage. It performs no I/O, hashing, signing, network access, process
//! execution, or candidate-code execution.
//!
//! `Digest` values are opaque commitments supplied by the caller. This crate
//! does not compute or authenticate them. A valid ledger is not proof that a
//! producer, runner, observation, grader, or causal claim is trustworthy.
//!
//! # Qualification boundary
//!
//! This is a standalone research tool crate, not a production dependency.
//! It does not emit or replace the CEB benchmark run receipt or DSSE envelope.
//! Hostile task execution remains blocked until the repository's OS-isolation
//! prerequisite is independently qualified.

use std::collections::{HashMap, HashSet};
use std::error::Error;
use std::fmt;

/// Opaque 32-byte digest supplied by an external, qualified digesting layer.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub struct Digest(pub [u8; 32]);

/// Exact task and source/configuration identity shared by every ledger record.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct TaskBinding {
    /// Stable benchmark task identifier.
    pub task_id: String,
    /// Immutable task-contract revision.
    pub task_revision: String,
    /// Source-tree digest for this task instance.
    pub source_tree_digest: Digest,
    /// Configuration-world digest (features, target, environment contract).
    pub configuration_digest: Digest,
}

/// Provenance ceiling for a referenced evidence item.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum EvidenceAuthority {
    /// Explicitly declared in source or configuration.
    SourceDeclared,
    /// Derived from syntax without compiler name/type resolution.
    SyntaxDerived,
    /// Established by a pinned compiler or language server.
    CompilerResolved,
    /// Measured during a named runtime execution.
    RuntimeObserved,
    /// Measured after a controlled intervention.
    InterventionObserved,
    /// Candidate inference; not an observation.
    Inferred,
    /// Generated by an exploratory dream/counterfactual heuristic.
    DreamDerived,
    /// Evidence is insufficient, conflicting, or unavailable.
    Unresolved,
}

/// One evidence reference and its immutable provenance linkage.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct EvidenceRecord {
    /// Stable evidence identifier.
    pub id: String,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Content digest of the immutable evidence payload (not authenticated here).
    pub content_digest: Digest,
    /// Authority level; never inferred from a digest or summary.
    pub authority: EvidenceAuthority,
    /// Stable origin grouping used to avoid double-counting copies/derivations.
    pub origin_id: String,
    /// Parent evidence identifiers. Parents must precede this record.
    pub parent_ids: Vec<String>,
    /// Action that produced this evidence, when applicable.
    pub source_action_id: Option<String>,
    /// Append order within this ledger (not trusted wall-clock time).
    pub sequence: u64,
}

/// Epistemic state of a task-scoped fault hypothesis.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum HypothesisStatus {
    /// Proposed explanation; not yet supported by causal evidence.
    Candidate,
    /// Supported by observational association only.
    Correlational,
    /// Supported by at least one controlled intervention observation.
    InterventionSupported,
    /// Identified only under explicitly declared assumptions.
    IdentifiedUnderAssumptions,
    /// Contradicted by evidence.
    Falsified,
    /// Available evidence cannot distinguish competing explanations.
    NonIdentifiable,
    /// Current task/profile is outside the declared applicability domain.
    OutOfDomain,
    /// Evidence is missing or conflicting.
    Unresolved,
}

/// A hypothesis with explicit support and contradiction references.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct HypothesisRecord {
    /// Unique immutable hypothesis-revision record identifier.
    pub id: String,
    /// Stable logical hypothesis identifier shared across revisions.
    pub hypothesis_id: String,
    /// Previous revision record, when this is an update.
    pub previous_record_id: Option<String>,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Exact causal or fault claim.
    pub claim: String,
    /// Declared domain in which this claim is intended to apply.
    pub applicability_domain: String,
    /// Competing logical hypothesis identifiers, including null where relevant.
    pub competing_hypothesis_ids: Vec<String>,
    /// Assumptions required for an identification claim.
    pub identification_assumptions: Vec<String>,
    /// Evidence references supporting this hypothesis.
    pub supporting_evidence_ids: Vec<String>,
    /// Evidence references contradicting this hypothesis.
    pub contradicting_evidence_ids: Vec<String>,
    /// Current epistemic status.
    pub status: HypothesisStatus,
    /// Append order within this ledger.
    pub sequence: u64,
}

/// Distinct action classes; these must not be treated as interchangeable.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ActionKind {
    /// Read-only inspection of source, state, or telemetry.
    Observation,
    /// Hard intervention on a declared variable (do(X=x)).
    HardIntervention,
    /// Replacement of a declared structural mechanism.
    MechanismReplacement,
    /// Execution of a frozen task-specific test oracle.
    TestExecution,
    /// Controlled perturbation of a configuration factor.
    ConfigurationPerturbation,
    /// Allocation of internal compute or a tool budget.
    ToolAllocation,
}

impl ActionKind {
    fn requires_explicit_authorization(self) -> bool {
        !matches!(self, Self::Observation | Self::ToolAllocation)
    }

    fn is_intervention(self) -> bool {
        matches!(
            self,
            Self::HardIntervention
                | Self::MechanismReplacement
                | Self::ConfigurationPerturbation
        )
    }
}

/// Authorization state recorded for a proposed action.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum Authorization {
    /// No external effect or privileged execution is requested.
    NotRequired,
    /// The relevant authority explicitly permitted this action.
    Granted { decision_id: String },
    /// The relevant authority denied this action.
    Denied { decision_id: String },
}

/// Predicted observation quality; unknown is not a numeric zero.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ForecastPrediction {
    /// Digest of a declared predicted observation distribution.
    Distribution(Digest),
    /// A forecast was made but has not been calibrated.
    Uncalibrated,
    /// No defensible prediction was available.
    Unknown,
}

/// Forecasted or measured metric, preserving missingness.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum MetricValue {
    /// Numeric estimate or observation.
    Value(f64),
    /// A value exists conceptually but cannot be measured.
    NotMeasurable,
    /// The relevant counterfactual was not observed.
    NotObserved,
    /// Measurement was censored by the protocol.
    Censored,
    /// Measurement was invalidated.
    Invalidated,
    /// Metric is not applicable to this action/task.
    NotApplicable,
    /// Estimate is explicitly uncalibrated.
    Uncalibrated,
    /// No estimate was made.
    Unknown,
}

impl MetricValue {
    fn is_missing(self) -> bool {
        !matches!(self, Self::Value(_))
    }
}

/// Immutable prospective forecast sealed before action/outcome exposure.
#[derive(Clone, Debug, PartialEq)]
pub struct ForecastRecord {
    /// Stable forecast identifier.
    pub id: String,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Action this forecast evaluates.
    pub action_id: String,
    /// Expected action semantics.
    pub action_kind: ActionKind,
    /// Exact hypothesis revision records available when this forecast was sealed.
    pub hypothesis_record_ids: Vec<String>,
    /// Digest of the competing hypothesis set used for this forecast.
    pub hypothesis_set_digest: Digest,
    /// Digest of the policy/profile that generated this forecast.
    pub policy_digest: Digest,
    /// Digest of the exact proposed action parameters.
    pub parameters_digest: Digest,
    /// Predicted observation state/distribution.
    pub predicted_observation: ForecastPrediction,
    /// Expected information gain (separate from decision value).
    pub information_gain: MetricValue,
    /// Expected change in task decision value.
    pub decision_value: MetricValue,
    /// Predicted reduction in task error.
    pub error_reduction: MetricValue,
    /// Predicted resource cost.
    pub cost: MetricValue,
    /// Predicted latency in milliseconds.
    pub latency_ms: MetricValue,
    /// Predicted risk in the declared [0, 1] scale.
    pub risk: MetricValue,
    /// Append order; must precede action and outcome records.
    pub sequence: u64,
}

/// Authorization and forecast binding for a candidate experiment.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ActionRecord {
    /// Stable action identifier.
    pub id: String,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Forecast that prospectively evaluated this action.
    pub forecast_id: String,
    /// Typed action semantics.
    pub kind: ActionKind,
    /// Digest of the policy/scaffold that selected this action.
    pub policy_digest: Digest,
    /// Digest of the exact parameters authorized/executed.
    pub parameters_digest: Digest,
    /// Authorization state.
    pub authorization: Authorization,
    /// Append order; must follow the forecast.
    pub sequence: u64,
}

/// Execution/result state. Missing outcomes remain explicit.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum OutcomeStatus {
    /// A result was observed and linked to evidence.
    Observed,
    /// The proposed action was not run.
    NotRun,
    /// The result could not be measured.
    NotMeasurable,
    /// The result was censored by the protocol.
    Censored,
    /// The result was invalidated.
    Invalidated,
    /// The outcome is not applicable.
    NotApplicable,
}

/// Realized outcome of an experiment; counterfactual absence is not zero.
#[derive(Clone, Debug, PartialEq)]
pub struct OutcomeRecord {
    /// Stable outcome identifier.
    pub id: String,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Forecast that must precede this outcome.
    pub forecast_id: String,
    /// Authorized action that produced, or would have produced, the outcome.
    pub action_id: String,
    /// Outcome state.
    pub status: OutcomeStatus,
    /// Evidence reference for an observed result.
    pub observation_evidence_id: Option<String>,
    /// Realized utility/value, retaining missingness.
    pub realized_utility: MetricValue,
    /// Append order; must follow the forecast and action.
    pub sequence: u64,
}

/// Causal-ablation role for matched policy comparisons.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AblationArm {
    /// Full mechanism is active.
    Intact,
    /// Mechanism is computed but cannot affect action selection.
    Lesion,
    /// Matched bookkeeping without the target mechanism.
    Sham,
    /// The specific disabled consumption edge is restored.
    Rescue,
    /// Random action selection under matched cost.
    RandomMatchedCost,
    /// Frozen simple/static policy baseline.
    StaticBaseline,
}

/// Identity of a matched causal-ablation run.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AblationRecord {
    /// Stable ablation record identifier.
    pub id: String,
    /// Exact task/source/configuration identity.
    pub binding: TaskBinding,
    /// Shared pairing group for matched comparisons.
    pub matched_group_id: String,
    /// Treatment arm.
    pub arm: AblationArm,
    /// Digest of the policy/scaffold under test.
    pub policy_digest: Digest,
    /// Digest of the frozen resource budget.
    pub budget_digest: Digest,
    /// Append order.
    pub sequence: u64,
}

/// Final investigation decision before any repair or side effect.
