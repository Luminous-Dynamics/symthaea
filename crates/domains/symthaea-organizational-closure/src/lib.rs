/// Immutable reference to one exact component version.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ArtifactRef {
    pub id: ArtifactVersionId,
    pub digest: ContentDigest,
    pub origin: ArtifactOrigin,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum StoreError {
    DuplicateVersion(ArtifactVersionId),
}

/// Minimal artifact store used by the verifier. Production systems should
/// adapt this interface to immutable, content-addressed durable storage.
#[derive(Debug, Clone, Default)]
pub struct ArtifactStore {
    bytes_by_version: BTreeMap<ArtifactVersionId, Vec<u8>>,
}

impl ArtifactStore {
    /// Inserts bytes once and returns their recomputed digest.
    pub fn insert(
        &mut self,
        id: ArtifactVersionId,
        bytes: Vec<u8>,
    ) -> Result<ContentDigest, StoreError> {
        use std::collections::btree_map::Entry;
        let digest = ContentDigest::of(&bytes);
        match self.bytes_by_version.entry(id) {
            Entry::Vacant(entry) => {
                entry.insert(bytes);
                Ok(digest)
            }
            Entry::Occupied(entry) => Err(StoreError::DuplicateVersion(entry.key().clone())),
        }
    }

    pub fn get(&self, id: &ArtifactVersionId) -> Option<&[u8]> {
        self.bytes_by_version.get(id).map(Vec::as_slice)
    }

    pub fn len(&self) -> usize {
        self.bytes_by_version.len()
    }

    pub fn is_empty(&self) -> bool {
        self.bytes_by_version.is_empty()
    }
}

