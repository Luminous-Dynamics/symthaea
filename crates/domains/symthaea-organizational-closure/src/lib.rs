/// SHA-256 content identity. The verifier always recomputes this from stored
/// bytes; a digest supplied by an agent is never accepted on assertion alone.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct ContentDigest([u8; 32]);

impl ContentDigest {
    pub fn of(bytes: &[u8]) -> Self {
        let mut hasher = Sha256::new();
        hasher.update(bytes);
        let digest = hasher.finalize();
        let mut bytes_out = [0_u8; 32];
        bytes_out.copy_from_slice(&digest);
        Self(bytes_out)
    }

    pub fn as_bytes(&self) -> &[u8; 32] {
        &self.0
    }
}

/// Component categories prevent external resources and immutable roots from
/// being counted as internally regenerated components.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ComponentClass {
    /// Must be regenerated by an internal process and consumed downstream.
    RegenerativeInternal,
    /// Supplied by a trusted initializer; not claimed as regenerated.
    ProvisionedImmutable,
    /// External substrate or resource; record access as an external receipt.
    ExternalResource,
    /// Externally governed constraint; the evaluated agent cannot rewrite it.
    Constraint,
    /// Evidence generated by the system, such as a checkpoint or manifest.
    EvidenceArtifact,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ComponentSpec {
    pub id: ComponentId,
    pub class: ComponentClass,
    /// When true for a RegenerativeInternal component, the runtime trace must
    /// prove both a producer and a downstream consumer of an exact version.
    pub required_for_viability: bool,
}

impl ComponentSpec {
    pub fn new(
        id: impl Into<ComponentId>,
        class: ComponentClass,
        required_for_viability: bool,
    ) -> Self {
        Self {
            id: id.into(),
            class,
            required_for_viability,
        }
    }
}

/// A process contract distinguishes required and optional inputs/outputs.
/// External dependencies are an allow-list; every observed access must be
/// represented by an event receipt.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProcessSpec {
    pub id: ProcessId,
    pub version: ProcessVersion,
    /// Expected executable identity frozen in the organization declaration.
    /// This binds identity metadata; it is not proof that this binary ran.
    pub executable_digest: ContentDigest,
    pub required_inputs: BTreeSet<ComponentId>,
    pub optional_inputs: BTreeSet<ComponentId>,
    pub required_outputs: BTreeSet<ComponentId>,
    pub optional_outputs: BTreeSet<ComponentId>,
    pub required_external_dependencies: BTreeSet<DependencyId>,
    pub optional_external_dependencies: BTreeSet<DependencyId>,
}

impl ProcessSpec {
    pub fn new(
        id: impl Into<ProcessId>,
        version: impl Into<ProcessVersion>,
        executable_digest: ContentDigest,
    ) -> Self {
        Self {
            id: id.into(),
            version: version.into(),
            executable_digest,
            required_inputs: BTreeSet::new(),
            optional_inputs: BTreeSet::new(),
            required_outputs: BTreeSet::new(),
            optional_outputs: BTreeSet::new(),
            required_external_dependencies: BTreeSet::new(),
            optional_external_dependencies: BTreeSet::new(),
        }
    }

    pub fn allows_input(&self, id: &ComponentId) -> bool {
        self.required_inputs.contains(id) || self.optional_inputs.contains(id)
    }

    pub fn allows_output(&self, id: &ComponentId) -> bool {
        self.required_outputs.contains(id) || self.optional_outputs.contains(id)
    }
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct OrganizationSpec {
    pub components: BTreeMap<ComponentId, ComponentSpec>,
    pub processes: BTreeMap<ProcessId, ProcessSpec>,
}

impl OrganizationSpec {
    /// Returns false rather than silently replacing an existing declaration.
    pub fn insert_component(&mut self, component: ComponentSpec) -> bool {
        use std::collections::btree_map::Entry;
        match self.components.entry(component.id.clone()) {
            Entry::Vacant(entry) => {
                entry.insert(component);
                true
            }
            Entry::Occupied(_) => false,
        }
    }

    /// Returns false rather than silently replacing an existing declaration.
    pub fn insert_process(&mut self, process: ProcessSpec) -> bool {
        use std::collections::btree_map::Entry;
        match self.processes.entry(process.id.clone()) {
            Entry::Vacant(entry) => {
                entry.insert(process);
                true
            }
            Entry::Occupied(_) => false,
        }
    }
}

