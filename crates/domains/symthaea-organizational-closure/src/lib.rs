//! Evidence-oriented primitives for AOBench.
//!
//! This crate distinguishes declared organization from observed execution.
//! It verifies content-addressed component versions, process input/output
//! contracts, producer/consumer lineage, and declared external dependency
//! observations.
//!
//! It does NOT prove strict biological autopoiesis, life, sentience, or
//! phenomenal consciousness. A report is relative to the supplied system
//! boundary, organization specification, trace, and artifact store.
//!
#![forbid(unsafe_code)]

//! Trust boundary: this verifier recomputes artifact digests and validates
//! trace consistency. It does not authenticate the trace producer, establish
//! that a process truly ran on physical hardware, or authorize the process.
//! A production adapter must obtain events from an independent trusted logger,
//! authenticate receipts, and keep the verifier outside the agent's authority.

