/// Reconstruct historical contamination and bind it to the publication-authorized target set.
pub fn audit_authorized_targets(
    config: &LocalExperimentConfig,
    prepared: &PreparedExperiment,
    acquisition: &HistoricalSnapshotAcquisitionReceipt,
    database_state: &VerifiedImportedDatabaseState,
    extraction: &CompletedQmpyExtraction,
    authorized_targets: &AuthorizedHistoricalTargetSet,
    verifier_executable: &Path,
) -> Result<(VerifiedHistoricalRun, AuthorizedAuditBinding), ExperimentError> {
    prepared.validate_against(config)?;
    let verifier_sha = hash_file(verifier_executable)?.0;
    let archive = File::open(&config.compressed_snapshot_path).map_err(ExperimentError::Io)?;
    let targets = authorized_targets
        .to_audit_targets()
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
    let run = verify_historical_run(
        &verifier_sha,
        &oqmd_v17_fe_co_zr_protocol(),
        BufReader::new(archive),
        acquisition,
        &prepared.import_profile,
        &database_state.import_receipt,
        &database_state.inventory,
        &extraction.extraction_receipt,
        &extraction.corpus,
        &targets,
    )
    .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
    let binding = bind_authorized_targets_to_historical_run(&run, authorized_targets)
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
    Ok((run, binding))
}

/// Re-run pure end-to-end verification and require exact equality with stored run/binding artifacts.
pub fn verify_stored_audit(
    config: &LocalExperimentConfig,
    prepared: &PreparedExperiment,
    acquisition: &HistoricalSnapshotAcquisitionReceipt,
    database_state: &VerifiedImportedDatabaseState,
    extraction: &CompletedQmpyExtraction,
    authorized_targets: &AuthorizedHistoricalTargetSet,
    stored_run: &VerifiedHistoricalRun,
    stored_binding: &AuthorizedAuditBinding,
    verifier_executable: &Path,
) -> Result<(), ExperimentError> {
    let (recomputed_run, recomputed_binding) = audit_authorized_targets(
        config,
        prepared,
        acquisition,
        database_state,
        extraction,
        authorized_targets,
        verifier_executable,
    )?;
    if &recomputed_run != stored_run || &recomputed_binding != stored_binding {
        return Err(ExperimentError::StoredVerificationMismatch);
    }
    Ok(())
}

/// Read an immutable JSON artifact.
pub fn read_json<T: DeserializeOwned>(path: &Path) -> Result<T, ExperimentError> {
    let file = File::open(path).map_err(ExperimentError::Io)?;
    serde_json::from_reader(BufReader::new(file)).map_err(ExperimentError::Json)
}

/// Write an immutable pretty JSON artifact using create-new semantics.
pub fn write_json_new<T: Serialize>(path: &Path, value: &T) -> Result<(), ExperimentError> {
    if !path.is_absolute() {
        return Err(ExperimentError::PathNotAbsolute(path.display().to_string()));
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(ExperimentError::Io)?;
    }
    let mut file = OpenOptions::new()
        .create_new(true)
        .write(true)
        .open(path)
        .map_err(ExperimentError::Io)?;
    serde_json::to_writer_pretty(&mut file, value).map_err(ExperimentError::Json)?;
    file.write_all(b"\n").map_err(ExperimentError::Io)?;
    file.sync_all().map_err(ExperimentError::Io)
}

#[derive(Debug, Clone)]
struct ObservedFile {
    sha256: String,
}

fn observe_file(path: &Path) -> Result<ObservedFile, ExperimentError> {
    Ok(ObservedFile {
        sha256: hash_file(path)?.0,
    })
}

fn hash_file(path: &Path) -> Result<(String, u64), ExperimentError> {
    if !path.is_absolute() {
        return Err(ExperimentError::PathNotAbsolute(path.display().to_string()));
    }
    let file = File::open(path).map_err(ExperimentError::Io)?;
    let mut reader = BufReader::new(file);
    let mut digest = Sha256::new();
    let mut bytes = 0_u64;
    let mut buffer = [0_u8; 1024 * 1024];
    loop {
        let read = reader.read(&mut buffer).map_err(ExperimentError::Io)?;
        if read == 0 {
            break;
        }
        digest.update(&buffer[..read]);
        bytes = bytes
            .checked_add(read as u64)
            .ok_or(ExperimentError::ByteCountOverflow)?;
    }
    Ok((format!("{:x}", digest.finalize()), bytes))
}

fn read_pid_file(path: &Path) -> Result<u32, ExperimentError> {
    require_absolute("server_pid_file_path", path.to_string_lossy().as_ref())?;
    let text = std::fs::read_to_string(path).map_err(ExperimentError::Io)?;
    let pid = text
        .trim()
        .parse::<u32>()
        .map_err(|_| ExperimentError::InvalidPidFile)?;
    if pid == 0 {
        return Err(ExperimentError::InvalidPidFile);
    }
    Ok(pid)
}

fn require_absolute(field: &'static str, value: &str) -> Result<(), ExperimentError> {
    if value.trim().is_empty() || value.contains('\0') || !Path::new(value).is_absolute() {
        return Err(ExperimentError::InvalidAbsolutePath(field));
    }
    Ok(())
}

fn validate_sha256(value: &str) -> Result<(), ExperimentError> {
    if value.len() != 64 || !value.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        return Err(ExperimentError::InvalidSha256(value.to_string()));
    }
    Ok(())
}

fn sha256_hex(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

/// Local experiment orchestration failure.
#[derive(Debug, Error)]
pub enum ExperimentError {
    /// Configuration schema unsupported.
    #[error("unsupported local experiment config schema {0}")]
    UnsupportedConfigSchema(u32),
    /// Required path is not absolute.
    #[error("invalid absolute path for {0}")]
    InvalidAbsolutePath(&'static str),
    /// Generic absolute-path failure.
    #[error("path is not absolute: {0}")]
    PathNotAbsolute(String),
    /// Database name/user malformed.
    #[error("database name/user must be non-empty ASCII alphanumeric/underscore identifiers")]
    InvalidDatabaseIdentity,
    /// Database policy incomplete or incompatible with MAG-DATA-008.
    #[error("database policy is incomplete or invalid")]
    InvalidDatabasePolicy,
    /// SQL mode list is not strict lexical unique order.
    #[error("sql_mode must be lexically sorted, unique and nonempty")]
    NonCanonicalSqlMode,
    /// Timeout must be nonzero.
    #[error("experiment timeout must be nonzero")]
    InvalidTimeout,
    /// Target-source paths must be supplied together.
    #[error("disclosure manifest and target request paths must be supplied together")]
    IncompleteTargetInputs,
    /// State filename invalid.
    #[error("invalid state artifact filename: {0}")]
    InvalidStateFileName(String),
    /// Prepared object no longer matches config/protocol.
    #[error("prepared experiment identity differs from current configuration/protocol")]
    PreparedIdentityMismatch,
    /// Target inputs unavailable.
    #[error("publication-authorized scoring target inputs are unavailable")]
    TargetInputsUnavailable,
    /// PID file malformed.
    #[error("isolated database PID file is missing or invalid")]
    InvalidPidFile,
    /// Stored run/binding differs from fresh verification.
    #[error("stored historical run/audit binding differs from fresh verification")]
    StoredVerificationMismatch,
    /// SHA malformed.
    #[error("invalid SHA-256: {0}")]
    InvalidSha256(String),
    /// Byte count overflow.
    #[error("file byte count overflowed u64")]
    ByteCountOverflow,
    /// Upstream authority rejected input.
    #[error("experiment stage rejected by upstream authority: {0}")]
    Upstream(String),
    /// File I/O failed.
    #[error("file I/O failure: {0}")]
    Io(#[source] std::io::Error),
    /// JSON failed.
    #[error(transparent)]
    Json(#[from] serde_json::Error),
    /// Extraction executor failed.
    #[error(transparent)]
    Extraction(#[from] symthaea_materials_oqmd_extraction_executor::ExtractionExecutorError),
}
