impl LocalExperimentConfig {
    /// Validate human-authored shape and required absolute paths.
    pub fn validate(&self) -> Result<(), ExperimentError> {
        if self.schema_version != SCHEMA_VERSION {
            return Err(ExperimentError::UnsupportedConfigSchema(self.schema_version));
        }
        for (field, path) in [
            ("run_directory", self.run_directory.as_str()),
            ("source_listing_artifact_path", self.source_listing_artifact_path.as_str()),
            ("compressed_snapshot_path", self.compressed_snapshot_path.as_str()),
            ("response_headers_path", self.response_headers_path.as_str()),
            ("decompressed_sql_path", self.decompressed_sql_path.as_str()),
            ("raw_ndjson_path", self.raw_ndjson_path.as_str()),
            ("curl_executable_path", self.curl_executable_path.as_str()),
            ("ca_bundle_path", self.ca_bundle_path.as_str()),
            ("decompressor_path", self.decompressor_path.as_str()),
            ("mysql_client_path", self.mysql_client_path.as_str()),
            ("mysql_server_path", self.mysql_server_path.as_str()),
            ("stdin_launcher_path", self.stdin_launcher_path.as_str()),
            ("file_io_launcher_path", self.file_io_launcher_path.as_str()),
            ("python_path", self.python_path.as_str()),
            ("qmpy_adapter_script_path", self.qmpy_adapter_script_path.as_str()),
            ("qmpy_artifact_manifest_path", self.qmpy_artifact_manifest_path.as_str()),
            ("execution_environment_manifest_path", self.execution_environment_manifest_path.as_str()),
            ("empty_stdin_path", self.empty_stdin_path.as_str()),
            ("unix_socket_path", self.unix_socket_path.as_str()),
            ("server_pid_file_path", self.server_pid_file_path.as_str()),
        ] {
            require_absolute(field, path)?;
        }
        if self.database_name.is_empty()
            || self.mysql_user.is_empty()
            || !self
                .database_name
                .bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
            || !self
                .mysql_user
                .bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
        {
            return Err(ExperimentError::InvalidDatabaseIdentity);
        }
        if self.expected_server_version.trim().is_empty()
            || self.expected_client_version.trim().is_empty()
            || self.character_set_server.trim().is_empty()
            || self.collation_server.trim().is_empty()
            || self.time_zone != "+00:00"
            || self.max_allowed_packet_bytes == 0
            || self.max_output_bytes == 0
        {
            return Err(ExperimentError::InvalidDatabasePolicy);
        }
        if self
            .sql_mode
            .windows(2)
            .any(|window| window[0].as_str() >= window[1].as_str())
            || self.sql_mode.iter().any(|mode| mode.trim().is_empty())
        {
            return Err(ExperimentError::NonCanonicalSqlMode);
        }
        for timeout in [
            self.acquisition_timeout_ms,
            self.decompression_timeout_ms,
            self.probe_timeout_ms,
            self.import_timeout_ms,
            self.extraction_timeout_ms,
        ] {
            if timeout == 0 {
                return Err(ExperimentError::InvalidTimeout);
            }
        }
        match (&self.disclosure_manifest_path, &self.target_requests_path) {
            (Some(manifest), Some(requests)) => {
                require_absolute("disclosure_manifest_path", manifest)?;
                require_absolute("target_requests_path", requests)?;
            }
            (None, None) => {}
            _ => return Err(ExperimentError::IncompleteTargetInputs),
        }
        Ok(())
    }

    /// Deterministic identity of the human-authored experiment configuration.
    pub fn config_sha256(&self) -> Result<String, ExperimentError> {
        self.validate()?;
        Ok(sha256_hex(&serde_json::to_vec(self)?))
    }

    /// Resolve one immutable state-artifact path under the run directory.
    pub fn state_path(&self, file_name: &str) -> Result<PathBuf, ExperimentError> {
        self.validate()?;
        if file_name.is_empty()
            || file_name.contains('/')
            || file_name.contains('\\')
            || file_name.contains("..")
        {
            return Err(ExperimentError::InvalidStateFileName(file_name.to_string()));
        }
        Ok(Path::new(&self.run_directory).join(file_name))
    }
}

/// Derived pre-side-effect profiles and tool identities.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PreparedExperiment {
    /// Prepared-object schema version.
    pub schema_version: u32,
    /// Exact human configuration identity.
    pub config_sha256: String,
    /// Frozen OQMD v1.7 Fe/Co/Zr protocol identity.
    pub protocol_sha256: String,
    /// Exact HTTPS acquisition profile.
    pub acquisition_profile: OqmdHttpsAcquisitionProfile,
    /// Exact MySQL import semantics profile.
    pub import_profile: HistoricalImportProfile,
    /// qmpy adapter version expected later.
    pub qmpy_version: String,
    /// qmpy source commit expected later.
    pub qmpy_source_commit: String,
}

impl PreparedExperiment {
    /// Validate that this prepared object still corresponds to the supplied config and local bytes.
    pub fn validate_against(
        &self,
        config: &LocalExperimentConfig,
    ) -> Result<(), ExperimentError> {
        let protocol = oqmd_v17_fe_co_zr_protocol();
        if self.schema_version != SCHEMA_VERSION
            || self.config_sha256 != config.config_sha256()?
            || self.protocol_sha256
                != protocol
                    .protocol_sha256()
                    .map_err(|error| ExperimentError::Upstream(error.to_string()))?
            || self.qmpy_version != QMPY_VERSION
            || self.qmpy_source_commit != QMPY_SOURCE_COMMIT
        {
            return Err(ExperimentError::PreparedIdentityMismatch);
        }
        self.acquisition_profile
            .validate_against(&protocol)
            .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
        self.acquisition_profile
            .validate_local_artifacts()
            .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
        self.import_profile
            .validate_against(&protocol)
            .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
        Ok(())
    }

    /// Deterministic identity of the complete preparation object.
    pub fn prepared_sha256(&self) -> Result<String, ExperimentError> {
        validate_sha256(&self.config_sha256)?;
        validate_sha256(&self.protocol_sha256)?;
        Ok(sha256_hex(&serde_json::to_vec(self)?))
    }
}

/// Human-readable readiness without granting scientific authority.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ReadinessReport {
    /// Report schema version.
    pub schema_version: u32,
    /// Exact configuration identity.
    pub config_sha256: String,
    /// All pre-side-effect tool/profile checks passed.
    pub execution_prerequisites_ready: bool,
    /// Publication target inputs were supplied and could be authority-derived.
    pub scoring_targets_ready: bool,
    /// Number of currently authorized scoring targets, zero when unavailable.
    pub authorized_target_count: u64,
    /// Descriptive notes; these never upgrade evidence authority.
    pub notes: Vec<String>,
}

/// Prepare exact acquisition/import profiles from human inputs and observed local bytes.
pub fn prepare_experiment(config: &LocalExperimentConfig) -> Result<PreparedExperiment, ExperimentError> {
    config.validate()?;
    let protocol = oqmd_v17_fe_co_zr_protocol();
    let protocol_sha = protocol
        .protocol_sha256()
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;

    let source_listing = observe_file(Path::new(&config.source_listing_artifact_path))?;
    let curl = observe_file(Path::new(&config.curl_executable_path))?;
    let ca = observe_file(Path::new(&config.ca_bundle_path))?;
    let environment = observe_file(Path::new(&config.execution_environment_manifest_path))?;
    let decompressor = RuntimeArtifact::observe(Path::new(&config.decompressor_path))
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
    let mysql_client = RuntimeArtifact::observe(Path::new(&config.mysql_client_path))
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
    let mysql_server = RuntimeArtifact::observe(Path::new(&config.mysql_server_path))
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
    let file_io_launcher = FileIoLauncherArtifact::observe(Path::new(&config.file_io_launcher_path))
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
    let stdin_launcher = StdinLauncherArtifact::observe(Path::new(&config.stdin_launcher_path))
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;

    let acquisition_profile = OqmdHttpsAcquisitionProfile {
        schema_version: 1,
        protocol_sha256: protocol_sha.clone(),
        source_listing_url: OFFICIAL_DOWNLOAD_PAGE.to_string(),
        source_listing_artifact_path: config.source_listing_artifact_path.clone(),
        source_listing_artifact_sha256: source_listing.sha256,
        requested_url: config.requested_archive_url.clone(),
        curl_executable_path: config.curl_executable_path.clone(),
        curl_executable_sha256: curl.sha256,
        ca_bundle_path: config.ca_bundle_path.clone(),
        ca_bundle_sha256: ca.sha256,
        execution_environment_manifest_path: config.execution_environment_manifest_path.clone(),
        execution_environment_manifest_sha256: environment.sha256.clone(),
        timeout_ms: config.acquisition_timeout_ms,
        max_output_bytes: config.max_output_bytes.min(4 * 1024 * 1024),
    };
    acquisition_profile
        .validate_against(&protocol)
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
    acquisition_profile
        .validate_local_artifacts()
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;

    let mut import_profile = HistoricalImportProfile {
        schema_version: 1,
        protocol_sha256: protocol_sha.clone(),
        database_engine: HistoricalDatabaseEngine::MySql,
        server_artifact_sha256: mysql_server.sha256.clone(),
        client_artifact_sha256: mysql_client.sha256.clone(),
        decompressor_artifact_sha256: decompressor.sha256.clone(),
        import_environment_manifest_sha256: environment.sha256,
        server_version: config.expected_server_version.clone(),
        client_version: config.expected_client_version.clone(),
        character_set_server: config.character_set_server.clone(),
        collation_server: config.collation_server.clone(),
        sql_mode: config.sql_mode.clone(),
        lower_case_table_names: config.lower_case_table_names,
        time_zone: config.time_zone.clone(),
        max_allowed_packet_bytes: config.max_allowed_packet_bytes,
        innodb_strict_mode: config.innodb_strict_mode,
        import_command_sha256: "0".repeat(64),
    };
    let provisional_plan = OqmdLocalImportPlan {
        schema_version: 1,
        protocol_sha256: protocol_sha.clone(),
        import_profile_sha256: "0".repeat(64),
        acquisition_receipt_sha256: "0".repeat(64),
        compressed_snapshot_path: config.compressed_snapshot_path.clone(),
        decompressed_sql_path: config.decompressed_sql_path.clone(),
        decompressor,
        file_io_launcher,
        mysql_client,
        stdin_launcher,
        mysql_server,
        server_pid: 1,
        unix_socket_path: config.unix_socket_path.clone(),
        database_name: config.database_name.clone(),
        mysql_user: config.mysql_user.clone(),
        execution_environment_manifest: RuntimeArtifact {
            path: config.execution_environment_manifest_path.clone(),
            sha256: import_profile.import_environment_manifest_sha256.clone(),
        },
        decompression_timeout_ms: config.decompression_timeout_ms,
        probe_timeout_ms: config.probe_timeout_ms,
        import_timeout_ms: config.import_timeout_ms,
        max_output_bytes: config.max_output_bytes,
    };
    import_profile.import_command_sha256 = provisional_plan
        .mysql_command_contract(&import_profile)
        .and_then(|command| command.command_sha256())
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
    import_profile
        .validate_against(&protocol)
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;

    let prepared = PreparedExperiment {
        schema_version: 1,
        config_sha256: config.config_sha256()?,
        protocol_sha256: protocol_sha,
        acquisition_profile,
        import_profile,
        qmpy_version: QMPY_VERSION.to_string(),
        qmpy_source_commit: QMPY_SOURCE_COMMIT.to_string(),
    };
    prepared.validate_against(config)?;
    prepared.prepared_sha256()?;
    Ok(prepared)
}

/// Check pre-side-effect readiness and, when supplied, publication target authority.
pub fn readiness_report(
    config: &LocalExperimentConfig,
    prepared: &PreparedExperiment,
) -> Result<ReadinessReport, ExperimentError> {
    prepared.validate_against(config)?;
    let mut notes = vec![
        "execution prerequisites validated; no acquisition/import scientific claim is implied".to_string(),
    ];
    let (scoring_targets_ready, authorized_target_count) =
        match (&config.disclosure_manifest_path, &config.target_requests_path) {
            (Some(manifest_path), Some(requests_path)) => {
                let manifest: TargetDisclosureManifest = read_json(Path::new(manifest_path))?;
                let requests: Vec<TargetConstructionRequest> = read_json(Path::new(requests_path))?;
                match build_authorized_target_set(&manifest, &requests) {
                    Ok(targets) => (true, targets.targets.len() as u64),
                    Err(error) => {
                        notes.push(format!("scoring target authority not ready: {error}"));
                        (false, 0)
                    }
                }
            }
            _ => {
                notes.push(
                    "publication structure/property source inputs are absent; historical corpus execution may proceed, scoring may not"
                        .to_string(),
                );
                (false, 0)
            }
        };
    Ok(ReadinessReport {
        schema_version: 1,
        config_sha256: config.config_sha256()?,
        execution_prerequisites_ready: true,
        scoring_targets_ready,
        authorized_target_count,
        notes,
    })
}

/// Execute HTTPS acquisition. Failed attempts are returned as evidence rather than hidden.
pub fn acquire_snapshot(
    config: &LocalExperimentConfig,
    prepared: &PreparedExperiment,
) -> Result<OqmdHttpsAcquisitionAttempt, ExperimentError> {
    prepared.validate_against(config)?;
    execute_https_acquisition(
        &oqmd_v17_fe_co_zr_protocol(),
        &prepared.acquisition_profile,
        Path::new(&config.compressed_snapshot_path),
        Path::new(&config.response_headers_path),
    )
    .map_err(|error| ExperimentError::Upstream(error.to_string()))
}

/// Promote one complete acquisition attempt into the historical acquisition receipt.
pub fn acquisition_receipt(
    config: &LocalExperimentConfig,
    prepared: &PreparedExperiment,
    attempt: &OqmdHttpsAcquisitionAttempt,
    acquired_at_utc: &str,
) -> Result<HistoricalSnapshotAcquisitionReceipt, ExperimentError> {
    prepared.validate_against(config)?;
    bind_successful_acquisition_receipt(
        &oqmd_v17_fe_co_zr_protocol(),
        &prepared.acquisition_profile,
        attempt,
        acquired_at_utc,
    )
    .map_err(|error| ExperimentError::Upstream(error.to_string()))
}

/// Construct the final import plan after the isolated server has a concrete PID.
pub fn prepare_import_plan(
    config: &LocalExperimentConfig,
    prepared: &PreparedExperiment,
    acquisition: &HistoricalSnapshotAcquisitionReceipt,
) -> Result<OqmdLocalImportPlan, ExperimentError> {
    prepared.validate_against(config)?;
    let protocol = oqmd_v17_fe_co_zr_protocol();
    acquisition
        .validate_against(&protocol)
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
    let server_pid = read_pid_file(Path::new(&config.server_pid_file_path))?;
    let plan = OqmdLocalImportPlan {
        schema_version: 1,
        protocol_sha256: prepared.protocol_sha256.clone(),
        import_profile_sha256: prepared
            .import_profile
            .profile_sha256(&protocol)
            .map_err(|error| ExperimentError::Upstream(error.to_string()))?,
        acquisition_receipt_sha256: acquisition
            .receipt_sha256(&protocol)
            .map_err(|error| ExperimentError::Upstream(error.to_string()))?,
        compressed_snapshot_path: config.compressed_snapshot_path.clone(),
        decompressed_sql_path: config.decompressed_sql_path.clone(),
        decompressor: RuntimeArtifact::observe(Path::new(&config.decompressor_path))
            .map_err(|error| ExperimentError::Upstream(error.to_string()))?,
        file_io_launcher: FileIoLauncherArtifact::observe(Path::new(&config.file_io_launcher_path))
            .map_err(|error| ExperimentError::Upstream(error.to_string()))?,
        mysql_client: RuntimeArtifact::observe(Path::new(&config.mysql_client_path))
            .map_err(|error| ExperimentError::Upstream(error.to_string()))?,
        stdin_launcher: StdinLauncherArtifact::observe(Path::new(&config.stdin_launcher_path))
            .map_err(|error| ExperimentError::Upstream(error.to_string()))?,
        mysql_server: RuntimeArtifact::observe(Path::new(&config.mysql_server_path))
            .map_err(|error| ExperimentError::Upstream(error.to_string()))?,
        server_pid,
        unix_socket_path: config.unix_socket_path.clone(),
        database_name: config.database_name.clone(),
        mysql_user: config.mysql_user.clone(),
        execution_environment_manifest: RuntimeArtifact::observe(Path::new(
            &config.execution_environment_manifest_path,
        ))
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?,
        decompression_timeout_ms: config.decompression_timeout_ms,
        probe_timeout_ms: config.probe_timeout_ms,
        import_timeout_ms: config.import_timeout_ms,
        max_output_bytes: config.max_output_bytes,
    };
    plan.validate_contract(&protocol, &prepared.import_profile, acquisition)
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
    plan.validate_local_artifacts()
        .map_err(|error| ExperimentError::Upstream(error.to_string()))?;
    Ok(plan)
}

/// Execute exact archive -> create-new SQL decompression.
pub fn decompress_snapshot(
    prepared: &PreparedExperiment,
    acquisition: &HistoricalSnapshotAcquisitionReceipt,
    plan: &OqmdLocalImportPlan,
) -> Result<OqmdDecompressionEvidence, ExperimentError> {
    execute_decompression(
        &oqmd_v17_fe_co_zr_protocol(),
        &prepared.import_profile,
        acquisition,
        plan,
    )
    .map_err(|error| ExperimentError::Upstream(error.to_string()))
}

