//! # symthaea-gravcraft — Non-Inertial Metric Perturbation Embodiment
//!
//! GravCraft is a metric-ansatz research sandbox, not a demonstrated propulsion
//! technology. The legacy simulator is explicitly a kinematic toy: it applies
//! the amplifier shift as a coordinate-acceleration shortcut and must not be
//! mistaken for a geodesic solver.
//!
//! The separate adm_reference module builds a 4D ADM metric from the shift,
//! integrates true affine geodesics using Christoffel symbols, and reconstructs
//! the Einstein-implied stress-energy tensor. This is a stronger mathematical
//! reference path, but it still does not solve the source/constraint problem,
//! establish energy-condition feasibility, or show that the field can be
//! generated by physical matter.
//!
//! ## Architecture
//!
//! - 3 gravity amplifiers, each with (amplitude, focal_distance, azimuth, elevation)
//! - The legacy simulator remains a heuristic shift-to-acceleration toy.
//! - The ADM reference path constructs g_mu_nu = ADM(alpha=1, gamma=I, beta).
//! - Full 4D geodesics and Einstein-implied stress-energy are available as a
//!   reference calculation, with explicit non-claims and finite-difference limits.
//! - Any Phi-dependent authority is a controller policy, not a physical coupling.
//!
//! ## Safety Gating
//!
//! - Green (Phi > 0.6): full metric authority, all 3 amplifiers
//! - Yellow (0.3-0.6): single amplifier, reduced amplitude
//! - Orange (0.1-0.3): flat metric only, drift
//! - Red (< 0.1): emergency metric neutralization

