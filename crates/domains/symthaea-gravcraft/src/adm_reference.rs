//! Full 3+1 ADM metric reference for the legacy three-amplifier shift ansatz.
//!
//! Coordinate chart: x^mu = (c t, x, y, z), all coordinates measured in
//! metres, G=c=1 inside the differential-geometry kernel.
//!
//! ADM line element:
//! ds^2 = -alpha^2 (c dt)^2
//!        + delta_ij (dx^i + beta^i c dt)(dx^j + beta^j c dt)
//!
//! The first reference keeps alpha=1 and gamma_ij=delta_ij, while beta^i is
//! supplied by the existing three-amplifier shaping model. Therefore:
//! g_00 = -1 + beta_i beta^i; g_0i = beta_i; g_ij = delta_ij.
//!
//! This constructs a valid Lorentzian metric for any finite shift. It does
//! NOT establish that the metric solves a desired source problem, satisfies
//! an engineered boundary condition, can be generated by physical matter, or
//! is a viable propulsion geometry. The full 4D geodesic uses Christoffel
//! symbols from the metric-geometry reference crate; no shift-as-acceleration
//! shortcut is used here.
//!
//! The stress-energy helper reconstructs T_mu_nu = G_mu_nu/(8 pi) implied by
//! this metric in geometrized units. It reports the Eulerian energy density
//! and a finite-direction sampling of the null-energy contraction. A finite
//! angular sample is diagnostic only, not a proof of any energy condition.

#![forbid(unsafe_code)]

