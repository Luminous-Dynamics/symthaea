//! Evidence-aware research records for self-healing and bioactive concrete.
//!
//! These records organize hypotheses and supportable observations. They do not
//! generate biological protocols, establish biosafety, predict structural
//! fitness, or qualify a formulation for construction.

use crate::infrastructure::{EngineeringEvidence, EvidenceKind};
use serde::{Deserialize, Serialize};
use std::collections::HashSet;

/// Intended application class for a concrete or cementitious candidate.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ConcreteApplication {
    /// Small laboratory specimen used for material-property comparisons.
    LaboratoryCoupon,
    /// Mortar intended for repair or patching.
    RepairMortar,
    /// Cast-in-place or precast structural concrete.
    StructuralConcrete,
    /// Road pavement slab or concrete pavement component.
    RoadPavement,
    /// Concrete deck on a bridge or elevated structure.
    BridgeDeck,
    /// Precast railway sleeper or tie.
    RailwaySleeper,
    /// Concrete supporting a slab-track railway.
    SlabTrack,
    /// Culvert, drainage channel, or water-management structure.
    DrainageStructure,
    /// Retaining wall or related geotechnical concrete component.
    RetainingStructure,
    /// Another explicitly documented application.
    Other,
}

/// Candidate healing or damage-prevention mechanism.
///
/// The mechanism is a classification, not evidence that the mechanism works.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ConcreteHealingMechanism {
    /// Natural healing from continued hydration or mineral precipitation.
    Autogenous,
    /// Internal curing intended primarily to reduce early-age cracking.
    InternalCuring,
    /// Capsules or admixtures containing non-living healing agents.
    NonLivingEncapsulated,
    /// A viable biological system intended to induce localized mineralization.
    MicrobialMineralization,
    /// Fibers combined with mineral or healing-agent systems.
    FiberMineralHybrid,
    /// Another mechanism that must be explained in the candidate record.
    Other,
}

/// Evidence maturity claimed by the candidate submitter.
///
/// Validation checks the presence of records consistent with the declared
/// stage; it does not authenticate those records or certify their conclusions.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ConcreteEvidenceStage {
    /// Research hypothesis with traceable rationale/source evidence.
    Hypothesis,
    /// Relevant literature is recorded; the candidate itself may be untested.
    LiteratureSupported,
    /// At least one property outcome has been measured in a laboratory test.
    LabMeasured,
    /// More than one laboratory evidence source and an independent review are recorded.
    IndependentlyReplicated,
    /// At least one physical field-measurement outcome is recorded.
    FieldMonitored,
}

/// Whether an outcome is a physical observation or a model-generated estimate.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ConcreteOutcomeOrigin {
    /// Measurement derived from a specimen or physical asset.
    Measured,
    /// Estimate generated by an identified model or simulation.
    Predicted,
}

/// A separately reported outcome metric; do not collapse all into one score.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ConcreteOutcomeMetric {
    /// Fraction of initial crack width that closed, between zero and one.
    CrackWidthClosureFraction,
    /// Depth of water penetration in millimetres.
    WaterIngressDepthMm,
    /// Measured compressive strength in megapascals.
    CompressiveStrengthMpa,
    /// Measured flexural strength in megapascals.
    FlexuralStrengthMpa,
    /// Elastic modulus in gigapascals.
    ElasticModulusGpa,
    /// Length change in microstrain; either sign can occur.
    LengthChangeMicrostrain,
}

impl ConcreteOutcomeMetric {
    /// Canonical unit string required for this metric.
    pub fn unit(self) -> &'static str {
        match self {
            Self::CrackWidthClosureFraction => "fraction",
            Self::WaterIngressDepthMm => "mm",
            Self::CompressiveStrengthMpa | Self::FlexuralStrengthMpa => "MPa",
            Self::ElasticModulusGpa => "GPa",
            Self::LengthChangeMicrostrain => "microstrain",
        }
    }
}

/// A single, explicitly unit-tagged outcome tied to a source record.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ConcreteOutcome {
    /// Metric being reported.
    pub metric: ConcreteOutcomeMetric,
    /// Numeric result in the metric's canonical unit.
    pub value: f64,
    /// Unit string; must exactly match the selected metric's canonical unit.
    pub unit: String,
    /// Stable evidence identifier that supports this outcome.
    pub evidence_id: String,
    /// Measured or predicted origin; simulation must never be labelled measured.
    pub origin: ConcreteOutcomeOrigin,
    /// Number of physical specimens represented by a measured result.
    pub specimen_count: Option<u32>,
    /// Required model identifier for a predicted result.
    pub model_id: Option<String>,
    /// Optional absolute uncertainty in the same unit as the result.
    pub absolute_uncertainty: Option<f64>,
}

/// Declared biological status of a candidate formulation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ConcreteBiologicalStatus {
    /// No viable organism is deliberately present.
    NonLiving,
    /// A viable, non-engineered organism is deliberately present.
    ViableNonEngineered,
    /// A viable engineered organism is deliberately present.
    ViableEngineered,
}

/// Evidence-contract errors for a concrete candidate.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LivingConcreteValidationError {
    /// A required text field is blank.
    EmptyField { field: &'static str },
    /// An outcome or uncertainty contains NaN or infinity.
    NonFinite { field: &'static str },
    /// A value violates a basic metric-domain constraint.
    OutOfRange { field: &'static str },
    /// No source/evidence records were supplied.
    MissingEvidence,
    /// Evidence identifiers are duplicated.
    DuplicateEvidenceId,
    /// An outcome refers to an unknown evidence identifier.
    UnresolvedOutcomeEvidence,
    /// Unit string does not match the selected metric.
    UnitMismatch,
    /// A biological candidate lacks a strain identity.
    MissingStrainIdentity,
    /// A biological candidate lacks a biosafety assessment evidence record.
    MissingBiosafetyAssessment,
    /// Microbial mineralization was declared without a viable organism.
    BiologicalMechanismRequiresOrganism,
    /// Declared evidence stage is not supported by the supplied record types.
    StageEvidenceMissing,
    /// Predicted outcome lacks a model ID or does not reference simulation evidence.
    PredictedOutcomeMissingModel,
    /// Measured outcome is sourced only to synthetic simulation evidence.
    MeasuredOutcomeUsesSimulation,
    /// A measured outcome does not declare a positive specimen count.
    MissingSpecimenCount,
}

/// Research candidate for a self-healing or bioactive concrete formulation.
///
/// The candidate stores identities and separately reported outcomes rather
/// than an opaque "healing score". Component proportions, handling procedures,
/// or biological protocols belong in separately controlled, rights-cleared
/// records and are deliberately not generated by this module.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct LivingConcreteCandidate {
    /// Stable non-empty candidate identifier.
    pub candidate_id: String,
    /// Immutable version string for the candidate specification.
    pub version: String,
    /// Intended application class.
    pub application: ConcreteApplication,
    /// Declared healing/damage-prevention mechanism.
    pub mechanism: ConcreteHealingMechanism,
    /// Whether this candidate deliberately contains a viable biological system.
    pub biological_status: ConcreteBiologicalStatus,
    /// Strain or curated organism reference when biology is present.
    pub strain_identity: Option<String>,
    /// Evidence ID for a documented biosafety assessment when biology is present.
    pub biosafety_evidence_id: Option<String>,
    /// Declared evidence maturity; not a certification or quality score.
    pub evidence_stage: ConcreteEvidenceStage,
    /// Source records for claims, measurements, predictions and reviews.
    pub evidence: Vec<EngineeringEvidence>,
    /// Independent outcomes; predictions and measurements remain distinct.
    pub outcomes: Vec<ConcreteOutcome>,
}

impl LivingConcreteCandidate {
    /// Validate record integrity and that the declared stage has supporting records.
    ///
    /// A successful result does not establish structural safety, code compliance,
    /// environmental safety, economic advantage, or field readiness.
    pub fn validate(&self) -> Result<(), Vec<LivingConcreteValidationError>> {
        let mut errors = Vec::new();
        require_non_empty(&self.candidate_id, "candidate_id", &mut errors);
        require_non_empty(&self.version, "version", &mut errors);

        if self.evidence.is_empty() {
            errors.push(LivingConcreteValidationError::MissingEvidence);
        }

        let mut evidence_ids = HashSet::with_capacity(self.evidence.len());
        for item in &self.evidence {
            for error in item.validate() {
                match error {
                    crate::infrastructure::ValidationError::EmptyField { field } => {
                        errors.push(LivingConcreteValidationError::EmptyField { field });
                    }
                    crate::infrastructure::ValidationError::NonFinite { field } => {
                        errors.push(LivingConcreteValidationError::NonFinite { field });
                    }
                    crate::infrastructure::ValidationError::InvalidDigest => {
                        errors.push(LivingConcreteValidationError::OutOfRange {
                            field: "artifact_digest_hex",
                        });
                    }
                    _ => {}
                }
            }
            if !evidence_ids.insert(item.evidence_id.as_str()) {
                errors.push(LivingConcreteValidationError::DuplicateEvidenceId);
            }
        }

        if self.mechanism == ConcreteHealingMechanism::MicrobialMineralization
            && self.biological_status == ConcreteBiologicalStatus::NonLiving
        {
            errors.push(LivingConcreteValidationError::BiologicalMechanismRequiresOrganism);
        }

        match self.biological_status {
            ConcreteBiologicalStatus::NonLiving => {
                if self.strain_identity.is_some() || self.biosafety_evidence_id.is_some() {
                    errors.push(LivingConcreteValidationError::OutOfRange {
                        field: "biological_metadata_for_nonliving_candidate",
                    });
                }
            }
            ConcreteBiologicalStatus::ViableNonEngineered
            | ConcreteBiologicalStatus::ViableEngineered => {
                match self.strain_identity.as_deref() {
                    Some(identity) if !identity.trim().is_empty() => {}
                    _ => errors.push(LivingConcreteValidationError::MissingStrainIdentity),
                }
                match self.biosafety_evidence_id.as_deref() {
                    Some(id)
                        if self.evidence.iter().any(|item| {
                            item.evidence_id == id && item.kind == EvidenceKind::BiosafetyAssessment
                        }) => {}
                    _ => errors.push(LivingConcreteValidationError::MissingBiosafetyAssessment),
                }
                if self.mechanism != ConcreteHealingMechanism::MicrobialMineralization
                    && self.mechanism != ConcreteHealingMechanism::Other
                {
                    errors.push(LivingConcreteValidationError::OutOfRange {
                        field: "biological_mechanism_mismatch",
                    });
                }
            }
        }

        for outcome in &self.outcomes {
            require_non_empty(&outcome.evidence_id, "outcome.evidence_id", &mut errors);
            if !evidence_ids.contains(outcome.evidence_id.as_str()) {
                errors.push(LivingConcreteValidationError::UnresolvedOutcomeEvidence);
                continue;
            }
            if !outcome.value.is_finite() {
                errors.push(LivingConcreteValidationError::NonFinite { field: "outcome.value" });
            }
            if outcome.unit != outcome.metric.unit() {
                errors.push(LivingConcreteValidationError::UnitMismatch);
            }
            if let Some(uncertainty) = outcome.absolute_uncertainty {
                if !uncertainty.is_finite() {
                    errors.push(LivingConcreteValidationError::NonFinite {
                        field: "outcome.absolute_uncertainty",
                    });
                } else if uncertainty < 0.0 {
                    errors.push(LivingConcreteValidationError::OutOfRange {
                        field: "outcome.absolute_uncertainty",
                    });
                }
            }

            match outcome.metric {
                ConcreteOutcomeMetric::CrackWidthClosureFraction => {
                    if outcome.value.is_finite() && !(0.0..=1.0).contains(&outcome.value) {
                        errors.push(LivingConcreteValidationError::OutOfRange {
                            field: "outcome.crack_width_closure_fraction",
                        });
                    }
                }
                ConcreteOutcomeMetric::WaterIngressDepthMm => {
                    if outcome.value.is_finite() && outcome.value < 0.0 {
                        errors.push(LivingConcreteValidationError::OutOfRange {
                            field: "outcome.water_ingress_depth_mm",
                        });
                    }
                }
                ConcreteOutcomeMetric::CompressiveStrengthMpa
                | ConcreteOutcomeMetric::FlexuralStrengthMpa
                | ConcreteOutcomeMetric::ElasticModulusGpa => {
                    if outcome.value.is_finite() && outcome.value <= 0.0 {
                        errors.push(LivingConcreteValidationError::OutOfRange {
                            field: "outcome.positive_mechanical_property",
                        });
                    }
                }
                ConcreteOutcomeMetric::LengthChangeMicrostrain => {}
            }

            let source = self.evidence.iter().find(|item| item.evidence_id == outcome.evidence_id);
            match outcome.origin {
                ConcreteOutcomeOrigin::Measured => {
                    if outcome.specimen_count.unwrap_or(0) == 0 {
                        errors.push(LivingConcreteValidationError::MissingSpecimenCount);
                    }
                    if source.is_some_and(|item| item.kind == EvidenceKind::SyntheticSimulation) {
                        errors.push(LivingConcreteValidationError::MeasuredOutcomeUsesSimulation);
                    }
                }
                ConcreteOutcomeOrigin::Predicted => {
                    if outcome.model_id.as_deref().is_none_or(|id| id.trim().is_empty())
                        || !source.is_some_and(|item| item.kind == EvidenceKind::SyntheticSimulation)
                    {
                        errors.push(LivingConcreteValidationError::PredictedOutcomeMissingModel);
                    }
                }
            }
        }

        match self.evidence_stage {
            ConcreteEvidenceStage::Hypothesis => {}
            ConcreteEvidenceStage::LiteratureSupported => {
                if !self.evidence.iter().any(|item| item.kind == EvidenceKind::Literature) {
                    errors.push(LivingConcreteValidationError::StageEvidenceMissing);
                }
            }
            ConcreteEvidenceStage::LabMeasured => {
                if !self.evidence.iter().any(|item| item.kind == EvidenceKind::LaboratoryTest)
                    || !self.outcomes.iter().any(|outcome| {
                        outcome.origin == ConcreteOutcomeOrigin::Measured
                            && self.evidence.iter().any(|item| {
                                item.evidence_id == outcome.evidence_id
                                    && item.kind == EvidenceKind::LaboratoryTest
                            })
                    })
                {
                    errors.push(LivingConcreteValidationError::StageEvidenceMissing);
                }
            }
            ConcreteEvidenceStage::IndependentlyReplicated => {
                let lab_sources: HashSet<&str> = self
                    .evidence
                    .iter()
                    .filter(|item| item.kind == EvidenceKind::LaboratoryTest)
                    .map(|item| item.source_locator.as_str())
                    .collect();
                if lab_sources.len() < 2
                    || !self.evidence.iter().any(|item| item.kind == EvidenceKind::IndependentReview)
                    || !self.outcomes.iter().any(|outcome| {
                        outcome.origin == ConcreteOutcomeOrigin::Measured
                            && self.evidence.iter().any(|item| {
                                item.evidence_id == outcome.evidence_id
                                    && item.kind == EvidenceKind::LaboratoryTest
                            })
                    })
                {
                    errors.push(LivingConcreteValidationError::StageEvidenceMissing);
                }
            }
            ConcreteEvidenceStage::FieldMonitored => {
                let lab_sources: HashSet<&str> = self
                    .evidence
                    .iter()
                    .filter(|item| item.kind == EvidenceKind::LaboratoryTest)
                    .map(|item| item.source_locator.as_str())
                    .collect();
                let has_field_outcome = self.outcomes.iter().any(|outcome| {
                    outcome.origin == ConcreteOutcomeOrigin::Measured
                        && self.evidence.iter().any(|item| {
                            item.evidence_id == outcome.evidence_id
                                && item.kind == EvidenceKind::FieldMeasurement
                        })
                });
                if lab_sources.len() < 2
                    || !self.evidence.iter().any(|item| item.kind == EvidenceKind::IndependentReview)
                    || !self.evidence.iter().any(|item| item.kind == EvidenceKind::FieldMeasurement)
                    || !has_field_outcome
                {
                    errors.push(LivingConcreteValidationError::StageEvidenceMissing);
                }
            }
        }

        if errors.is_empty() { Ok(()) } else { Err(errors) }
    }
}

fn require_non_empty(
    value: &str,
    field: &'static str,
    errors: &mut Vec<LivingConcreteValidationError>,
) {
    if value.trim().is_empty() {
        errors.push(LivingConcreteValidationError::EmptyField { field });
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn evidence(id: &str, kind: EvidenceKind, source: &str) -> EngineeringEvidence {
        EngineeringEvidence {
            evidence_id: id.to_string(),
            kind,
            source_locator: source.to_string(),
            method_id: "declared-method-v1".to_string(),
            artifact_digest_hex: Some("b".repeat(64)),
        }
    }

    fn candidate() -> LivingConcreteCandidate {
        LivingConcreteCandidate {
            candidate_id: "candidate-autogenous-001".to_string(),
            version: "1".to_string(),
            application: ConcreteApplication::LaboratoryCoupon,
            mechanism: ConcreteHealingMechanism::Autogenous,
            biological_status: ConcreteBiologicalStatus::NonLiving,
            strain_identity: None,
            biosafety_evidence_id: None,
            evidence_stage: ConcreteEvidenceStage::LiteratureSupported,
            evidence: vec![evidence(
                "literature-1",
                EvidenceKind::Literature,
                "https://example.org/review",
            )],
            outcomes: vec![],
        }
    }

    #[test]
    fn literature_hypothesis_is_well_formed_not_qualified() {
        assert!(candidate().validate().is_ok());
    }

    #[test]
    fn unit_mismatch_and_out_of_range_healing_fraction_fail() {
        let mut sample = candidate();
        sample.evidence.push(evidence("lab-1", EvidenceKind::LaboratoryTest, "lab-record:1"));
        sample.evidence_stage = ConcreteEvidenceStage::LabMeasured;
        sample.outcomes.push(ConcreteOutcome {
            metric: ConcreteOutcomeMetric::CrackWidthClosureFraction,
            value: 1.2,
            unit: "percent".to_string(),
            evidence_id: "lab-1".to_string(),
            origin: ConcreteOutcomeOrigin::Measured,
            specimen_count: Some(3),
            model_id: None,
            absolute_uncertainty: Some(0.1),
        });

        let errors = sample.validate().expect_err("invalid outcome should fail");
        assert!(errors.contains(&LivingConcreteValidationError::UnitMismatch));
        assert!(errors.contains(&LivingConcreteValidationError::OutOfRange {
            field: "outcome.crack_width_closure_fraction"
        }));
    }

    #[test]
    fn simulation_output_cannot_be_labeled_measured() {
        let mut sample = candidate();
        sample.evidence.push(evidence("sim-1", EvidenceKind::SyntheticSimulation, "run:synthetic-1"));
        sample.outcomes.push(ConcreteOutcome {
            metric: ConcreteOutcomeMetric::CompressiveStrengthMpa,
            value: 42.0,
            unit: "MPa".to_string(),
            evidence_id: "sim-1".to_string(),
            origin: ConcreteOutcomeOrigin::Measured,
            specimen_count: Some(4),
            model_id: None,
            absolute_uncertainty: None,
        });

        assert!(sample
            .validate()
            .expect_err("simulation is not a measurement")
            .contains(&LivingConcreteValidationError::MeasuredOutcomeUsesSimulation));
    }

    #[test]
    fn predicted_outcome_requires_model_and_simulation_record() {
        let mut sample = candidate();
        sample.evidence.push(evidence("sim-1", EvidenceKind::SyntheticSimulation, "run:synthetic-2"));
        sample.outcomes.push(ConcreteOutcome {
            metric: ConcreteOutcomeMetric::WaterIngressDepthMm,
            value: 2.1,
            unit: "mm".to_string(),
            evidence_id: "sim-1".to_string(),
            origin: ConcreteOutcomeOrigin::Predicted,
            specimen_count: None,
            model_id: None,
            absolute_uncertainty: Some(0.2),
        });

        assert!(sample
            .validate()
            .expect_err("prediction needs model identity")
            .contains(&LivingConcreteValidationError::PredictedOutcomeMissingModel));
    }

    #[test]
    fn biological_candidate_requires_strain_and_biosafety_evidence() {
        let mut sample = candidate();
        sample.mechanism = ConcreteHealingMechanism::MicrobialMineralization;
        sample.biological_status = ConcreteBiologicalStatus::ViableNonEngineered;

        let errors = sample.validate().expect_err("bio candidate missing risk records should fail");
        assert!(errors.contains(&LivingConcreteValidationError::MissingStrainIdentity));
        assert!(errors.contains(&LivingConcreteValidationError::MissingBiosafetyAssessment));
    }

    #[test]
    fn microbial_mechanism_cannot_be_declared_nonliving() {
        let mut sample = candidate();
        sample.mechanism = ConcreteHealingMechanism::MicrobialMineralization;
        assert!(sample
            .validate()
            .expect_err("microbial mechanism requires viable organism declaration")
            .contains(&LivingConcreteValidationError::BiologicalMechanismRequiresOrganism));
    }

    #[test]
    fn field_monitored_stage_requires_prior_lab_evidence_and_review() {
        let mut sample = candidate();
        sample.evidence_stage = ConcreteEvidenceStage::FieldMonitored;
        sample.evidence.push(evidence(
            "field-1",
            EvidenceKind::FieldMeasurement,
            "field-record:1",
        ));
        sample.outcomes.push(ConcreteOutcome {
            metric: ConcreteOutcomeMetric::WaterIngressDepthMm,
            value: 2.0,
            unit: "mm".to_string(),
            evidence_id: "field-1".to_string(),
            origin: ConcreteOutcomeOrigin::Measured,
            specimen_count: Some(1),
            model_id: None,
            absolute_uncertainty: Some(0.2),
        });

        assert!(sample
            .validate()
            .expect_err("field stage should require prior lab/independent review")
            .contains(&LivingConcreteValidationError::StageEvidenceMissing));
    }

    #[test]
    fn independent_replication_requires_distinct_lab_sources_and_review() {
        let mut sample = candidate();
        sample.evidence_stage = ConcreteEvidenceStage::IndependentlyReplicated;
        sample.evidence.extend([
            evidence("lab-1", EvidenceKind::LaboratoryTest, "lab-A:record-1"),
            evidence("lab-2", EvidenceKind::LaboratoryTest, "lab-B:record-2"),
        ]);
        sample.evidence.push(evidence("review-1", EvidenceKind::IndependentReview, "review-record:1"));
        sample.outcomes.extend([
            ConcreteOutcome {
                metric: ConcreteOutcomeMetric::CompressiveStrengthMpa,
                value: 40.0,
                unit: "MPa".to_string(),
                evidence_id: "lab-1".to_string(),
                origin: ConcreteOutcomeOrigin::Measured,
                specimen_count: Some(3),
                model_id: None,
                absolute_uncertainty: Some(1.0),
            },
            ConcreteOutcome {
                metric: ConcreteOutcomeMetric::CompressiveStrengthMpa,
                value: 39.0,
                unit: "MPa".to_string(),
                evidence_id: "lab-2".to_string(),
                origin: ConcreteOutcomeOrigin::Measured,
                specimen_count: Some(3),
                model_id: None,
                absolute_uncertainty: Some(1.2),
            },
        ]);

        assert!(sample.validate().is_ok());
    }
}
