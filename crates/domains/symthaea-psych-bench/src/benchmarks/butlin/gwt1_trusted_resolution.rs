//! Candidate generation for the final trusted GWT-1 resolved artifact.
//!
//! This module deliberately separates **deterministic resolution bytes** from
//! **final public authority**. The function below may be called by a trusted
//! workflow to reconstruct direct evidence, cryptographically verify the causal
//! promotion package through the crate-internal verifier, resolve the V2
//! multi-lineage view, and classify its diagnostic causal disposition.
//!
//! The returned value is still only a *candidate*. It becomes authoritative
//! only when a separately reviewed final-resolution workflow packages these
//! bytes together with independently verified upstream provenance and attests
//! the complete deterministic archive. This keeps the opaque promotion token
//! constructor crate-internal while avoiding a second, parallel resolution path.

use std::fs;
use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::harness::BenchmarkConfig;

use super::gwt1_causal_verified_promotion::{
    Gwt1CausalPromotionVerificationErrorV1, verify_gwt1_causal_promotion_package_v1,
};
use super::gwt1_end_to_end::Gwt1EndToEndEvidenceV1;
use super::gwt1_evidence_disposition::{
    Gwt1EvidenceDispositionErrorV1, Gwt1EvidenceDispositionSummaryV1,
    classify_gwt1_evidence_disposition_v1,
};
use super::gwt1_evidence_envelope::{
    Gwt1EvidenceEnvelopeResolutionV1, Gwt1EvidenceEnvelopeV1,
    resolve_gwt1_evidence_envelope_v1,
};
use super::indicators::ButlinIndicatorSuite;
use super::report::{ButlinIndicatorReport, EvidenceOutcome, SupportTier};
use super::resolution_view_v2::{
    ButlinResolvedEvidenceViewV2, EvidenceResolutionViewErrorV2,
    resolve_gwt1_causal_evidence_view_v2,
};

pub const GWT1_TRUSTED_RESOLUTION_CANDIDATE_SCHEMA_V1: &str =
    "butlin-gwt1-trusted-resolution-candidate-v1";

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Gwt1TrustedResolutionCandidateV1 {
    pub schema: String,
    /// Canonical architecture-only report generated by the trusted resolution
    /// revision with `BenchmarkConfig::default()` and no runtime input.
    pub base_report: ButlinIndicatorReport,
    /// Non-destructive direct + causal evidence lineage.
    pub resolved_view: ButlinResolvedEvidenceViewV2,
    /// Diagnostic state that prevents a retained `Observed` support floor from
    /// hiding a causal null, contradiction, or inconclusive result.
    pub disposition: Gwt1EvidenceDispositionSummaryV1,
}

#[derive(Debug)]
pub enum Gwt1TrustedResolutionCandidateErrorV1 {
    Io(String),
    Json { path: String, error: String },
    DirectResolutionMismatch,
    CanonicalBaseMissingGwt1,
    CanonicalBaseDuplicateGwt1,
    CanonicalBaseGwt1NotArchitectural { observed: EvidenceOutcome },
    PromotionVerification(Gwt1CausalPromotionVerificationErrorV1),
    Resolution(EvidenceResolutionViewErrorV2),
    Disposition(Gwt1EvidenceDispositionErrorV1),
}

impl std::fmt::Display for Gwt1TrustedResolutionCandidateErrorV1 {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Io(error) => write!(f, "I/O failure: {error}"),
            Self::Json { path, error } => write!(f, "invalid JSON at {path:?}: {error}"),
            Self::DirectResolutionMismatch => write!(
                f,
                "persisted direct GWT-1 resolution differs from fresh recomputation"
            ),
            Self::CanonicalBaseMissingGwt1 => {
                write!(f, "canonical base report is missing GWT-1")
            }
            Self::CanonicalBaseDuplicateGwt1 => {
                write!(f, "canonical base report contains duplicate GWT-1 entries")
            }
            Self::CanonicalBaseGwt1NotArchitectural { observed } => write!(
                f,
                "canonical GWT-1 base must be ArchitecturalOnly, observed {observed:?}"
            ),
            Self::PromotionVerification(error) => {
                write!(f, "promotion verification failed: {error}")
            }
            Self::Resolution(error) => write!(f, "V2 resolution failed: {error}"),
            Self::Disposition(error) => write!(f, "disposition classification failed: {error}"),
        }
    }
}

impl std::error::Error for Gwt1TrustedResolutionCandidateErrorV1 {}

impl From<Gwt1CausalPromotionVerificationErrorV1>
    for Gwt1TrustedResolutionCandidateErrorV1
{
    fn from(value: Gwt1CausalPromotionVerificationErrorV1) -> Self {
        Self::PromotionVerification(value)
    }
}

impl From<EvidenceResolutionViewErrorV2> for Gwt1TrustedResolutionCandidateErrorV1 {
    fn from(value: EvidenceResolutionViewErrorV2) -> Self {
        Self::Resolution(value)
    }
}

impl From<Gwt1EvidenceDispositionErrorV1> for Gwt1TrustedResolutionCandidateErrorV1 {
    fn from(value: Gwt1EvidenceDispositionErrorV1) -> Self {
        Self::Disposition(value)
    }
}

fn read_json<T: for<'de> Deserialize<'de>>(
    path: &Path,
) -> Result<T, Gwt1TrustedResolutionCandidateErrorV1> {
    let bytes = fs::read(path)
        .map_err(|error| Gwt1TrustedResolutionCandidateErrorV1::Io(error.to_string()))?;
    serde_json::from_slice(&bytes).map_err(|error| {
        Gwt1TrustedResolutionCandidateErrorV1::Json {
            path: path.display().to_string(),
            error: error.to_string(),
        }
    })
}

fn load_direct_evidence(
    evidence_dir: &Path,
) -> Result<Gwt1EndToEndEvidenceV1, Gwt1TrustedResolutionCandidateErrorV1> {
    let raw_observation_bytes = fs::read(evidence_dir.join("raw_observations.json"))
        .map_err(|error| Gwt1TrustedResolutionCandidateErrorV1::Io(error.to_string()))?;
    let envelope: Gwt1EvidenceEnvelopeV1 =
        read_json(&evidence_dir.join("evidence_envelope.json"))?;
    let resolution: Gwt1EvidenceEnvelopeResolutionV1 =
        read_json(&evidence_dir.join("resolution.json"))?;

    let recomputed = resolve_gwt1_evidence_envelope_v1(&envelope, &raw_observation_bytes);
    if recomputed != resolution {
        return Err(Gwt1TrustedResolutionCandidateErrorV1::DirectResolutionMismatch);
    }

    Ok(Gwt1EndToEndEvidenceV1 {
        raw_observation_bytes,
        envelope,
        resolution,
    })
}

fn canonical_base_report()
-> Result<ButlinIndicatorReport, Gwt1TrustedResolutionCandidateErrorV1> {
    let report = ButlinIndicatorSuite::evaluate(&BenchmarkConfig::default());
    let mut gwt1 = report
        .indicators
        .iter()
        .filter(|indicator| indicator.id == "GWT-1");
    let observed = gwt1
        .next()
        .ok_or(Gwt1TrustedResolutionCandidateErrorV1::CanonicalBaseMissingGwt1)?
        .outcome;
    if gwt1.next().is_some() {
        return Err(Gwt1TrustedResolutionCandidateErrorV1::CanonicalBaseDuplicateGwt1);
    }
    if observed != EvidenceOutcome::Supported(SupportTier::ArchitecturalOnly) {
        return Err(
            Gwt1TrustedResolutionCandidateErrorV1::CanonicalBaseGwt1NotArchitectural {
                observed,
            },
        );
    }
    Ok(report)
}

/// Generate deterministic final-resolution candidate data from already-persisted
/// direct evidence and a cryptographically verified causal promotion package.
///
/// This is intentionally public so the package binary can invoke it. Calling it
/// outside the reviewed final workflow does **not** mint public/reporting
/// authority: the returned value has no opaque authority token and is not an
/// attestation. Final authority belongs to the separately attested archive
/// produced by the dedicated workflow.
pub fn generate_gwt1_trusted_resolution_candidate_v1(
    direct_evidence_dir: &Path,
    promotion_capsule_path: &Path,
    promotion_attestation_bundle_path: &Path,
    gh_executable: &Path,
    sha256sum_executable: &Path,
    gh_config_dir: &Path,
) -> Result<Gwt1TrustedResolutionCandidateV1, Gwt1TrustedResolutionCandidateErrorV1> {
    let direct_evidence = load_direct_evidence(direct_evidence_dir)?;
    let verified_causal = verify_gwt1_causal_promotion_package_v1(
        promotion_capsule_path,
        promotion_attestation_bundle_path,
        gh_executable,
        sha256sum_executable,
        gh_config_dir,
    )?;

    let base_report = canonical_base_report()?;
    let resolved_view =
        resolve_gwt1_causal_evidence_view_v2(&base_report, &direct_evidence, &verified_causal)?;
    let disposition = classify_gwt1_evidence_disposition_v1(&resolved_view)?;

    Ok(Gwt1TrustedResolutionCandidateV1 {
        schema: GWT1_TRUSTED_RESOLUTION_CANDIDATE_SCHEMA_V1.to_string(),
        base_report,
        resolved_view,
        disposition,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn canonical_base_has_exactly_one_architectural_gwt1() {
        let report = canonical_base_report().expect("canonical Butlin base");
        let gwt1: Vec<_> = report
            .indicators
            .iter()
            .filter(|indicator| indicator.id == "GWT-1")
            .collect();
        assert_eq!(gwt1.len(), 1);
        assert_eq!(
            gwt1[0].outcome,
            EvidenceOutcome::Supported(SupportTier::ArchitecturalOnly)
        );
    }

    #[test]
    fn candidate_schema_is_frozen() {
        assert_eq!(
            GWT1_TRUSTED_RESOLUTION_CANDIDATE_SCHEMA_V1,
            "butlin-gwt1-trusted-resolution-candidate-v1"
        );
    }

    #[test]
    fn io_error_is_human_readable() {
        let error = Gwt1TrustedResolutionCandidateErrorV1::Io("missing".into());
        assert!(error.to_string().contains("missing"));
    }
}
