//! Batch-level observation accounting for MIS candidate-score experiments.
//!
//! A physical circuit shot and a candidate observation are different units: one
//! measured sample can update several observables/candidate sufficient statistics.
//! This module preserves the joint outcome vector and separately counts physical
//! shots, per-candidate observations, and estimated cost units. It does not execute
//! circuits or attest that caller-supplied device/context labels are truthful.

use core::fmt;

/// Provenance class for a measurement batch; classes must not be silently merged.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum MisMeasurementEvidenceClass {
    /// Explicitly synthetic sample stream generated by a test harness.
    Synthetic,
    /// Sample outcomes replayed from an identified classical result artifact.
    ClassicalReplay,
    /// Ideal circuit simulation with no hardware-noise claim.
    IdealSimulation,
    /// Tensor-network or related approximate/exact simulator result.
    TensorNetworkSimulation,
    /// Observation returned by a physical quantum device.
    PhysicalQpu,
}

impl MisMeasurementEvidenceClass {
    /// Stable label suitable for a run manifest or machine-readable report.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Synthetic => "synthetic",
            Self::ClassicalReplay => "classical-replay",
            Self::IdealSimulation => "ideal-simulation",
            Self::TensorNetworkSimulation => "tensor-network-simulation",
            Self::PhysicalQpu => "physical-qpu",
        }
    }
}

/// Context and accounting contract for one identical-circuit measurement batch.
///
/// The cost figures are in a caller-defined unit named by `cost_model_id`; this type
/// cannot determine whether a source's costs are measured, estimated, or amortized.
/// Setup cost is charged once for a non-empty batch, and per-shot cost is charged once
/// for each physical shot regardless of how many candidate observables it updates.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct MisMeasurementBatchSpec {
    batch_id: String,
    circuit_context_sha256: [u8; 32],
    execution_profile_id: String,
    measurement_basis_id: String,
    evidence_class: MisMeasurementEvidenceClass,
    candidate_vertices: Vec<usize>,
    cost_model_id: String,
    setup_cost_units: u64,
    per_shot_cost_units: u64,
}

impl MisMeasurementBatchSpec {
    /// Validate and construct a batch contract.
    ///
    /// Candidate vertex IDs are sorted to make outcome ordering and reports canonical.
    /// Duplicate candidate IDs are rejected, because an observation map must not update
    /// the same candidate twice from one physical shot.
    #[allow(clippy::too_many_arguments)]
    pub fn new(
        batch_id: impl Into<String>,
        circuit_context_sha256: [u8; 32],
        execution_profile_id: impl Into<String>,
        measurement_basis_id: impl Into<String>,
        evidence_class: MisMeasurementEvidenceClass,
        mut candidate_vertices: Vec<usize>,
        cost_model_id: impl Into<String>,
        setup_cost_units: u64,
        per_shot_cost_units: u64,
    ) -> Result<Self, MisMeasurementBatchError> {
        let batch_id = batch_id.into();
        let execution_profile_id = execution_profile_id.into();
        let measurement_basis_id = measurement_basis_id.into();
        let cost_model_id = cost_model_id.into();
        for (field, value) in [
            ("batch_id", batch_id.as_str()),
            ("execution_profile_id", execution_profile_id.as_str()),
            ("measurement_basis_id", measurement_basis_id.as_str()),
            ("cost_model_id", cost_model_id.as_str()),
        ] {
            validate_identifier(field, value)?;
        }
        if candidate_vertices.is_empty() {
            return Err(MisMeasurementBatchError::EmptyCandidateSet);
        }
        candidate_vertices.sort_unstable();
        for pair in candidate_vertices.windows(2) {
            if pair[0] == pair[1] {
                return Err(MisMeasurementBatchError::DuplicateCandidate {
                    vertex: pair[0],
                });
            }
        }
        Ok(Self {
            batch_id,
            circuit_context_sha256,
            execution_profile_id,
            measurement_basis_id,
            evidence_class,
            candidate_vertices,
            cost_model_id,
            setup_cost_units,
            per_shot_cost_units,
        })
    }

    /// Stable batch identifier.
    pub fn batch_id(&self) -> &str {
        &self.batch_id
    }

    /// Caller-supplied digest binding this batch to circuit/model/parameter context.
    pub fn circuit_context_sha256(&self) -> [u8; 32] {
        self.circuit_context_sha256
    }

    /// Device/simulator/execution profile label, including calibration where relevant.
    pub fn execution_profile_id(&self) -> &str {
        &self.execution_profile_id
    }

    /// Measurement basis/observable grouping contract.
    pub fn measurement_basis_id(&self) -> &str {
        &self.measurement_basis_id
    }

    /// Evidence class for every record in this batch.
    pub fn evidence_class(&self) -> MisMeasurementEvidenceClass {
        self.evidence_class
    }

    /// Canonically sorted candidate IDs updated by each shot.
    pub fn candidate_vertices(&self) -> &[usize] {
        &self.candidate_vertices
    }

    /// Cost model identifier; the actual unit is defined by the caller.
    pub fn cost_model_id(&self) -> &str {
        &self.cost_model_id
    }

    /// One-time setup cost for a non-empty batch.
    pub fn setup_cost_units(&self) -> u64 {
        self.setup_cost_units
    }

    /// Cost charged for each physical shot, not once per candidate.
    pub fn per_shot_cost_units(&self) -> u64 {
        self.per_shot_cost_units
    }
}

/// Boolean observation for one candidate obtained from one shot result.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MisCandidateOutcome {
    /// Candidate/vertex identity.
    pub vertex: usize,
    /// Whether the corresponding measured observable indicates inclusion.
    pub included: bool,
}

/// Immutable normalized record for one circuit shot.
///
/// All candidate outcomes from this sample live in the same record. This preserves
/// their joint observation and permits later estimation of cross-candidate co-inclusion.
/// A raw backend result/bitstring and external hardware receipt should be retained as
/// separate artifacts when needed; this record is the validated normalized view.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MisMeasurementShotRecord {
    spec: MisMeasurementBatchSpec,
    shot_index: u64,
    source_record_id: String,
    outcomes: Vec<MisCandidateOutcome>,
}

impl MisMeasurementShotRecord {
    /// Validate one shot record against the batch's declared observation map.
    pub fn new(
        spec: &MisMeasurementBatchSpec,
        shot_index: u64,
        source_record_id: impl Into<String>,
        mut outcomes: Vec<MisCandidateOutcome>,
    ) -> Result<Self, MisMeasurementBatchError> {
        let source_record_id = source_record_id.into();
        validate_identifier("source_record_id", &source_record_id)?;
        outcomes.sort_unstable_by_key(|outcome| outcome.vertex);
        if outcomes.len() != spec.candidate_vertices.len() {
            return Err(MisMeasurementBatchError::OutcomeCountMismatch {
                expected: spec.candidate_vertices.len(),
                actual: outcomes.len(),
            });
        }
        for (index, outcome) in outcomes.iter().enumerate() {
            let expected_vertex = spec.candidate_vertices[index];
            if outcome.vertex != expected_vertex {
                return Err(MisMeasurementBatchError::OutcomeMappingMismatch {
                    expected_vertex,
                    actual_vertex: outcome.vertex,
                });
            }
        }
        Ok(Self {
            spec: spec.clone(),
            shot_index,
            source_record_id,
            outcomes,
        })
    }

    /// Batch contract copied into this immutable record.
    pub fn spec(&self) -> &MisMeasurementBatchSpec {
        &self.spec
    }

    /// Shot index within the batch.
    pub fn shot_index(&self) -> u64 {
        self.shot_index
    }

    /// Source log or replay-artifact identifier.
    pub fn source_record_id(&self) -> &str {
        &self.source_record_id
    }

    /// Joint outcome vector, canonically ordered by candidate ID.
    pub fn outcomes(&self) -> &[MisCandidateOutcome] {
        &self.outcomes
    }
}

/// Aggregator for one batch; each physical shot contributes once to physical cost.
#[derive(Debug, Clone)]
pub struct MisMeasurementBatchAccumulator {
    spec: MisMeasurementBatchSpec,
    seen_shot_indices: Vec<u64>,
    inclusion_counts: Vec<u64>,
    joint_inclusion_counts: Vec<u64>,
}

impl MisMeasurementBatchAccumulator {
    /// Start an empty accumulator for the supplied batch.
    pub fn new(spec: MisMeasurementBatchSpec) -> Self {
        let candidate_count = spec.candidate_vertices.len();
        Self {
            spec,
            seen_shot_indices: Vec::new(),
            inclusion_counts: vec![0; candidate_count],
            joint_inclusion_counts: vec![0; candidate_count * candidate_count],
        }
    }

    /// Record one shot, preserving joint outcomes and refusing duplicate/mixed contexts.
    pub fn observe(
        &mut self,
        record: MisMeasurementShotRecord,
    ) -> Result<(), MisMeasurementBatchError> {
        if record.spec != self.spec {
            return Err(MisMeasurementBatchError::BatchContextMismatch);
        }
        if self.seen_shot_indices.contains(&record.shot_index) {
            return Err(MisMeasurementBatchError::DuplicateShotIndex {
                shot_index: record.shot_index,
            });
        }
        let k = self.spec.candidate_vertices.len();
        for (index, outcome) in record.outcomes.iter().enumerate() {
            if outcome.included {
                self.inclusion_counts[index] = self.inclusion_counts[index]
                    .checked_add(1)
                    .ok_or(MisMeasurementBatchError::CounterOverflow)?;
                for (other_index, other) in record.outcomes.iter().enumerate() {
                    if other.included {
                        let pair_index = index * k + other_index;
                        self.joint_inclusion_counts[pair_index] = self.joint_inclusion_counts[pair_index]
                            .checked_add(1)
                            .ok_or(MisMeasurementBatchError::CounterOverflow)?;
                    }
                }
            }
        }
        self.seen_shot_indices.push(record.shot_index);
        Ok(())
    }

    /// Number of unique physical shot results consumed.
    pub fn physical_shot_count(&self) -> u64 {
        self.seen_shot_indices.len() as u64
    }

    /// Number of per-candidate observations represented by all recorded shots.
    pub fn candidate_observation_count(&self) -> u128 {
        u128::from(self.physical_shot_count()) * self.spec.candidate_vertices.len() as u128
    }

    /// Estimated cost in the caller-defined cost units, setup once per non-empty batch.
    pub fn estimated_cost_units(&self) -> u128 {
        let shots = u128::from(self.physical_shot_count());
        if shots == 0 {
            0
        } else {
            u128::from(self.spec.setup_cost_units)
                + shots * u128::from(self.spec.per_shot_cost_units)
        }
    }

    /// Return a summary without losing the joint count matrix.
    pub fn summary(&self) -> MisMeasurementBatchSummary {
        let k = self.spec.candidate_vertices.len();
        let inclusion_counts = self.spec.candidate_vertices.iter().copied()
            .zip(self.inclusion_counts.iter().copied())
            .collect();
        let mut pairwise_co_inclusion_counts = Vec::new();
        for left in 0..k {
            for right in (left + 1)..k {
                pairwise_co_inclusion_counts.push((
                    self.spec.candidate_vertices[left],
                    self.spec.candidate_vertices[right],
                    self.joint_inclusion_counts[left * k + right],
                ));
            }
        }
        MisMeasurementBatchSummary {
            batch_id: self.spec.batch_id.clone(),
            evidence_class: self.spec.evidence_class,
            cost_model_id: self.spec.cost_model_id.clone(),
            physical_shot_count: self.physical_shot_count(),
            candidate_observation_count: self.candidate_observation_count(),
            inclusion_counts,
            pairwise_co_inclusion_counts,
            estimated_cost_units: self.estimated_cost_units(),
        }
    }
}

/// Aggregate counts with physical executions kept separate from candidate observations.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MisMeasurementBatchSummary {
    /// Stable batch identifier.
    pub batch_id: String,
    /// Evidence class of the batch.
    pub evidence_class: MisMeasurementEvidenceClass,
    /// Caller-defined cost model ID.
    pub cost_model_id: String,
    /// Unique physical shots recorded in this batch.
    pub physical_shot_count: u64,
    /// Sum of per-candidate observations contributed by those shots.
    pub candidate_observation_count: u128,
    /// Per-candidate inclusion counts, sorted by candidate ID.
    pub inclusion_counts: Vec<(usize, u64)>,
    /// Joint inclusion count for every unordered candidate pair.
    pub pairwise_co_inclusion_counts: Vec<(usize, usize, u64)>,
    /// One-time batch setup plus per-physical-shot cost.
    pub estimated_cost_units: u128,
}

/// Validation failure for batch context or shot observations.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum MisMeasurementBatchError {
    /// Required identifier is empty or contains control characters.
    InvalidIdentifier {
        /// Field name rejected.
        field: &'static str,
    },
    /// Batch requires at least one candidate.
    EmptyCandidateSet,
    /// Candidate appears more than once in the observation map.
    DuplicateCandidate {
        /// Repeated candidate ID.
        vertex: usize,
    },
    /// Outcome vector does not include exactly every declared candidate.
    OutcomeCountMismatch {
        /// Expected number of outcomes.
        expected: usize,
        /// Actual number of outcomes.
        actual: usize,
    },
    /// Outcome vector is missing an expected candidate or includes an unexpected one.
    OutcomeMappingMismatch {
        /// Candidate ID expected at this canonical position.
        expected_vertex: usize,
        /// Candidate ID supplied at this canonical position.
        actual_vertex: usize,
    },
    /// Shot index already observed for this batch.
    DuplicateShotIndex {
        /// Reused shot index.
        shot_index: u64,
    },
    /// A record belongs to a different batch or different full execution context.
    BatchContextMismatch,
    /// An observation counter overflowed.
    CounterOverflow,
}

impl fmt::Display for MisMeasurementBatchError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidIdentifier { field } => write!(f, "{field} must be non-empty and contain no control characters"),
            Self::EmptyCandidateSet => write!(f, "measurement batch must update at least one candidate"),
            Self::DuplicateCandidate { vertex } => write!(f, "candidate {vertex} is duplicated in the observation map"),
            Self::OutcomeCountMismatch { expected, actual } => write!(f, "expected {expected} candidate outcomes, got {actual}"),
            Self::OutcomeMappingMismatch { expected_vertex, actual_vertex } => write!(f, "expected candidate {expected_vertex}, got candidate {actual_vertex}"),
            Self::DuplicateShotIndex { shot_index } => write!(f, "shot index {shot_index} was already recorded"),
            Self::BatchContextMismatch => write!(f, "shot record belongs to a different batch/evaluation context"),
            Self::CounterOverflow => write!(f, "measurement counter overflowed"),
        }
    }
}

impl std::error::Error for MisMeasurementBatchError {}

fn validate_identifier(field: &'static str, value: &str) -> Result<(), MisMeasurementBatchError> {
    if value.trim().is_empty() || value.chars().any(char::is_control) {
        return Err(MisMeasurementBatchError::InvalidIdentifier { field });
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn spec(candidates: Vec<usize>, evidence_class: MisMeasurementEvidenceClass) -> MisMeasurementBatchSpec {
        MisMeasurementBatchSpec::new(
            "batch-01",
            [8; 32],
            "device-A/calibration-7/layout-3",
            "computational-basis-v1",
            evidence_class,
            candidates,
            "microsecond-model-v1",
            100,
            2,
        ).expect("valid batch spec")
    }

    fn record(spec: &MisMeasurementBatchSpec, shot: u64, values: &[(usize, bool)]) -> MisMeasurementShotRecord {
        MisMeasurementShotRecord::new(
            spec,
            shot,
            format!("source-row-{shot}"),
            values.iter().map(|&(vertex, included)| MisCandidateOutcome { vertex, included }).collect(),
        ).expect("valid shot record")
    }

    #[test]
    fn one_physical_shot_updates_multiple_candidate_observations() {
        let batch = spec(vec![9, 2, 5], MisMeasurementEvidenceClass::PhysicalQpu);
        let mut accumulator = MisMeasurementBatchAccumulator::new(batch.clone());
        accumulator.observe(record(&batch, 0, &[(2, true), (5, false), (9, true)])).expect("valid result");
        let summary = accumulator.summary();
        assert_eq!(summary.physical_shot_count, 1);
        assert_eq!(summary.candidate_observation_count, 3);
        assert_eq!(summary.estimated_cost_units, 102); // setup once + one physical shot
        assert_eq!(summary.inclusion_counts, vec![(2, 1), (5, 0), (9, 1)]);
        assert_eq!(summary.pairwise_co_inclusion_counts, vec![(2, 5, 0), (2, 9, 1), (5, 9, 0)]);
    }

    #[test]
    fn batch_keeps_cross_candidate_cooccurrence_from_shared_shots() {
        let batch = spec(vec![0, 1], MisMeasurementEvidenceClass::Synthetic);
        let mut accumulator = MisMeasurementBatchAccumulator::new(batch.clone());
        accumulator.observe(record(&batch, 0, &[(0, true), (1, true)])).expect("joint success");
        accumulator.observe(record(&batch, 1, &[(0, false), (1, false)])).expect("joint failure");
        let summary = accumulator.summary();
        assert_eq!(summary.inclusion_counts, vec![(0, 1), (1, 1)]);
        assert_eq!(summary.pairwise_co_inclusion_counts, vec![(0, 1, 1)]);
        assert_eq!(summary.physical_shot_count, 2);
        assert_eq!(summary.candidate_observation_count, 4);
    }

    #[test]
    fn setup_cost_is_charged_once_not_once_per_candidate() {
        let batch = spec(vec![0, 1, 2, 3], MisMeasurementEvidenceClass::IdealSimulation);
        let mut accumulator = MisMeasurementBatchAccumulator::new(batch.clone());
        assert_eq!(accumulator.estimated_cost_units(), 0);
        for shot in 0..5 {
            accumulator.observe(record(&batch, shot, &[(0, true), (1, false), (2, true), (3, false)]))
                .expect("valid sample");
        }
        assert_eq!(accumulator.physical_shot_count(), 5);
        assert_eq!(accumulator.candidate_observation_count(), 20);
        assert_eq!(accumulator.estimated_cost_units(), 110); // 100 + 5 * 2
    }

    #[test]
    fn same_batch_rejects_duplicate_shot_indices() {
        let batch = spec(vec![0, 1], MisMeasurementEvidenceClass::Synthetic);
        let mut accumulator = MisMeasurementBatchAccumulator::new(batch.clone());
        accumulator.observe(record(&batch, 5, &[(0, true), (1, false)])).expect("first shot");
        assert_eq!(
            accumulator.observe(record(&batch, 5, &[(0, false), (1, true)])).expect_err("duplicate index"),
            MisMeasurementBatchError::DuplicateShotIndex { shot_index: 5 }
        );
    }

    #[test]
    fn accumulator_rejects_mixed_execution_contexts() {
        let batch_a = spec(vec![0, 1], MisMeasurementEvidenceClass::Synthetic);
        let batch_b = MisMeasurementBatchSpec::new(
            "batch-02", [8; 32], "device-A/calibration-7/layout-3",
            "computational-basis-v1", MisMeasurementEvidenceClass::Synthetic,
            vec![0, 1], "microsecond-model-v1", 100, 2
        ).expect("valid other batch");
        let mut accumulator = MisMeasurementBatchAccumulator::new(batch_a);
        assert_eq!(
            accumulator.observe(record(&batch_b, 0, &[(0, true), (1, false)])).expect_err("mixed batch"),
            MisMeasurementBatchError::BatchContextMismatch
        );
    }

    #[test]
    fn batch_key_binds_evidence_class_context_and_candidate_mapping() {
        let synthetic = spec(vec![0, 1], MisMeasurementEvidenceClass::Synthetic);
        let physical = MisMeasurementBatchSpec::new(
            "batch-01", [8; 32], "device-A/calibration-7/layout-3",
            "computational-basis-v1", MisMeasurementEvidenceClass::PhysicalQpu,
            vec![0, 1], "microsecond-model-v1", 100, 2
        ).expect("valid physical spec");
        assert_ne!(synthetic, physical);

        let changed_layout = MisMeasurementBatchSpec::new(
            "batch-01", [8; 32], "device-A/calibration-8/layout-3",
            "computational-basis-v1", MisMeasurementEvidenceClass::Synthetic,
            vec![0, 1], "microsecond-model-v1", 100, 2
        ).expect("valid alternate context");
        assert_ne!(synthetic, changed_layout);
    }

    #[test]
    fn outcomes_must_cover_exact_declared_candidate_set() {
        let batch = spec(vec![3, 4], MisMeasurementEvidenceClass::Synthetic);
        assert_eq!(
            MisMeasurementShotRecord::new(
                &batch, 0, "row-0",
                vec![MisCandidateOutcome { vertex: 3, included: true }]
            ).expect_err("missing an outcome"),
            MisMeasurementBatchError::OutcomeCountMismatch { expected: 2, actual: 1 }
        );
        assert_eq!(
            MisMeasurementShotRecord::new(
                &batch, 0, "row-0",
                vec![
                    MisCandidateOutcome { vertex: 3, included: true },
                    MisCandidateOutcome { vertex: 8, included: false },
                ]
            ).expect_err("unexpected candidate"),
            MisMeasurementBatchError::OutcomeMappingMismatch {
                expected_vertex: 4, actual_vertex: 8
            }
        );
    }

    #[test]
    fn rejects_empty_or_duplicate_candidate_maps() {
        assert_eq!(
            MisMeasurementBatchSpec::new(
                "batch", [0; 32], "profile", "basis", MisMeasurementEvidenceClass::Synthetic,
                vec![], "cost-v1", 0, 0
            ).expect_err("empty candidate map"),
            MisMeasurementBatchError::EmptyCandidateSet
        );
        assert_eq!(
            MisMeasurementBatchSpec::new(
                "batch", [0; 32], "profile", "basis", MisMeasurementEvidenceClass::Synthetic,
                vec![1, 2, 1], "cost-v1", 0, 0
            ).expect_err("duplicate candidate"),
            MisMeasurementBatchError::DuplicateCandidate { vertex: 1 }
        );
    }

    #[test]
    fn rejects_invalid_batch_and_source_identifiers() {
        assert_eq!(
            MisMeasurementBatchSpec::new(
                "batch", [0; 32], " ", "basis", MisMeasurementEvidenceClass::Synthetic,
                vec![0], "cost-v1", 0, 0
            ).expect_err("blank profile"),
            MisMeasurementBatchError::InvalidIdentifier { field: "execution_profile_id" }
        );
        let batch = spec(vec![0], MisMeasurementEvidenceClass::Synthetic);
        assert_eq!(
            MisMeasurementShotRecord::new(&batch, 0, "bad\nsource", vec![
                MisCandidateOutcome { vertex: 0, included: true }
            ]).expect_err("control char source"),
            MisMeasurementBatchError::InvalidIdentifier { field: "source_record_id" }
        );
    }

    #[test]
    fn evidence_classes_have_stable_distinct_labels() {
        assert_eq!(MisMeasurementEvidenceClass::PhysicalQpu.as_str(), "physical-qpu");
        assert_ne!(MisMeasurementEvidenceClass::IdealSimulation.as_str(), MisMeasurementEvidenceClass::PhysicalQpu.as_str());
        assert_eq!(MisMeasurementEvidenceClass::ClassicalReplay.as_str(), "classical-replay");
    }
}
