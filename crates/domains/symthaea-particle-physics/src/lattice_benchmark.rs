//! Tiny pure-SU(3) benchmark harness.
//!
//! This module exists to generate reproducible *qualification traces* from very
//! small lattices. It deliberately does not infer thermalization or convergence.
//! Cold and strongly disordered starts are compared downstream with independent
//! chain-statistics evidence.

use crate::lattice_gauge::{LatticeGaugeError, WilsonGaugeField, su3_mul};
use crate::lattice_metropolis::{LatticeMetropolisError, Su2Subgroup, embedded_su2_rotation};
use crate::lattice_rng::{
    LatticeChaCha8Stream, LatticeRngError, LatticeStreamCoordinates, LatticeStreamDomain,
};
use crate::lattice_sweep::{
    LatticeSweepError, SymmetricProposalConfig, draw_symmetric_subgroup_proposal,
    metropolis_sweep,
};
use crate::symmetry_groups::Complex;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum QualificationStart {
    ColdIdentity,
    /// A reproducible, strongly randomized start generated by repeated embedded
    /// SU(2) rotations. This is intentionally **not** claimed to be Haar SU(3).
    Disordered {
        rounds: u32,
        max_angle: f64,
    },
}

#[derive(Debug, Clone, PartialEq)]
pub struct TinyBenchmarkPlan {
    pub dims: [usize; 4],
    pub beta: f64,
    pub thermalization_sweeps: u64,
    pub measurement_stride: u64,
    pub measurements: usize,
    pub proposal_max_angle: f64,
    pub seed: [u8; 32],
    pub ensemble_slot: u32,
    pub replica: u16,
    pub rank: u16,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct BenchmarkSample {
    pub sweep: u64,
    pub wilson_action: f64,
    pub average_plaquette: f64,
    pub spatial_mean_polyakov: Complex,
    /// Acceptance rate of the sweep immediately preceding this sample.
    pub preceding_sweep_acceptance: f64,
}

#[derive(Debug, Clone, PartialEq)]
pub struct TinyBenchmarkTrace {
    pub start: QualificationStart,
    pub transition_stream_id: u64,
    pub initialization_stream_id: Option<u64>,
    pub initial_wilson_action: f64,
    pub initial_average_plaquette: f64,
    pub samples: Vec<BenchmarkSample>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct PairedBenchmarkTrace {
    pub cold: TinyBenchmarkTrace,
    pub disordered: TinyBenchmarkTrace,
}

#[derive(Debug, Clone, PartialEq)]
pub enum TinyBenchmarkError {
    Gauge(LatticeGaugeError),
    Metropolis(LatticeMetropolisError),
    Rng(LatticeRngError),
    Sweep(LatticeSweepError),
    InvalidBeta(f64),
    InvalidMeasurementStride(u64),
    InvalidMeasurementCount(usize),
    InvalidDisorderRounds(u32),
    MeasurementScheduleOverflow,
}

impl From<LatticeGaugeError> for TinyBenchmarkError {
    fn from(value: LatticeGaugeError) -> Self { Self::Gauge(value) }
}
impl From<LatticeMetropolisError> for TinyBenchmarkError {
    fn from(value: LatticeMetropolisError) -> Self { Self::Metropolis(value) }
}
impl From<LatticeRngError> for TinyBenchmarkError {
    fn from(value: LatticeRngError) -> Self { Self::Rng(value) }
}
impl From<LatticeSweepError> for TinyBenchmarkError {
    fn from(value: LatticeSweepError) -> Self { Self::Sweep(value) }
}

impl TinyBenchmarkPlan {
    pub fn measurement_schedule(&self) -> Result<Vec<u64>, TinyBenchmarkError> {
        if !self.beta.is_finite() || self.beta <= 0.0 {
            return Err(TinyBenchmarkError::InvalidBeta(self.beta));
        }
        if self.measurement_stride == 0 {
            return Err(TinyBenchmarkError::InvalidMeasurementStride(0));
        }
        if self.measurements == 0 {
            return Err(TinyBenchmarkError::InvalidMeasurementCount(0));
        }
        let mut schedule = Vec::with_capacity(self.measurements);
        for index in 1..=self.measurements {
            let offset = self.measurement_stride
                .checked_mul(index as u64)
                .ok_or(TinyBenchmarkError::MeasurementScheduleOverflow)?;
            schedule.push(self.thermalization_sweeps
                .checked_add(offset)
                .ok_or(TinyBenchmarkError::MeasurementScheduleOverflow)?);
        }
        Ok(schedule)
    }

    fn coordinates(&self, domain: LatticeStreamDomain) -> LatticeStreamCoordinates {
        LatticeStreamCoordinates {
            domain,
            ensemble_slot: self.ensemble_slot,
            replica: self.replica,
            rank: self.rank,
        }
    }
}

fn spatial_mean_polyakov(field: &WilsonGaugeField) -> Result<Complex, LatticeGaugeError> {
    let dims = field.dims();
    let mut re = 0.0;
    let mut im = 0.0;
    let mut count = 0usize;
    for x in 0..dims[0] {
        for y in 0..dims[1] {
            for z in 0..dims[2] {
                let value = field.polyakov_loop([x, y, z])?;
                re += value.re;
                im += value.im;
                count += 1;
            }
        }
    }
    Ok(Complex::new(re / count as f64, im / count as f64))
}

fn disordered_field(
    plan: &TinyBenchmarkPlan,
    rounds: u32,
    max_angle: f64,
) -> Result<(WilsonGaugeField, u64), TinyBenchmarkError> {
    if rounds == 0 {
        return Err(TinyBenchmarkError::InvalidDisorderRounds(0));
    }
    let mut field = WilsonGaugeField::identity(plan.dims)?;
    let mut source = LatticeChaCha8Stream::new(
        plan.seed,
        plan.coordinates(LatticeStreamDomain::GaugeInitialization),
    )?;
    let stream_id = source.stream_id();
    let config = SymmetricProposalConfig { max_angle };
    let dims = field.dims();

    for _ in 0..rounds {
        for x in 0..dims[0] {
            for y in 0..dims[1] {
                for z in 0..dims[2] {
                    for t in 0..dims[3] {
                        let site = [x, y, z, t];
                        for mu in 0..4 {
                            for subgroup in Su2Subgroup::ALL {
                                let proposal = draw_symmetric_subgroup_proposal(
                                    &mut source, subgroup, config,
                                )?;
                                let rotation = embedded_su2_rotation(proposal)?;
                                let current = *field.link(site, mu)?;
                                field.set_link(site, mu, su3_mul(&rotation, &current))?;
                            }
                        }
                    }
                }
            }
        }
    }
    Ok((field, stream_id))
}

pub fn run_tiny_benchmark(
    plan: &TinyBenchmarkPlan,
    start: QualificationStart,
) -> Result<TinyBenchmarkTrace, TinyBenchmarkError> {
    let schedule = plan.measurement_schedule()?;
    let (mut field, initialization_stream_id) = match start {
        QualificationStart::ColdIdentity => (WilsonGaugeField::identity(plan.dims)?, None),
        QualificationStart::Disordered { rounds, max_angle } => {
            let (field, id) = disordered_field(plan, rounds, max_angle)?;
            (field, Some(id))
        }
    };

    let initial_wilson_action = field.wilson_action(plan.beta)?;
    let initial_average_plaquette = field.average_plaquette()?;
    let mut transition = LatticeChaCha8Stream::new(
        plan.seed,
        plan.coordinates(LatticeStreamDomain::GaugeTransition),
    )?;
    let transition_stream_id = transition.stream_id();
    let config = SymmetricProposalConfig { max_angle: plan.proposal_max_angle };
    let final_sweep = *schedule.last().expect("validated non-empty schedule");
    let mut samples = Vec::with_capacity(schedule.len());
    let mut schedule_cursor = 0usize;

    for sweep in 1..=final_sweep {
        let stats = metropolis_sweep(&mut field, plan.beta, config, &mut transition)?;
        if schedule_cursor < schedule.len() && sweep == schedule[schedule_cursor] {
            samples.push(BenchmarkSample {
                sweep,
                wilson_action: field.wilson_action(plan.beta)?,
                average_plaquette: field.average_plaquette()?,
                spatial_mean_polyakov: spatial_mean_polyakov(&field)?,
                preceding_sweep_acceptance: stats.acceptance_rate(),
            });
            schedule_cursor += 1;
        }
    }

    Ok(TinyBenchmarkTrace {
        start,
        transition_stream_id,
        initialization_stream_id,
        initial_wilson_action,
        initial_average_plaquette,
        samples,
    })
}

pub fn run_paired_tiny_benchmark(
    plan: &TinyBenchmarkPlan,
    disorder_rounds: u32,
    disorder_max_angle: f64,
) -> Result<PairedBenchmarkTrace, TinyBenchmarkError> {
    Ok(PairedBenchmarkTrace {
        cold: run_tiny_benchmark(plan, QualificationStart::ColdIdentity)?,
        disordered: run_tiny_benchmark(
            plan,
            QualificationStart::Disordered {
                rounds: disorder_rounds,
                max_angle: disorder_max_angle,
            },
        )?,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn plan() -> TinyBenchmarkPlan {
        TinyBenchmarkPlan {
            dims: [2, 2, 1, 2],
            beta: 5.7,
            thermalization_sweeps: 1,
            measurement_stride: 1,
            measurements: 2,
            proposal_max_angle: 0.18,
            seed: [0x5a; 32],
            ensemble_slot: 17,
            replica: 0,
            rank: 0,
        }
    }

    #[test]
    fn measurement_schedule_never_samples_at_burnin_boundary() {
        assert_eq!(plan().measurement_schedule().unwrap(), vec![2, 3]);
    }

    #[test]
    fn paired_trace_is_deterministically_replayable() {
        let a = run_paired_tiny_benchmark(&plan(), 2, std::f64::consts::PI).unwrap();
        let b = run_paired_tiny_benchmark(&plan(), 2, std::f64::consts::PI).unwrap();
        assert_eq!(a, b);
        assert_eq!(a.cold.samples.len(), 2);
        assert_eq!(a.disordered.samples.len(), 2);
    }

    #[test]
    fn initialization_and_transition_streams_are_separate() {
        let trace = run_tiny_benchmark(
            &plan(),
            QualificationStart::Disordered { rounds: 1, max_angle: 1.0 },
        )
        .unwrap();
        assert_ne!(Some(trace.transition_stream_id), trace.initialization_stream_id);
    }

    #[test]
    fn disordered_start_is_observably_not_the_identity_fixture() {
        let trace = run_tiny_benchmark(
            &plan(),
            QualificationStart::Disordered { rounds: 2, max_angle: std::f64::consts::PI },
        )
        .unwrap();
        assert!(trace.initial_wilson_action > 0.0);
        assert!(trace.initial_average_plaquette < 0.999);
    }

    #[test]
    fn trace_does_not_claim_convergence() {
        let paired = run_paired_tiny_benchmark(&plan(), 1, 1.0).unwrap();
        // The type contains raw histories only: no pass/fail or equilibrium field exists.
        assert_eq!(paired.cold.samples[0].sweep, 2);
        assert_eq!(paired.disordered.samples[0].sweep, 2);
    }
}
