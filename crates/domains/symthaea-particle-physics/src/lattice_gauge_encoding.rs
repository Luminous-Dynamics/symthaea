    #[test]
    fn negative_zero_survives_exact_roundtrip() {
        let mut field = WilsonGaugeField::identity([1, 1, 1, 1]).unwrap();
        let mut matrix = *field.link([0, 0, 0, 0], 0).unwrap();
        matrix[0][1] = Complex::new(-0.0, 0.0);
        field.set_link([0, 0, 0, 0], 0, matrix).unwrap();

        let bytes = encode_wilson_gauge_field(&field).unwrap();
        let decoded = decode_wilson_gauge_field(&bytes).unwrap();
        assert_eq!(
            decoded.link([0, 0, 0, 0], 0).unwrap()[0][1].re.to_bits(),
            0x8000_0000_0000_0000
        );
    }

    #[test]
    fn malformed_bytes_fail_closed() {
        let bytes = encode_wilson_gauge_field(&fixture()).unwrap();

        assert!(matches!(
            decode_wilson_gauge_field(&bytes[..bytes.len() - 1]),
            Err(GaugeFieldEncodingError::LengthMismatch { .. })
        ));

        let mut trailing = bytes.clone();
        trailing.push(0);
        assert!(matches!(
            decode_wilson_gauge_field(&trailing),
            Err(GaugeFieldEncodingError::LengthMismatch { .. })
        ));

        let mut wrong_tag = bytes.clone();
        wrong_tag[0] ^= 1;
        assert_eq!(
            decode_wilson_gauge_field(&wrong_tag),
            Err(GaugeFieldEncodingError::WrongTag)
        );

        let mut zero_extent = bytes.clone();
        let offset = WILSON_GAUGE_FIELD_TAG.len();
        zero_extent[offset..offset + 4].copy_from_slice(&0u32.to_be_bytes());
        assert!(matches!(
            decode_wilson_gauge_field(&zero_extent),
            Err(GaugeFieldEncodingError::ExtentDoesNotFitU32(_))
        ));

        let mut nan_payload = bytes.clone();
        let payload = WILSON_GAUGE_FIELD_TAG.len() + HEADER_BYTES;
        nan_payload[payload..payload + 8]
            .copy_from_slice(&0x7ff8_0000_0000_0000u64.to_be_bytes());
        assert!(matches!(
            decode_wilson_gauge_field(&nan_payload),
            Err(GaugeFieldEncodingError::NonFiniteScalar { .. })
        ));

        let mut finite_but_not_su3 = bytes;
        finite_but_not_su3[payload..payload + 8]
            .copy_from_slice(&2.0f64.to_bits().to_be_bytes());
        assert!(matches!(
            decode_wilson_gauge_field(&finite_but_not_su3),
            Err(GaugeFieldEncodingError::Gauge(
                LatticeGaugeError::InvalidSu3Link { .. }
            ))
        ));
    }
