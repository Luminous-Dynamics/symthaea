//! Junction–hypha graph projection for geometric network analysis.
//!
//! This graph is deliberately distinct from MycelialNetworkGraph:
//! - MycelialNetworkGraph has filaments as vertices for filament-failure tests.
//! - This graph has branch/tip/fusion junctions as vertices and curve intervals
//!   as weighted hypha segments.
//!
//! All lengths are in renderer-local model units. They are not millimetres,
//! biological hyphal lengths, measured flow, or physical transport costs.
//! Geometric crossings never create connections; only parent IDs and explicit,
//! accepted anastomosis records contribute topology.

use std::cmp::Ordering;
use std::collections::{BTreeMap, BTreeSet, BinaryHeap, HashMap, HashSet, VecDeque};
use std::error::Error;
use std::fmt;

use serde::{Deserialize, Serialize};

use crate::mycelial_model::{
    MYCELIAL_MODEL_VERSION, MycelialFilament, MycelialModel, SpatialPoint3,
};
use crate::mycelial_network::{
    AnastomosisKind, MycelialAnastomosis, MycelialNetworkConfig, build_mycelial_network_graph,
};

pub const MYCELIAL_JUNCTION_GRAPH_SCHEMA_VERSION: u16 = 1;
pub const MAX_JUNCTION_GRAPH_JUNCTIONS: usize = 8_192;
pub const MAX_JUNCTION_GRAPH_SEGMENTS: usize = 16_384;
pub const PARAMETER_SCALE: u32 = 1_000_000;
const ARC_LENGTH_SUBDIVISIONS: usize = 64;
const MAX_MODEL_COORDINATE: f32 = 1_024.0;
const MAX_GRAPH_COORDINATE: f32 = MAX_MODEL_COORDINATE + 1.0;
const MAX_SEGMENT_ARC_LENGTH_MODEL_UNITS: f64 = 12_000.0;
const MAX_SEGMENT_WELD_OFFSET_MODEL_UNITS: f64 = 1.0;
const MAX_GRAPH_ID_BYTES: usize = 128;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum JunctionLengthUnit {
    /// Scale-free coordinates generated by the Mycelial Presence renderer.
    OrganismLocalModelUnit,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum JunctionKind {
    /// An unparented filament start. Coincident starts are not implicitly joined.
    Origin,
    /// An explicit parent-end / child-start connection.
    Branch,
    /// An unconnected terminal hyphal tip.
    Tip,
    /// An explicitly accepted tip-to-tip or tip-to-side fusion.
    Anastomosis,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MycelialJunction {
    pub id: String,
    pub kind: JunctionKind,
    pub position: SpatialPoint3,
    /// Filaments that explicitly terminate, begin, or fuse at this junction.
    pub incident_filament_ids: Vec<u32>,
    /// Non-empty only for a terminal contact (including a tip fused to a side).
    pub terminal_filament_ids: Vec<u32>,
    pub anastomosis_ids: Vec<u32>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MycelialHyphaSegment {
    pub id: String,
    pub filament_id: u32,
    /// Quantized source-curve interval. The complete source curve is [0, 1e6].
    pub t_start_micros: u32,
    pub t_end_micros: u32,
    pub start_junction_id: String,
    pub end_junction_id: String,
    /// Actual cubic-Bezier arc length; excludes any small junction weld offset.
    pub arc_length_model_units: f64,
    /// Straight-line endpoint correction to the canonical junction anchors.
    /// This is a geometric weld diagnostic, not constructed hypha material.
    pub start_junction_offset_model_units: f64,
    pub end_junction_offset_model_units: f64,
    pub radius_start_model_units: f32,
    pub radius_end_model_units: f32,
}

impl MycelialHyphaSegment {
    /// Path weight used by graph shortest paths. Weld offsets are included so
    /// that fusing two near-contact curves cannot create a path shorter than
    /// the represented geometry. They remain excluded from hyphal material cost.
    pub fn traversal_length_model_units(&self) -> f64 {
        self.arc_length_model_units
            + self.start_junction_offset_model_units
            + self.end_junction_offset_model_units
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MycelialJunctionHyphaGraph {
    pub schema_version: u16,
    pub source_model_version: u16,
    pub length_unit: JunctionLengthUnit,
    pub source_geometry_digest: String,
    /// Complete, sorted identity set of source filaments represented by segments.
    /// This allows deserialized graph validation to detect a wholly omitted curve.
    pub source_filament_ids: Vec<u32>,
    pub maximum_junction_gap_model_units: f32,
    pub junctions: Vec<MycelialJunction>,
    pub segments: Vec<MycelialHyphaSegment>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MycelialJunctionGraphMetrics {
    pub junction_count: usize,
    pub hypha_segment_count: usize,
    pub connected_components: usize,
    pub cycle_rank: usize,
    /// Sum of source-curve arc lengths. Does not include weld offsets.
    pub total_hypha_length_model_units_microunits: u64,
    /// Sum of straight-line junction weld offsets, separately reported.
    pub total_junction_offset_model_units_microunits: u64,
    pub maximum_junction_gap_microunits: u32,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct GeometricEfficiencyReport {
    pub mean_directness: Option<f64>,
    pub eligible_pairs: usize,
    pub reachable_pairs: usize,
    pub unreachable_pairs: usize,
    pub mean_network_path_length_model_units: Option<f64>,
    pub length_unit: JunctionLengthUnit,
}

#[derive(Debug, Clone, PartialEq)]
pub enum MycelialJunctionGraphError {
    UnsupportedModelVersion(u16),
    InvalidConfig,
    FilamentLimitExceeded(usize),
    InvalidFilamentGeometry(u32),
    DuplicateFilamentId(u32),
    MissingParent {
        filament_id: u32,
        parent_id: u32,
    },
    ParentCycle(u32),
    ParentJunctionGap {
        filament_id: u32,
        gap: f32,
        limit: f32,
    },
    TerminalFlagMismatch(u32),
    NetworkValidation(String),
    InvalidFusionParameter(u32),
    JunctionGapExceeded {
        fusion_id: u32,
        gap: f32,
        limit: f32,
    },
    SharedFusionContact {
        filament_id: u32,
        parameter_micros: u32,
    },
    JunctionLimitExceeded(usize),
    SegmentLimitExceeded(usize),
    DegenerateHyphaSegment(u32),
    InvalidGraph(&'static str),
    UnknownRootJunction(String),
    EfficiencyGraphTooLarge(usize),
}

impl fmt::Display for MycelialJunctionGraphError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::UnsupportedModelVersion(version) => {
                write!(f, "unsupported MycelialModel version {version}")
            }
            Self::InvalidConfig => write!(f, "invalid junction graph configuration"),
            Self::FilamentLimitExceeded(count) => {
                write!(f, "filament count {count} exceeds the mesh limit")
            }
            Self::InvalidFilamentGeometry(id) => {
                write!(f, "filament {id} has invalid or unbounded geometry")
            }
            Self::DuplicateFilamentId(id) => write!(f, "duplicate filament ID {id}"),
            Self::MissingParent {
                filament_id,
                parent_id,
            } => write!(
                f,
                "filament {filament_id} references missing parent {parent_id}"
            ),
            Self::ParentCycle(id) => write!(f, "parent cycle includes filament {id}"),
            Self::ParentJunctionGap {
                filament_id,
                gap,
                limit,
            } => write!(
                f,
                "filament {filament_id} child start gap {gap:.6} exceeds junction tolerance {limit:.6}"
            ),
            Self::TerminalFlagMismatch(id) => {
                write!(
                    f,
                    "filament {id} terminal flag disagrees with its child set"
                )
            }
            Self::NetworkValidation(message) => {
                write!(f, "accepted anastomosis validation failed: {message}")
            }
            Self::InvalidFusionParameter(id) => {
                write!(f, "anastomosis {id} has a non-canonical curve parameter")
            }
            Self::JunctionGapExceeded {
                fusion_id,
                gap,
                limit,
            } => write!(
                f,
                "anastomosis {fusion_id} weld gap {gap:.6} exceeds junction tolerance {limit:.6}"
            ),
            Self::SharedFusionContact {
                filament_id,
                parameter_micros,
            } => write!(
                f,
                "multiple anastomoses claim filament {filament_id} at t={parameter_micros}/1e6"
            ),
            Self::JunctionLimitExceeded(count) => {
                write!(f, "junction count {count} exceeds its bound")
            }
            Self::SegmentLimitExceeded(count) => {
                write!(f, "hypha segment count {count} exceeds its bound")
            }
            Self::DegenerateHyphaSegment(id) => {
                write!(f, "filament {id} produces a degenerate curve interval")
            }
            Self::InvalidGraph(reason) => write!(f, "invalid junction–hypha graph: {reason}"),
            Self::UnknownRootJunction(id) => write!(f, "unknown declared root junction {id}"),
            Self::EfficiencyGraphTooLarge(count) => {
                write!(
                    f,
                    "efficiency calculation is bounded to 2,048 junctions, got {count}"
                )
            }
        }
    }
}

impl Error for MycelialJunctionGraphError {}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct MycelialJunctionGraphConfig {
    /// Maximum distance between an explicit junction anchor and a source curve
    /// contact, in renderer-local model units.
    pub maximum_junction_gap_model_units: f32,
}

impl Default for MycelialJunctionGraphConfig {
    fn default() -> Self {
        Self {
            maximum_junction_gap_model_units: 0.05,
        }
    }
}

/// Build a junction–hypha graph from a MycelialModel and explicit accepted fusions.
///
/// A parent ID is the authority for branch connectivity. A fusion record is the
/// authority for anastomosis connectivity. Identical coordinates alone never
/// connect two filaments. Tip-to-side fusion splits the target Bezier at its
/// quantized parameter and preserves both source-curve intervals.
pub fn build_mycelial_junction_hypha_graph(
    model: &MycelialModel,
    anastomoses: &[MycelialAnastomosis],
    config: MycelialJunctionGraphConfig,
) -> Result<MycelialJunctionHyphaGraph, MycelialJunctionGraphError> {
    if model.schema_version != MYCELIAL_MODEL_VERSION {
        return Err(MycelialJunctionGraphError::UnsupportedModelVersion(
            model.schema_version,
        ));
    }
    if !config.maximum_junction_gap_model_units.is_finite()
        || !(0.0..=1.0).contains(&config.maximum_junction_gap_model_units)
    {
        return Err(MycelialJunctionGraphError::InvalidConfig);
    }
    if model.filaments.len() > crate::mycelial_mesh::MAX_MYCELIAL_FILAMENTS {
        return Err(MycelialJunctionGraphError::FilamentLimitExceeded(
            model.filaments.len(),
        ));
    }

    // Reuse the existing accepted-fusion contract. Candidate detection alone
    // never reaches this builder: callers must pass approved fusion records.
    build_mycelial_network_graph(model, anastomoses, MycelialNetworkConfig::default())
        .map_err(|error| MycelialJunctionGraphError::NetworkValidation(error.to_string()))?;

    let mut filaments = BTreeMap::<u32, &MycelialFilament>::new();
    let mut children = BTreeMap::<u32, Vec<u32>>::new();
    for filament in &model.filaments {
        if filaments.insert(filament.id, filament).is_some() {
            return Err(MycelialJunctionGraphError::DuplicateFilamentId(filament.id));
        }
        if !valid_filament_geometry(filament) {
            return Err(MycelialJunctionGraphError::InvalidFilamentGeometry(
                filament.id,
            ));
        }
        if let Some(parent_id) = filament.parent_id {
            children.entry(parent_id).or_default().push(filament.id);
        }
    }

    let mut maximum_gap = 0.0f32;
    for filament in &model.filaments {
        let has_children = children
            .get(&filament.id)
            .is_some_and(|child_ids| !child_ids.is_empty());
        if filament.terminal == has_children {
            return Err(MycelialJunctionGraphError::TerminalFlagMismatch(
                filament.id,
            ));
        }
        let mut visited = HashSet::new();
        let mut cursor = Some(filament.id);
        while let Some(id) = cursor {
            if !visited.insert(id) {
                return Err(MycelialJunctionGraphError::ParentCycle(id));
            }
            cursor = filaments.get(&id).and_then(|value| value.parent_id);
        }
        if let Some(parent_id) = filament.parent_id {
            let parent =
                filaments
                    .get(&parent_id)
                    .ok_or(MycelialJunctionGraphError::MissingParent {
                        filament_id: filament.id,
                        parent_id,
                    })?;
            let gap = point_distance(parent.end, filament.start);
            maximum_gap = maximum_gap.max(gap);
            if gap > config.maximum_junction_gap_model_units {
                return Err(MycelialJunctionGraphError::ParentJunctionGap {
                    filament_id: filament.id,
                    gap,
                    limit: config.maximum_junction_gap_model_units,
                });
            }
        }
    }

    let source_geometry_digest = source_geometry_digest(model);
    let mut nodes = BTreeMap::<String, MycelialJunction>::new();
    let mut contact_to_node = BTreeMap::<(u32, u32), String>::new();

    for fusion in anastomoses {
        let source = filaments.get(&fusion.source_filament_id).ok_or(
            MycelialJunctionGraphError::InvalidFusionParameter(fusion.id),
        )?;
        let target = filaments.get(&fusion.target_filament_id).ok_or(
            MycelialJunctionGraphError::InvalidFusionParameter(fusion.id),
        )?;
        let source_t = parameter_micros(fusion.source_t);
        let target_t = parameter_micros(fusion.target_t);
        if source_t != PARAMETER_SCALE
            || (fusion.kind == AnastomosisKind::TipToTip && target_t != PARAMETER_SCALE)
            || (fusion.kind == AnastomosisKind::TipToSide
                && (target_t <= 50_000 || target_t >= 950_000))
        {
            return Err(MycelialJunctionGraphError::InvalidFusionParameter(
                fusion.id,
            ));
        }

        let source_point = bezier_point(source, source_t);
        let target_point = bezier_point(target, target_t);
        let source_gap = point_distance(source_point, fusion.junction_position);
        let target_gap = point_distance(target_point, fusion.junction_position);
        let gap = source_gap.max(target_gap);
        maximum_gap = maximum_gap.max(gap);
        if !gap.is_finite() || gap > config.maximum_junction_gap_model_units {
            return Err(MycelialJunctionGraphError::JunctionGapExceeded {
                fusion_id: fusion.id,
                gap,
                limit: config.maximum_junction_gap_model_units,
            });
        }

        let node_id = format!("anastomosis:{}", fusion.id);
        for key in [
            (fusion.source_filament_id, source_t),
            (fusion.target_filament_id, target_t),
        ] {
            if contact_to_node.insert(key, node_id.clone()).is_some() {
                return Err(MycelialJunctionGraphError::SharedFusionContact {
                    filament_id: key.0,
                    parameter_micros: key.1,
                });
            }
        }
        let mut terminal_filament_ids = vec![fusion.source_filament_id];
        if fusion.kind == AnastomosisKind::TipToTip {
            terminal_filament_ids.push(fusion.target_filament_id);
        }
        terminal_filament_ids.sort_unstable();
        nodes.insert(
            node_id.clone(),
            MycelialJunction {
                id: node_id,
                kind: JunctionKind::Anastomosis,
                position: fusion.junction_position,
                incident_filament_ids: vec![fusion.source_filament_id, fusion.target_filament_id],
                terminal_filament_ids,
                anastomosis_ids: vec![fusion.id],
            },
        );
    }

    let mut segments = Vec::new();
    for (&filament_id, filament) in &filaments {
        let start_id = match filament.parent_id {
            Some(parent_id) => format!("branch:{parent_id}"),
            None => format!("origin:{filament_id}"),
        };
        let start_kind = if filament.parent_id.is_some() {
            JunctionKind::Branch
        } else {
            JunctionKind::Origin
        };
        insert_or_check_node(
            &mut nodes,
            start_id.clone(),
            start_kind,
            filament.start,
            config.maximum_junction_gap_model_units,
        )?;

        let end_key = (filament_id, PARAMETER_SCALE);
        let end_id = if let Some(fusion_node) = contact_to_node.get(&end_key) {
            fusion_node.clone()
        } else if children
            .get(&filament_id)
            .is_some_and(|child_ids| !child_ids.is_empty())
        {
            format!("branch:{filament_id}")
        } else {
            format!("tip:{filament_id}")
        };
        let end_kind = if contact_to_node.contains_key(&end_key) {
            JunctionKind::Anastomosis
        } else if children
            .get(&filament_id)
            .is_some_and(|child_ids| !child_ids.is_empty())
        {
            JunctionKind::Branch
        } else {
            JunctionKind::Tip
        };
        insert_or_check_node(
            &mut nodes,
            end_id.clone(),
            end_kind,
            filament.end,
            config.maximum_junction_gap_model_units,
        )?;
        if end_kind == JunctionKind::Tip {
            if let Some(node) = nodes.get_mut(&end_id) {
                node.terminal_filament_ids.push(filament_id);
            }
        }

        let mut breakpoints = vec![(0u32, start_id)];
        for (&(source_id, parameter), node_id) in &contact_to_node {
            if source_id == filament_id && parameter > 0 && parameter < PARAMETER_SCALE {
                breakpoints.push((parameter, node_id.clone()));
            }
        }
        breakpoints.push((PARAMETER_SCALE, end_id));
        breakpoints.sort_by_key(|(parameter, _)| *parameter);
        for pair in breakpoints.windows(2) {
            let (t_start, start_junction_id) = (&pair[0].0, &pair[0].1);
            let (t_end, end_junction_id) = (&pair[1].0, &pair[1].1);
            if t_end <= t_start {
                return Err(MycelialJunctionGraphError::InvalidGraph(
                    "curve breakpoints are not strictly increasing",
                ));
            }
            let start_parameter = *t_start as f32 / PARAMETER_SCALE as f32;
            let end_parameter = *t_end as f32 / PARAMETER_SCALE as f32;
            let start_point = bezier_point(filament, *t_start);
            let end_point = bezier_point(filament, *t_end);
            let arc_length = bezier_arc_length(filament, start_parameter, end_parameter);
            if !arc_length.is_finite() || arc_length <= 1.0e-9 {
                return Err(MycelialJunctionGraphError::DegenerateHyphaSegment(
                    filament_id,
                ));
            }
            let start_node =
                nodes
                    .get(start_junction_id)
                    .ok_or(MycelialJunctionGraphError::InvalidGraph(
                        "segment start junction is missing",
                    ))?;
            let end_node =
                nodes
                    .get(end_junction_id)
                    .ok_or(MycelialJunctionGraphError::InvalidGraph(
                        "segment end junction is missing",
                    ))?;
            let start_offset = f64::from(point_distance(start_point, start_node.position));
            let end_offset = f64::from(point_distance(end_point, end_node.position));
            let id = format!("hypha:{filament_id}:{}-{}", t_start, t_end);
            segments.push(MycelialHyphaSegment {
                id,
                filament_id,
                t_start_micros: *t_start,
                t_end_micros: *t_end,
                start_junction_id: start_junction_id.clone(),
                end_junction_id: end_junction_id.clone(),
                arc_length_model_units: arc_length,
                start_junction_offset_model_units: start_offset,
                end_junction_offset_model_units: end_offset,
                radius_start_model_units: radius_at(filament, start_parameter),
                radius_end_model_units: radius_at(filament, end_parameter),
            });
            if let Some(node) = nodes.get_mut(start_junction_id) {
                node.incident_filament_ids.push(filament_id);
            }
            if let Some(node) = nodes.get_mut(end_junction_id) {
                node.incident_filament_ids.push(filament_id);
            }
        }
    }

    for node in nodes.values_mut() {
        node.incident_filament_ids.sort_unstable();
        node.incident_filament_ids.dedup();
        node.terminal_filament_ids.sort_unstable();
        node.terminal_filament_ids.dedup();
        node.anastomosis_ids.sort_unstable();
        node.anastomosis_ids.dedup();
    }
    if nodes.len() > MAX_JUNCTION_GRAPH_JUNCTIONS {
        return Err(MycelialJunctionGraphError::JunctionLimitExceeded(
            nodes.len(),
        ));
    }
    if segments.len() > MAX_JUNCTION_GRAPH_SEGMENTS {
        return Err(MycelialJunctionGraphError::SegmentLimitExceeded(
            segments.len(),
        ));
    }

    let graph = MycelialJunctionHyphaGraph {
        schema_version: MYCELIAL_JUNCTION_GRAPH_SCHEMA_VERSION,
        source_model_version: model.schema_version,
        length_unit: JunctionLengthUnit::OrganismLocalModelUnit,
        source_geometry_digest,
        source_filament_ids: filaments.keys().copied().collect(),
        maximum_junction_gap_model_units: maximum_gap,
        junctions: nodes.into_values().collect(),
        segments,
    };
    graph.validate()?;
    Ok(graph)
}

fn insert_or_check_node(
    nodes: &mut BTreeMap<String, MycelialJunction>,
    id: String,
    kind: JunctionKind,
    position: SpatialPoint3,
    maximum_gap: f32,
) -> Result<(), MycelialJunctionGraphError> {
    if let Some(existing) = nodes.get(&id) {
        let gap = point_distance(existing.position, position);
        if gap > maximum_gap {
            return Err(MycelialJunctionGraphError::InvalidGraph(
                "shared parent/child junction exceeds its geometric tolerance",
            ));
        }
        return Ok(());
    }
    nodes.insert(
        id.clone(),
        MycelialJunction {
            id,
            kind,
            position,
            incident_filament_ids: Vec::new(),
            terminal_filament_ids: Vec::new(),
            anastomosis_ids: Vec::new(),
        },
    );
    Ok(())
}

fn valid_filament_geometry(filament: &MycelialFilament) -> bool {
    let bounded = |point: SpatialPoint3| {
        point.is_finite()
            && point.x.abs() <= MAX_MODEL_COORDINATE
            && point.y.abs() <= MAX_MODEL_COORDINATE
            && point.z.abs() <= MAX_MODEL_COORDINATE
    };
    [
        filament.start,
        filament.control_a,
        filament.control_b,
        filament.end,
    ]
    .into_iter()
    .all(bounded)
        && filament.radius_start.is_finite()
        && filament.radius_end.is_finite()
        && (0.005..=128.0).contains(&filament.radius_start)
        && (0.005..=128.0).contains(&filament.radius_end)
}

fn parameter_micros(parameter: f32) -> u32 {
    (f64::from(parameter.clamp(0.0, 1.0)) * f64::from(PARAMETER_SCALE)).round() as u32
}

fn bezier_point(filament: &MycelialFilament, parameter_micros: u32) -> SpatialPoint3 {
    let t = f64::from(parameter_micros) / f64::from(PARAMETER_SCALE);
    let u = 1.0 - t;
    let points = [
        filament.start,
        filament.control_a,
        filament.control_b,
        filament.end,
    ];
    let coordinate = |axis: fn(SpatialPoint3) -> f32| {
        let p0 = f64::from(axis(points[0]));
        let p1 = f64::from(axis(points[1]));
        let p2 = f64::from(axis(points[2]));
        let p3 = f64::from(axis(points[3]));
        (u * u * u * p0 + 3.0 * u * u * t * p1 + 3.0 * u * t * t * p2 + t * t * t * p3) as f32
    };
    SpatialPoint3 {
        x: coordinate(|point| point.x),
        y: coordinate(|point| point.y),
        z: coordinate(|point| point.z),
    }
}

fn bezier_derivative(filament: &MycelialFilament, t: f64) -> [f64; 3] {
    let u = 1.0 - t;
    let p0 = filament.start;
    let p1 = filament.control_a;
    let p2 = filament.control_b;
    let p3 = filament.end;
    let component = |a: f32, b: f32, c: f32, d: f32| {
        3.0 * u * u * (f64::from(b) - f64::from(a))
            + 6.0 * u * t * (f64::from(c) - f64::from(b))
            + 3.0 * t * t * (f64::from(d) - f64::from(c))
    };
    [
        component(p0.x, p1.x, p2.x, p3.x),
        component(p0.y, p1.y, p2.y, p3.y),
        component(p0.z, p1.z, p2.z, p3.z),
    ]
}

fn bezier_arc_length(filament: &MycelialFilament, start: f32, end: f32) -> f64 {
    let intervals = ARC_LENGTH_SUBDIVISIONS;
    let step = (f64::from(end) - f64::from(start)) / intervals as f64;
    let speed = |index: usize| {
        let derivative = bezier_derivative(filament, f64::from(start) + index as f64 * step);
        (derivative[0] * derivative[0]
            + derivative[1] * derivative[1]
            + derivative[2] * derivative[2])
            .sqrt()
    };
    let mut sum = speed(0) + speed(intervals);
    for index in 1..intervals {
        sum += if index % 2 == 0 { 2.0 } else { 4.0 } * speed(index);
    }
    sum * step / 3.0
}

fn radius_at(filament: &MycelialFilament, parameter: f32) -> f32 {
    filament.radius_start
        + (filament.radius_end - filament.radius_start) * parameter.clamp(0.0, 1.0)
}

fn point_distance(left: SpatialPoint3, right: SpatialPoint3) -> f32 {
    left.sub(right).length()
}

impl MycelialJunctionHyphaGraph {
    pub fn validate(&self) -> Result<(), MycelialJunctionGraphError> {
        if self.schema_version != MYCELIAL_JUNCTION_GRAPH_SCHEMA_VERSION
            || self.source_model_version != MYCELIAL_MODEL_VERSION
            || self.source_geometry_digest.len() != 64
            || !self
                .source_geometry_digest
                .bytes()
                .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
            || !self.maximum_junction_gap_model_units.is_finite()
            || !(0.0..=1.0).contains(&self.maximum_junction_gap_model_units)
        {
            return Err(MycelialJunctionGraphError::InvalidGraph(
                "invalid schema, digest, or junction-gap metadata",
            ));
        }
        let mut node_index = HashMap::with_capacity(self.junctions.len());
        for (index, junction) in self.junctions.iter().enumerate() {
            let bounded_position = junction.position.is_finite()
                && junction.position.x.abs() <= MAX_GRAPH_COORDINATE
                && junction.position.y.abs() <= MAX_GRAPH_COORDINATE
                && junction.position.z.abs() <= MAX_GRAPH_COORDINATE;
            if junction.id.is_empty()
                || junction.incident_filament_ids.is_empty()
                || junction.id.len() > MAX_GRAPH_ID_BYTES
                || junction.id.chars().any(char::is_control)
                || !bounded_position
                || junction
                    .incident_filament_ids
                    .windows(2)
                    .any(|pair| pair[0] >= pair[1])
                || junction
                    .terminal_filament_ids
                    .windows(2)
                    .any(|pair| pair[0] >= pair[1])
                || junction
                    .anastomosis_ids
                    .windows(2)
                    .any(|pair| pair[0] >= pair[1])
                || junction
                    .terminal_filament_ids
                    .iter()
                    .any(|id| !junction.incident_filament_ids.contains(id))
                || junction.incident_filament_ids.iter().any(|id| {
                    !self.source_filament_ids.contains(id)
                })
                || node_index.insert(junction.id.as_str(), index).is_some()
            {
                return Err(MycelialJunctionGraphError::InvalidGraph(
                    "duplicate, unbounded, or internally inconsistent junction",
                ));
            }
            match junction.kind {
                JunctionKind::Origin | JunctionKind::Branch => {
                    if !junction.terminal_filament_ids.is_empty()
                        || !junction.anastomosis_ids.is_empty()
                    {
                        return Err(MycelialJunctionGraphError::InvalidGraph(
                            "origin/branch junction has terminal or fusion metadata",
                        ));
                    }
                }
                JunctionKind::Tip => {
                    if junction.terminal_filament_ids.len() != 1
                        || !junction.anastomosis_ids.is_empty()
                    {
                        return Err(MycelialJunctionGraphError::InvalidGraph(
                            "tip junction has invalid terminal/fusion metadata",
                        ));
                    }
                }
                JunctionKind::Anastomosis => {
                    if junction.incident_filament_ids.len() < 2
                        || junction.terminal_filament_ids.is_empty()
                        || junction.anastomosis_ids.is_empty()
                    {
                        return Err(MycelialJunctionGraphError::InvalidGraph(
                            "anastomosis junction has no explicit fusion/terminal identity",
                        ));
                    }
                }
            }
        }
        if self.junctions.len() > MAX_JUNCTION_GRAPH_JUNCTIONS
            || self.segments.len() > MAX_JUNCTION_GRAPH_SEGMENTS
        {
            return Err(MycelialJunctionGraphError::InvalidGraph(
                "junction or segment limit exceeded",
            ));
        }
        if self.source_filament_ids.windows(2).any(|pair| pair[0] >= pair[1]) {
            return Err(MycelialJunctionGraphError::InvalidGraph(
                "source filament IDs must be sorted and unique",
            ));
        }
        let source_filaments: HashSet<_> = self.source_filament_ids.iter().copied().collect();
        let mut segment_ids = HashSet::with_capacity(self.segments.len());
        let mut intervals = BTreeMap::<u32, Vec<(u32, u32)>>::new();
        for segment in &self.segments {
            let start_index = node_index.get(segment.start_junction_id.as_str());
            let end_index = node_index.get(segment.end_junction_id.as_str());
            let endpoints_are_incident = start_index.is_some_and(|index| {
                self.junctions[*index]
                    .incident_filament_ids
                    .contains(&segment.filament_id)
            }) && end_index.is_some_and(|index| {
                self.junctions[*index]
                    .incident_filament_ids
                    .contains(&segment.filament_id)
            });
            if segment.id.is_empty()
                || segment.id.len() > MAX_GRAPH_ID_BYTES
                || segment.id.chars().any(char::is_control)
                || !segment_ids.insert(segment.id.as_str())
                || segment.t_start_micros >= segment.t_end_micros
                || segment.t_end_micros > PARAMETER_SCALE
                || start_index.is_none()
                || end_index.is_none()
                || !endpoints_are_incident
                || segment.start_junction_id == segment.end_junction_id
                || !source_filaments.contains(&segment.filament_id)
                || !segment.arc_length_model_units.is_finite()
                || segment.arc_length_model_units <= 0.0
                || segment.arc_length_model_units > MAX_SEGMENT_ARC_LENGTH_MODEL_UNITS
                || !segment.start_junction_offset_model_units.is_finite()
                || !segment.end_junction_offset_model_units.is_finite()
                || segment.start_junction_offset_model_units < 0.0
                || segment.end_junction_offset_model_units < 0.0
                || segment.start_junction_offset_model_units > MAX_SEGMENT_WELD_OFFSET_MODEL_UNITS
                || segment.end_junction_offset_model_units > MAX_SEGMENT_WELD_OFFSET_MODEL_UNITS
                || !segment.radius_start_model_units.is_finite()
                || !segment.radius_end_model_units.is_finite()
                || !(0.005..=128.0).contains(&segment.radius_start_model_units)
                || !(0.005..=128.0).contains(&segment.radius_end_model_units)
            {
                return Err(MycelialJunctionGraphError::InvalidGraph(
                    "invalid or dangling hypha segment",
                ));
            }
            intervals
                .entry(segment.filament_id)
                .or_default()
                .push((segment.t_start_micros, segment.t_end_micros));
        }
        if intervals.len() != self.source_filament_ids.len()
            || self
                .source_filament_ids
                .iter()
                .any(|filament_id| !intervals.contains_key(filament_id))
        {
            return Err(MycelialJunctionGraphError::InvalidGraph(
                "one or more source filaments have no represented curve intervals",
            ));
        }
        for coverage in intervals.values_mut() {
            coverage.sort_unstable();
            if coverage.first().map(|interval| interval.0) != Some(0)
                || coverage.last().map(|interval| interval.1) != Some(PARAMETER_SCALE)
                || coverage.windows(2).any(|pair| pair[0].1 != pair[1].0)
            {
                return Err(MycelialJunctionGraphError::InvalidGraph(
                    "source filament intervals are missing, overlapping, or discontinuous",
                ));
            }
        }
        Ok(())
    }

    pub fn metrics(&self) -> Result<MycelialJunctionGraphMetrics, MycelialJunctionGraphError> {
        self.validate()?;
        let adjacency = self.adjacency()?;
        let components = count_components(&adjacency);
        let edge_count = self.segments.len();
        let vertex_count = self.junctions.len();
        let cycle_rank = edge_count
            .saturating_add(components)
            .saturating_sub(vertex_count);
        let total_length = self
            .segments
            .iter()
            .map(|segment| segment.arc_length_model_units)
            .sum::<f64>();
        let total_offsets = self
            .segments
            .iter()
            .map(|segment| {
                segment.start_junction_offset_model_units + segment.end_junction_offset_model_units
            })
            .sum::<f64>();
        Ok(MycelialJunctionGraphMetrics {
            junction_count: vertex_count,
            hypha_segment_count: edge_count,
            connected_components: components,
            cycle_rank,
            total_hypha_length_model_units_microunits: quantize_nonnegative(total_length),
            total_junction_offset_model_units_microunits: quantize_nonnegative(total_offsets),
            maximum_junction_gap_microunits: quantize_nonnegative(f64::from(
                self.maximum_junction_gap_model_units,
            ))
            .min(u64::from(u32::MAX)) as u32,
        })
    }

    /// Mean Euclidean separation / weighted network shortest-path length over
    /// all unordered connected junction pairs. Disconnected pairs are reported,
    /// never silently treated as zero-distance paths.
    pub fn global_geometric_efficiency(
        &self,
    ) -> Result<GeometricEfficiencyReport, MycelialJunctionGraphError> {
        self.validate()?;
        if self.junctions.len() > 2_048 {
            return Err(MycelialJunctionGraphError::EfficiencyGraphTooLarge(
                self.junctions.len(),
            ));
        }
        let adjacency = self.adjacency()?;
        let mut sum_directness = 0.0;
        let mut sum_path_length = 0.0;
        let mut reachable_pairs = 0usize;
        let eligible_pairs = self
            .junctions
            .len()
            .saturating_mul(self.junctions.len().saturating_sub(1))
            / 2;
        for source in 0..self.junctions.len() {
            let distances = shortest_path_distances(&adjacency, source);
            for target in (source + 1)..self.junctions.len() {
                let path_length = distances[target];
                if !path_length.is_finite() {
                    continue;
                }
                let direct = f64::from(point_distance(
                    self.junctions[source].position,
                    self.junctions[target].position,
                ));
                if path_length <= 0.0 || direct > path_length + 1.0e-4 {
                    return Err(MycelialJunctionGraphError::InvalidGraph(
                        "direct Euclidean distance exceeds represented network path",
                    ));
                }
                sum_directness += direct / path_length;
                sum_path_length += path_length;
                reachable_pairs += 1;
            }
        }
        Ok(GeometricEfficiencyReport {
            mean_directness: (reachable_pairs > 0)
                .then_some(sum_directness / reachable_pairs as f64),
            eligible_pairs,
            reachable_pairs,
            unreachable_pairs: eligible_pairs - reachable_pairs,
            mean_network_path_length_model_units: (reachable_pairs > 0)
                .then_some(sum_path_length / reachable_pairs as f64),
            length_unit: self.length_unit,
        })
    }

    /// For each terminal filament contact, select the nearest reachable member
    /// of the caller-declared root set. Model origins are not assumed to be
    /// biological plant roots; root identity must be supplied explicitly.
    pub fn root_directed_geometric_efficiency(
        &self,
        root_junction_ids: &[String],
    ) -> Result<GeometricEfficiencyReport, MycelialJunctionGraphError> {
        self.validate()?;
        if self.junctions.len() > 2_048 {
            return Err(MycelialJunctionGraphError::EfficiencyGraphTooLarge(
                self.junctions.len(),
            ));
        }
        let index_by_id: HashMap<_, _> = self
            .junctions
            .iter()
            .enumerate()
            .map(|(index, junction)| (junction.id.as_str(), index))
            .collect();
        let mut roots = BTreeSet::new();
        for root_id in root_junction_ids {
            let index = index_by_id
                .get(root_id.as_str())
                .copied()
                .ok_or_else(|| MycelialJunctionGraphError::UnknownRootJunction(root_id.clone()))?;
            roots.insert(index);
        }
        let adjacency = self.adjacency()?;
        let terminals: Vec<_> = self
            .junctions
            .iter()
            .enumerate()
            .filter(|(_, junction)| !junction.terminal_filament_ids.is_empty())
            .map(|(index, _)| index)
            .collect();
        let mut sum_directness = 0.0;
        let mut sum_path_length = 0.0;
        let mut reachable_pairs = 0usize;
        for terminal in &terminals {
            let distances = shortest_path_distances(&adjacency, *terminal);
            let nearest = roots
                .iter()
                .filter_map(|root| {
                    let distance = distances[*root];
                    distance.is_finite().then_some((*root, distance))
                })
                .min_by(|left, right| {
                    left.1
                        .total_cmp(&right.1)
                        .then_with(|| left.0.cmp(&right.0))
                });
            if let Some((root, path_length)) = nearest {
                let direct = f64::from(point_distance(
                    self.junctions[*terminal].position,
                    self.junctions[root].position,
                ));
                if path_length <= 0.0 || direct > path_length + 1.0e-4 {
                    return Err(MycelialJunctionGraphError::InvalidGraph(
                        "direct tip-to-root distance exceeds represented network path",
                    ));
                }
                sum_directness += direct / path_length;
                sum_path_length += path_length;
                reachable_pairs += 1;
            }
        }
        let eligible_pairs = terminals.len();
        Ok(GeometricEfficiencyReport {
            mean_directness: (reachable_pairs > 0)
                .then_some(sum_directness / reachable_pairs as f64),
            eligible_pairs,
            reachable_pairs,
            unreachable_pairs: eligible_pairs - reachable_pairs,
            mean_network_path_length_model_units: (reachable_pairs > 0)
                .then_some(sum_path_length / reachable_pairs as f64),
            length_unit: self.length_unit,
        })
    }

    pub fn canonical_digest_hex(&self) -> Result<String, MycelialJunctionGraphError> {
        self.validate()?;
        let mut hasher = blake3::Hasher::new();
        hasher.update(b"symthaea-mycelial-junction-hypha-v1");
        hasher.update(&self.schema_version.to_le_bytes());
        hasher.update(&self.source_model_version.to_le_bytes());
        hasher.update(&[0]); // organism_local_model_unit
        hasher.update(self.source_geometry_digest.as_bytes());
        hasher.update(&(self.source_filament_ids.len() as u64).to_le_bytes());
        for filament_id in &self.source_filament_ids {
            hasher.update(&filament_id.to_le_bytes());
        }
        hasher.update(
            &self
                .maximum_junction_gap_model_units
                .to_bits()
                .to_le_bytes(),
        );
        let mut junctions: Vec<_> = self.junctions.iter().collect();
        junctions.sort_by(|left, right| left.id.cmp(&right.id));
        hasher.update(&(junctions.len() as u64).to_le_bytes());
        for junction in junctions {
            hash_string(&mut hasher, &junction.id);
            hasher.update(&[match junction.kind {
                JunctionKind::Origin => 0,
                JunctionKind::Branch => 1,
                JunctionKind::Tip => 2,
                JunctionKind::Anastomosis => 3,
            }]);
            hash_point(&mut hasher, junction.position);
            hash_u32_list(&mut hasher, &junction.incident_filament_ids);
            hash_u32_list(&mut hasher, &junction.terminal_filament_ids);
            hash_u32_list(&mut hasher, &junction.anastomosis_ids);
        }
        let mut segments: Vec<_> = self.segments.iter().collect();
        segments.sort_by(|left, right| left.id.cmp(&right.id));
        hasher.update(&(segments.len() as u64).to_le_bytes());
        for segment in segments {
            hash_string(&mut hasher, &segment.id);
            hasher.update(&segment.filament_id.to_le_bytes());
            hasher.update(&segment.t_start_micros.to_le_bytes());
            hasher.update(&segment.t_end_micros.to_le_bytes());
            hash_string(&mut hasher, &segment.start_junction_id);
            hash_string(&mut hasher, &segment.end_junction_id);
            hasher.update(&segment.arc_length_model_units.to_bits().to_le_bytes());
            hasher.update(
                &segment
                    .start_junction_offset_model_units
                    .to_bits()
                    .to_le_bytes(),
            );
            hasher.update(
                &segment
                    .end_junction_offset_model_units
                    .to_bits()
                    .to_le_bytes(),
            );
            hasher.update(&segment.radius_start_model_units.to_bits().to_le_bytes());
            hasher.update(&segment.radius_end_model_units.to_bits().to_le_bytes());
        }
        Ok(hex_digest(hasher.finalize().as_bytes()))
    }

    fn adjacency(&self) -> Result<Vec<Vec<(usize, f64)>>, MycelialJunctionGraphError> {
        let indices: HashMap<_, _> = self
            .junctions
            .iter()
            .enumerate()
            .map(|(index, junction)| (junction.id.as_str(), index))
            .collect();
        let mut adjacency = vec![Vec::new(); self.junctions.len()];
        for segment in &self.segments {
            let source = indices
                .get(segment.start_junction_id.as_str())
                .copied()
                .ok_or(MycelialJunctionGraphError::InvalidGraph(
                    "unknown segment start junction",
                ))?;
            let target = indices
                .get(segment.end_junction_id.as_str())
                .copied()
                .ok_or(MycelialJunctionGraphError::InvalidGraph(
                    "unknown segment end junction",
                ))?;
            let weight = segment.traversal_length_model_units();
            adjacency[source].push((target, weight));
            adjacency[target].push((source, weight));
        }
        for neighbours in &mut adjacency {
            neighbours.sort_by(|left, right| {
                left.0
                    .cmp(&right.0)
                    .then_with(|| left.1.total_cmp(&right.1))
            });
        }
        Ok(adjacency)
    }
}

#[derive(Debug, Clone, Copy)]
struct QueueEntry {
    node: usize,
    distance: f64,
}

impl PartialEq for QueueEntry {
    fn eq(&self, other: &Self) -> bool {
        self.node == other.node && self.distance.to_bits() == other.distance.to_bits()
    }
}

impl Eq for QueueEntry {}

impl PartialOrd for QueueEntry {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

impl Ord for QueueEntry {
    fn cmp(&self, other: &Self) -> Ordering {
        other
            .distance
            .total_cmp(&self.distance)
            .then_with(|| other.node.cmp(&self.node))
    }
}

fn shortest_path_distances(adjacency: &[Vec<(usize, f64)>], source: usize) -> Vec<f64> {
    let mut distances = vec![f64::INFINITY; adjacency.len()];
    let mut queue = BinaryHeap::new();
    distances[source] = 0.0;
    queue.push(QueueEntry {
        node: source,
        distance: 0.0,
    });
    while let Some(current) = queue.pop() {
        if current.distance > distances[current.node] {
            continue;
        }
        for &(target, weight) in &adjacency[current.node] {
            let candidate = current.distance + weight;
            if candidate < distances[target] {
                distances[target] = candidate;
                queue.push(QueueEntry {
                    node: target,
                    distance: candidate,
                });
            }
        }
    }
    distances
}

fn count_components(adjacency: &[Vec<(usize, f64)>]) -> usize {
    let mut visited = vec![false; adjacency.len()];
    let mut components = 0;
    for start in 0..adjacency.len() {
        if visited[start] {
            continue;
        }
        components += 1;
        visited[start] = true;
        let mut queue = VecDeque::from([start]);
        while let Some(current) = queue.pop_front() {
            for &(target, _) in &adjacency[current] {
                if !visited[target] {
                    visited[target] = true;
                    queue.push_back(target);
                }
            }
        }
    }
    components
}

fn source_geometry_digest(model: &MycelialModel) -> String {
    let mut hasher = blake3::Hasher::new();
    hasher.update(b"symthaea-mycelial-source-curves-v1");
    hasher.update(&model.schema_version.to_le_bytes());
    let mut filaments: Vec<_> = model.filaments.iter().collect();
    filaments.sort_by_key(|filament| filament.id);
    hasher.update(&(filaments.len() as u64).to_le_bytes());
    for filament in filaments {
        hasher.update(&filament.id.to_le_bytes());
        match filament.parent_id {
            Some(parent) => {
                hasher.update(&[1]);
                hasher.update(&parent.to_le_bytes());
            }
            None => {
                hasher.update(&[0]);
            }
        }
        hasher.update(&[filament.generation, u8::from(filament.terminal)]);
        for point in [
            filament.start,
            filament.control_a,
            filament.control_b,
            filament.end,
        ] {
            hash_point(&mut hasher, point);
        }
        hasher.update(&filament.radius_start.to_bits().to_le_bytes());
        hasher.update(&filament.radius_end.to_bits().to_le_bytes());
    }
    hex_digest(hasher.finalize().as_bytes())
}

fn hash_point(hasher: &mut blake3::Hasher, point: SpatialPoint3) {
    for coordinate in [point.x, point.y, point.z] {
        hasher.update(&coordinate.to_bits().to_le_bytes());
    }
}

fn hash_string(hasher: &mut blake3::Hasher, value: &str) {
    hasher.update(&(value.len() as u64).to_le_bytes());
    hasher.update(value.as_bytes());
}

fn hash_u32_list(hasher: &mut blake3::Hasher, values: &[u32]) {
    hasher.update(&(values.len() as u64).to_le_bytes());
    for value in values {
        hasher.update(&value.to_le_bytes());
    }
}

fn quantize_nonnegative(value: f64) -> u64 {
    if value.is_finite() && value >= 0.0 {
        (value * 1_000_000.0).round().min(u64::MAX as f64) as u64
    } else {
        0
    }
}

fn hex_digest(bytes: &[u8; 32]) -> String {
    let mut output = String::with_capacity(64);
    for byte in bytes {
        use fmt::Write as _;
        write!(&mut output, "{byte:02x}").expect("writing to String cannot fail");
    }
    output
}

