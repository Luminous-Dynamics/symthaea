fn envelope(signature: [u8; 64]) -> XeniaSignatureEnvelopeV1 {
    XeniaSignatureEnvelopeV1 {
        algorithm: ED25519_SIGNATURE_ALGORITHM.to_string(),
        signature: signature.to_vec(),
    }
}

#[test]
fn reproduces_frozen_xenia_witness_frontier_vector_v1() {
    let key = SigningKey::from_bytes(&[7; 32]);
    assert_eq!(key.verifying_key().to_bytes(), PUBLIC_KEY);
    assert_eq!(derive_xenia_witness_frontier_source_id(PUBLIC_KEY, [0x33; 32]).unwrap(), SOURCE_ID);
    assert_eq!(witness_frontier_statement_digest([0x44; 16], 9, [0x55; 32]), FRONTIER_DIGEST);

    let target = XeniaWitnessFrontierAnchorTargetV1 {
        schema_version: XENIA_WITNESS_FRONTIER_ANCHOR_SCHEMA_VERSION,
        operation_id: OPERATION_ID,
        source_id: SOURCE_ID,
        source_epoch: 3,
        anchor_policy_digest: [0x33; 32],
        witness_id: [0x44; 16],
        high_watermark: 9,
        reservation_head: [0x55; 32],
        frontier_statement_digest: FRONTIER_DIGEST,
    };
    target.validate().unwrap();
    assert_eq!(target.recompute_operation_id(), OPERATION_ID);

    let anchor = XeniaSignedWitnessFrontierAnchorV1 {
        schema_version: XENIA_WITNESS_FRONTIER_ANCHOR_SCHEMA_VERSION,
        target,
        anchor_sequence: 1,
        previous_anchor_fingerprint: [0; 32],
        ledger_entry_count: 12,
        ledger_head_hash: [0x77; 32],
        ledger_public_key: PUBLIC_KEY,
        issued_at_unix_s: 1_000,
        signature: envelope(ANCHOR_SIGNATURE),
    };
    let anchor_message = anchor.canonical_message().unwrap();
    assert_eq!(anchor_message.len(), 384);
    assert_eq!(key.sign(&anchor_message).to_bytes(), ANCHOR_SIGNATURE);
    anchor.verify_with_trusted_key(PUBLIC_KEY).unwrap();
    assert_eq!(anchor.fingerprint().unwrap(), ANCHOR_FINGERPRINT);

    let observation = XeniaSignedWitnessFrontierObservationV1 {
        schema_version: XENIA_WITNESS_FRONTIER_ANCHOR_SCHEMA_VERSION,
        source_id: SOURCE_ID,
        source_epoch: 3,
        anchor_policy_digest: [0x33; 32],
        witness_id: [0x44; 16],
        challenge: [0x66; 32],
        observed_at_unix_s: 1_010,
        current: Some(XeniaWitnessFrontierAnchorSummaryV1 {
            anchor_sequence: 1,
            anchor_fingerprint: ANCHOR_FINGERPRINT,
            operation_id: OPERATION_ID,
            high_watermark: 9,
            reservation_head: [0x55; 32],
            frontier_statement_digest: FRONTIER_DIGEST,
        }),
        ledger_entry_count: 13,
        ledger_head_hash: [0x88; 32],
        ledger_public_key: PUBLIC_KEY,
        signature: envelope(OBSERVATION_SIGNATURE),
    };
    let observation_message = observation.canonical_message().unwrap();
    assert_eq!(observation_message.len(), 369);
    assert_eq!(key.sign(&observation_message).to_bytes(), OBSERVATION_SIGNATURE);
    observation.verify_with_trusted_key(PUBLIC_KEY).unwrap();
    assert_eq!(observation.fingerprint().unwrap(), OBSERVATION_FINGERPRINT);
}
