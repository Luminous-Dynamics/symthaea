/// EEG frequency bands with standard clinical ranges.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum EegBand {
    /// Delta: 0.5-4 Hz (deep sleep, unconscious processing)
    Delta,
    /// Theta: 4-8 Hz (memory encoding, drowsiness)
    Theta,
    /// Alpha: 8-13 Hz (relaxed wakefulness, visual cortex idle)
    Alpha,
    /// Beta: 13-30 Hz (active thinking, focus, motor planning)
    Beta,
    /// Gamma: 30-100 Hz (consciousness binding, attention, perception)
    Gamma,
}

impl EegBand {
    pub const ALL: [EegBand; 5] = [
        EegBand::Delta,
        EegBand::Theta,
        EegBand::Alpha,
        EegBand::Beta,
        EegBand::Gamma,
    ];

    pub fn as_str(&self) -> &'static str {
        match self {
            EegBand::Delta => "delta",
            EegBand::Theta => "theta",
            EegBand::Alpha => "alpha",
            EegBand::Beta => "beta",
            EegBand::Gamma => "gamma",
        }
    }

    /// Frequency range in Hz.
    pub fn range_hz(&self) -> (f32, f32) {
        match self {
            EegBand::Delta => (0.5, 4.0),
            EegBand::Theta => (4.0, 8.0),
            EegBand::Alpha => (8.0, 13.0),
            EegBand::Beta => (13.0, 30.0),
            EegBand::Gamma => (30.0, 100.0),
        }
    }
}

/// Per-region EEG power spectrum snapshot.
///
/// Maps each CorticalRegion × EegBand to a power value (μV²/Hz).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EegPowerMap {
    /// Power per region per band.
    pub powers: HashMap<CorticalRegion, HashMap<EegBand, f32>>,
    /// Timestamp (cycle number or milliseconds).
    pub timestamp: u64,
    /// Source of the data.
    pub source: ActivationSource,
}

impl EegPowerMap {
    /// Create with all bands at zero for all regions.
    pub fn zeros(source: ActivationSource, timestamp: u64) -> Self {
        let powers = CorticalRegion::ALL
            .iter()
            .map(|r| {
                let bands: HashMap<EegBand, f32> = EegBand::ALL.iter().map(|b| (*b, 0.0)).collect();
                (*r, bands)
            })
            .collect();
        Self {
            powers,
            timestamp,
            source,
        }
    }

    /// Set power for a specific region and band.
    pub fn set(&mut self, region: CorticalRegion, band: EegBand, value: f32) {
        self.powers
            .entry(region)
            .or_default()
            .insert(band, value.max(0.0));
    }

    /// Get power for a specific region and band.
    pub fn get(&self, region: CorticalRegion, band: EegBand) -> f32 {
        self.powers
            .get(&region)
            .and_then(|m| m.get(&band))
            .copied()
            .unwrap_or(0.0)
    }

    /// Get total power across all bands for a region.
    pub fn total_power(&self, region: CorticalRegion) -> f32 {
        self.powers
            .get(&region)
            .map(|m| m.values().sum())
            .unwrap_or(0.0)
    }

    /// Compute correlation of band power profiles between two EEG maps.
    /// Flattens all (region, band) pairs into a vector, computes Pearson r.
    pub fn correlation(&self, other: &Self) -> f64 {
        let mut a = Vec::new();
        let mut b = Vec::new();
        for region in CorticalRegion::ALL {
            for band in EegBand::ALL {
                a.push(self.get(region, band) as f64);
                b.push(other.get(region, band) as f64);
            }
        }
        pearson_f64(&a, &b)
    }
}

/// Simulated EEG power from cortical activations.
///
/// Maps activation levels to plausible EEG band powers based on
/// neuroscience priors (e.g., high visual activation → high gamma in Visual).
pub fn activations_to_eeg(map: &CorticalActivationMap) -> EegPowerMap {
    let mut eeg = EegPowerMap::zeros(map.source, map.timestamp_cycles);

    for region in CorticalRegion::ALL {
        let activation = map.get(region) as f64;

        // Base power distribution (resting state, eyes open).
        // Alpha dominant, beta moderate, gamma low.
        let delta_base = 0.3;
        let theta_base = 0.2;
        let alpha_base = 0.5;
        let beta_base = 0.3;
        let gamma_base = 0.1;

        // Activation modulates: ↑activation → ↑beta/gamma, ↓alpha (desynchronization).
        // This is the standard ERD/ERS pattern (Pfurtscheller & Lopes da Silva 1999).
        let alpha = (alpha_base * (1.0 - 0.6 * activation)).max(0.05) as f32;
        let beta = (beta_base + 0.4 * activation) as f32;
        let gamma = (gamma_base + 0.5 * activation) as f32;
        let theta = (theta_base + 0.15 * activation) as f32;
        let delta = (delta_base * (1.0 - 0.3 * activation)).max(0.1) as f32;

        eeg.set(region, EegBand::Delta, delta);
        eeg.set(region, EegBand::Theta, theta);
        eeg.set(region, EegBand::Alpha, alpha);
        eeg.set(region, EegBand::Beta, beta);
        eeg.set(region, EegBand::Gamma, gamma);
    }

    eeg
}

/// Pearson correlation on f64 slices.
pub fn pearson_f64(a: &[f64], b: &[f64]) -> f64 {
    let n = a.len() as f64;
    if n < 2.0 {
        return 0.0;
    }
    let mean_a: f64 = a.iter().sum::<f64>() / n;
    let mean_b: f64 = b.iter().sum::<f64>() / n;
    let mut cov = 0.0;
    let mut var_a = 0.0;
    let mut var_b = 0.0;
    for (x, y) in a.iter().zip(b.iter()) {
        let da = x - mean_a;
        let db = y - mean_b;
        cov += da * db;
        var_a += da * da;
        var_b += db * db;
    }
    let denom = (var_a * var_b).sqrt();
    if denom < 1e-12 {
        return 0.0;
    }
    cov / denom
}

