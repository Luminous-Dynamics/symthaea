#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_zeros_map() {
        let map = CorticalActivationMap::zeros(ActivationSource::Simulated, 0);
        assert_eq!(map.activations.len(), 12);
        for r in CorticalRegion::ALL {
            assert_eq!(map.get(r), 0.0);
        }
    }

    #[test]
    fn test_set_clamps() {
        let mut map = CorticalActivationMap::zeros(ActivationSource::Simulated, 0);
        map.set(CorticalRegion::Visual, 1.5);
        assert_eq!(map.get(CorticalRegion::Visual), 1.0);
        map.set(CorticalRegion::Motor, -0.3);
        assert_eq!(map.get(CorticalRegion::Motor), 0.0);
    }

    #[test]
    fn test_to_vec_order() {
        let mut map = CorticalActivationMap::zeros(ActivationSource::Simulated, 0);
        map.set(CorticalRegion::Prefrontal, 0.9);
        map.set(CorticalRegion::Integration, 0.1);
        let v = map.to_vec();
        assert_eq!(v.len(), 12);
        assert_eq!(v[0], 0.9); // Prefrontal is first in ALL
        assert_eq!(v[11], 0.1); // Integration is last in ALL
    }

    #[test]
    fn test_cosine_identical() {
        let mut a = CorticalActivationMap::zeros(ActivationSource::Simulated, 0);
        a.set(CorticalRegion::Visual, 0.8);
        a.set(CorticalRegion::Auditory, 0.4);
        let b = a.clone();
        let sim = a.cosine_similarity(&b);
        assert!(
            (sim - 1.0).abs() < 1e-6,
            "identical maps should have cosine=1, got {sim}"
        );
    }

    #[test]
    fn test_cosine_orthogonal() {
        let mut a = CorticalActivationMap::zeros(ActivationSource::Simulated, 0);
        a.set(CorticalRegion::Visual, 1.0);
        let mut b = CorticalActivationMap::zeros(ActivationSource::FmriPredicted, 0);
        b.set(CorticalRegion::Auditory, 1.0);
        let sim = a.cosine_similarity(&b);
        assert!(
            sim.abs() < 1e-6,
            "orthogonal maps should have cosine=0, got {sim}"
        );
    }

    #[test]
    fn test_cosine_zero_vector() {
        let a = CorticalActivationMap::zeros(ActivationSource::Simulated, 0);
        let mut b = CorticalActivationMap::zeros(ActivationSource::FmriPredicted, 0);
        b.set(CorticalRegion::Visual, 0.5);
        assert_eq!(a.cosine_similarity(&b), 0.0);
    }

    #[test]
    fn test_pearson_perfect() {
        let mut a = CorticalActivationMap::zeros(ActivationSource::Simulated, 0);
        let mut b = CorticalActivationMap::zeros(ActivationSource::FmriPredicted, 0);
        // Set matching pattern: a and b have same rank order with linear scaling
        // that stays within [0, 1] (set() clamps).
        for (i, r) in CorticalRegion::ALL.iter().enumerate() {
            let v = (i as f32 + 1.0) / 24.0; // max = 0.5
            a.set(*r, v);
            b.set(*r, v * 2.0); // max = 1.0, still within clamp range
        }
        let r = a.pearson_correlation(&b);
        assert!(
            (r - 1.0).abs() < 1e-6,
            "perfectly correlated should give r=1, got {r}"
        );
    }

    #[test]
    fn test_pearson_anti_correlated() {
        let mut a = CorticalActivationMap::zeros(ActivationSource::Simulated, 0);
        let mut b = CorticalActivationMap::zeros(ActivationSource::FmriPredicted, 0);
        for (i, r) in CorticalRegion::ALL.iter().enumerate() {
            a.set(*r, (i as f32 + 1.0) / 12.0);
            b.set(*r, 1.0 - (i as f32 + 1.0) / 12.0);
        }
        let r = a.pearson_correlation(&b);
        assert!(
            (r - (-1.0)).abs() < 1e-6,
            "anti-correlated should give r=-1, got {r}"
        );
    }

    #[test]
    fn test_spearman_rank() {
        let mut a = CorticalActivationMap::zeros(ActivationSource::Simulated, 0);
        let mut b = CorticalActivationMap::zeros(ActivationSource::FmriPredicted, 0);
        // Same rank order but different magnitudes.
        for (i, r) in CorticalRegion::ALL.iter().enumerate() {
            a.set(*r, (i as f32 + 1.0) / 12.0);
            b.set(*r, ((i as f32 + 1.0) / 12.0).powi(2));
        }
        let rho = a.spearman_rank_correlation(&b);
        assert!(
            (rho - 1.0).abs() < 1e-6,
            "same rank order should give rho=1, got {rho}"
        );
    }

    #[test]
    fn test_per_region_difference() {
        let mut a = CorticalActivationMap::zeros(ActivationSource::Simulated, 0);
        let mut b = CorticalActivationMap::zeros(ActivationSource::FmriPredicted, 0);
        a.set(CorticalRegion::Visual, 0.8);
        b.set(CorticalRegion::Visual, 0.3);
        let diff = a.per_region_difference(&b);
        assert!((diff[&CorticalRegion::Visual] - 0.5).abs() < 1e-6);
        assert!((diff[&CorticalRegion::Motor] - 0.0).abs() < 1e-6);
    }

    #[test]
    fn test_timeseries_region_extraction() {
        let mut ts = CorticalActivationTimeseries::new(31.0);
        for i in 0..5 {
            let mut map = CorticalActivationMap::zeros(ActivationSource::Simulated, i);
            map.set(CorticalRegion::Visual, i as f32 * 0.1);
            ts.push(map);
        }
        let visual_ts = ts.region_timeseries(CorticalRegion::Visual);
        assert_eq!(visual_ts, vec![0.0, 0.1, 0.2, 0.3, 0.4]);
    }

    #[test]
    fn test_timeseries_duration() {
        let mut ts = CorticalActivationTimeseries::new(31.0);
        for i in 0..62 {
            ts.push(CorticalActivationMap::zeros(ActivationSource::Simulated, i));
        }
        assert!((ts.duration_secs() - 2.0).abs() < 0.01);
    }

    #[test]
    fn test_ranks_with_ties() {
        let ranks = to_ranks(&[0.5, 0.3, 0.5, 0.1]);
        // Sorted: 0.1(idx3)=rank1, 0.3(idx1)=rank2, 0.5(idx0,2)=rank3.5
        assert!((ranks[3] - 1.0).abs() < 1e-6);
        assert!((ranks[1] - 2.0).abs() < 1e-6);
        assert!((ranks[0] - 3.5).abs() < 1e-6);
        assert!((ranks[2] - 3.5).abs() < 1e-6);
    }

    // ── EEG tests ──

    #[test]
    fn test_eeg_zeros() {
        let eeg = EegPowerMap::zeros(ActivationSource::Simulated, 0);
        for region in CorticalRegion::ALL {
            for band in EegBand::ALL {
                assert_eq!(eeg.get(region, band), 0.0);
            }
        }
    }

    #[test]
    fn test_eeg_set_get() {
        let mut eeg = EegPowerMap::zeros(ActivationSource::Simulated, 0);
        eeg.set(CorticalRegion::Visual, EegBand::Gamma, 0.8);
        assert!((eeg.get(CorticalRegion::Visual, EegBand::Gamma) - 0.8).abs() < 1e-6);
        assert_eq!(eeg.get(CorticalRegion::Visual, EegBand::Alpha), 0.0);
    }

    #[test]
    fn test_eeg_total_power() {
        let mut eeg = EegPowerMap::zeros(ActivationSource::Simulated, 0);
        eeg.set(CorticalRegion::Visual, EegBand::Alpha, 0.5);
        eeg.set(CorticalRegion::Visual, EegBand::Gamma, 0.3);
        let total = eeg.total_power(CorticalRegion::Visual);
        assert!((total - 0.8).abs() < 1e-6);
    }

    #[test]
    fn test_eeg_correlation_identical() {
        let mut eeg = EegPowerMap::zeros(ActivationSource::Simulated, 0);
        eeg.set(CorticalRegion::Visual, EegBand::Gamma, 0.8);
        eeg.set(CorticalRegion::Auditory, EegBand::Alpha, 0.5);
        let r = eeg.correlation(&eeg);
        assert!((r - 1.0).abs() < 1e-6);
    }

    #[test]
    fn test_activations_to_eeg_desynchronization() {
        // High visual activation → alpha should decrease (ERD), gamma should increase (ERS).
        let mut low = CorticalActivationMap::zeros(ActivationSource::Simulated, 0);
        low.set(CorticalRegion::Visual, 0.1);
        let mut high = CorticalActivationMap::zeros(ActivationSource::Simulated, 1);
        high.set(CorticalRegion::Visual, 0.9);

        let eeg_low = activations_to_eeg(&low);
        let eeg_high = activations_to_eeg(&high);

        // Alpha should decrease with activation (ERD).
        assert!(
            eeg_high.get(CorticalRegion::Visual, EegBand::Alpha)
                < eeg_low.get(CorticalRegion::Visual, EegBand::Alpha),
            "Alpha should decrease with activation (event-related desynchronization)"
        );
        // Gamma should increase with activation (ERS).
        assert!(
            eeg_high.get(CorticalRegion::Visual, EegBand::Gamma)
                > eeg_low.get(CorticalRegion::Visual, EegBand::Gamma),
            "Gamma should increase with activation (event-related synchronization)"
        );
    }

    #[test]
    fn test_eeg_band_ranges() {
        assert_eq!(EegBand::Alpha.range_hz(), (8.0, 13.0));
        assert_eq!(EegBand::Gamma.range_hz(), (30.0, 100.0));
        assert_eq!(EegBand::ALL.len(), 5);
    }
}
