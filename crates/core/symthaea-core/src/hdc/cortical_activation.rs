//! Cortical Activation Map — per-region activation tracking for neural validation.
//!
//! Provides explicit per-region activation vectors that can be compared against
//! external neuroscience ground-truth (e.g., TRIBE v2 fMRI predictions from Meta FAIR).
//!
//! Each cognitive cycle produces a `CorticalActivationMap` with normalized [0,1]
//! activation levels for each of the 12 `CorticalRegion` variants. These maps
//! can then be compared via cosine similarity, Pearson correlation, or rank
//! correlation against externally predicted or observed fMRI activation patterns.
//!
//! # References
//!
//! - Glasser et al. (2016). A multi-modal parcellation of human cerebral cortex.
//!   *Nature*, 536, 171-178. doi:10.1038/nature18933
//! - TRIBE v2 (Meta FAIR, 2026). Tri-modal brain encoding for fMRI prediction.

use serde::{Deserialize, Serialize};
use std::collections::HashMap;

use super::substrate_independence::CorticalRegion;

/// Source of the activation data.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum ActivationSource {
    /// Generated by Symthaea's cognitive loop (simulated dynamics).
    Simulated,
    /// Predicted by an external brain encoding model (e.g., TRIBE v2).
    FmriPredicted,
    /// Observed from actual fMRI recordings.
    FmriObserved,
    /// Observed from EEG recordings.
    EegObserved,
}

/// Per-region activation snapshot from a single cognitive cycle or time window.
///
/// Activations are normalized to [0.0, 1.0] where 0 = baseline and 1 = maximal
/// activation for that region.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CorticalActivationMap {
    /// Normalized activation level per region.
    pub activations: HashMap<CorticalRegion, f32>,
    /// Cycle number (for simulated) or time index (for fMRI).
    pub timestamp_cycles: u64,
    /// Where this data came from.
    pub source: ActivationSource,
    /// Optional stimulus identifier for cross-system comparison.
    pub stimulus_id: Option<String>,
}

impl CorticalActivationMap {
    /// Create a new activation map with all regions at zero.
    pub fn zeros(source: ActivationSource, timestamp_cycles: u64) -> Self {
        let activations = CorticalRegion::ALL.iter().map(|r| (*r, 0.0)).collect();
        Self {
            activations,
            timestamp_cycles,
            source,
            stimulus_id: None,
        }
    }

    /// Create from a pre-built hashmap.
    pub fn from_map(
        activations: HashMap<CorticalRegion, f32>,
        source: ActivationSource,
        timestamp_cycles: u64,
    ) -> Self {
        Self {
            activations,
            timestamp_cycles,
            source,
            stimulus_id: None,
        }
    }

    /// Set a region's activation level, clamping to [0, 1].
    pub fn set(&mut self, region: CorticalRegion, value: f32) {
        self.activations.insert(region, value.clamp(0.0, 1.0));
    }

    /// Get a region's activation (0.0 if absent).
    pub fn get(&self, region: CorticalRegion) -> f32 {
        self.activations.get(&region).copied().unwrap_or(0.0)
    }

    /// Convert to a 12-element vector in `CorticalRegion::ALL` order.
    pub fn to_vec(&self) -> Vec<f32> {
        CorticalRegion::ALL.iter().map(|r| self.get(*r)).collect()
    }

    /// Cosine similarity with another activation map.
    ///
    /// Returns a value in [-1, 1] (though typically [0, 1] since activations
    /// are non-negative). Returns 0.0 if either vector is zero.
    pub fn cosine_similarity(&self, other: &Self) -> f64 {
        let a = self.to_vec();
        let b = other.to_vec();

        let dot: f64 = a
            .iter()
            .zip(b.iter())
            .map(|(x, y)| *x as f64 * *y as f64)
            .sum();
        let mag_a: f64 = a.iter().map(|x| (*x as f64).powi(2)).sum::<f64>().sqrt();
        let mag_b: f64 = b.iter().map(|x| (*x as f64).powi(2)).sum::<f64>().sqrt();

        if mag_a < 1e-12 || mag_b < 1e-12 {
            return 0.0;
        }
        dot / (mag_a * mag_b)
    }

    /// Pearson correlation with another activation map.
    ///
    /// Returns r in [-1, 1]. Returns 0.0 if either has zero variance.
    pub fn pearson_correlation(&self, other: &Self) -> f64 {
        let a = self.to_vec();
        let b = other.to_vec();
        let n = a.len() as f64;

        let mean_a: f64 = a.iter().map(|x| *x as f64).sum::<f64>() / n;
        let mean_b: f64 = b.iter().map(|x| *x as f64).sum::<f64>() / n;

        let mut cov = 0.0;
        let mut var_a = 0.0;
        let mut var_b = 0.0;
        for (x, y) in a.iter().zip(b.iter()) {
            let da = *x as f64 - mean_a;
            let db = *y as f64 - mean_b;
            cov += da * db;
            var_a += da * da;
            var_b += db * db;
        }

        let denom = (var_a * var_b).sqrt();
        if denom < 1e-12 {
            return 0.0;
        }
        cov / denom
    }

    /// Spearman rank correlation with another activation map.
    ///
    /// Converts activations to ranks, then computes Pearson on ranks.
    pub fn spearman_rank_correlation(&self, other: &Self) -> f64 {
        let ranks_a = to_ranks(&self.to_vec());
        let ranks_b = to_ranks(&other.to_vec());
        pearson_on_ranks(&ranks_a, &ranks_b)
    }

    /// Per-region absolute difference (useful for identifying which regions
    /// diverge most between simulated and predicted).
    pub fn per_region_difference(&self, other: &Self) -> HashMap<CorticalRegion, f32> {
        CorticalRegion::ALL
            .iter()
            .map(|r| (*r, (self.get(*r) - other.get(*r)).abs()))
            .collect()
    }
}

/// Timeseries of cortical activations (for HRF convolution and temporal analysis).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CorticalActivationTimeseries {
    /// Ordered sequence of activation maps.
    pub maps: Vec<CorticalActivationMap>,
    /// Sample rate in Hz (e.g., 31.0 for Symthaea's cognitive loop).
    pub sample_rate_hz: f32,
}

impl CorticalActivationTimeseries {
    pub fn new(sample_rate_hz: f32) -> Self {
        Self {
            maps: Vec::new(),
            sample_rate_hz,
        }
    }

    pub fn push(&mut self, map: CorticalActivationMap) {
        self.maps.push(map);
    }

    /// Extract a single region's timeseries as a Vec<f32>.
    pub fn region_timeseries(&self, region: CorticalRegion) -> Vec<f32> {
        self.maps.iter().map(|m| m.get(region)).collect()
    }

    /// Duration in seconds.
    pub fn duration_secs(&self) -> f32 {
        if self.sample_rate_hz <= 0.0 || self.maps.is_empty() {
            return 0.0;
        }
        self.maps.len() as f32 / self.sample_rate_hz
    }
}

