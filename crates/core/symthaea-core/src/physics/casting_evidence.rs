//! Provenance-aware train/calibration/holdout manifests for casting research.
//!
//! This module is a software evidence boundary, not a foundry qualification system.
//! It records which evidence populations were used for fitting, conformal calibration,
//! and final evaluation, and refuses common forms of identifier/source-record leakage.
//!
//! Identifiers and digests cannot prove that trials were physically independent or that
//! a source record is truthful. Those remain protocol/audit obligations. The manifest
//! does make declarations deterministic, inspectable, and independently reproducible.

use std::collections::HashMap;
use std::error::Error;
use std::fmt;

use super::casting::{
    CastingModelError, ChvorinovConformalCalibrator, ChvorinovModel, ChvorinovObservation,
};

/// A source class for a casting observation.
///
/// These classes describe evidence provenance only. They do not imply accuracy,
/// process capability, acceptance, or fitness for service.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum CastingEvidenceClass {
    /// Algorithmic fixture generated only to test arithmetic or software semantics.
    Synthetic = 0,
    /// Output generated by a numerical or statistical model, not measured from a part.
    Simulated = 1,
    /// Previously collected records replayed for reproducibility testing.
    HistoricalReplay = 2,
    /// Observation measured from a physical casting under a documented protocol.
    MeasuredPhysical = 3,
    /// Physical result independently repeated under a declared replication protocol.
    IndependentlyReplicated = 4,
}

impl CastingEvidenceClass {
    /// Number of stable evidence classes in this schema version.
    pub const COUNT: usize = 5;

    const fn index(self) -> usize {
        self as usize
    }
}

/// Name of one partition in a casting benchmark split.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CastingDataPartition {
    /// Observations used to fit the point prediction model.
    Training,
    /// Disjoint observations used to calibrate prediction intervals.
    ConformalCalibration,
    /// Final observations reserved for evaluation.
    Holdout,
}

impl CastingDataPartition {
    const fn as_u8(self) -> u8 {
        match self {
            Self::Training => 0,
            Self::ConformalCalibration => 1,
            Self::Holdout => 2,
        }
    }
}

/// An evidence-bound solidification observation.
///
/// All digests are BLAKE3 digests supplied by the caller:
/// - process_population_digest binds the declared alloy/material, mold/tooling,
///   measurement protocol, and other applicability dimensions of this study;
/// - geometry_digest identifies the exact geometry subject;
/// - source_record_digest identifies the immutable originating observation record.
///
/// A non-zero digest is only a structural safeguard against omitted placeholders; it
/// does not verify the source artifact itself. The upstream evidence system must retain
/// the artifact and independently verify that its digest is correct.
#[derive(Debug, Clone, PartialEq)]
pub struct CastingObservationRecord {
    observation_id: String,
    observation: ChvorinovObservation,
    evidence_class: CastingEvidenceClass,
    process_population_digest: [u8; 32],
    geometry_digest: [u8; 32],
    source_record_digest: [u8; 32],
}

impl CastingObservationRecord {
    /// Construct a validated observation record.
    ///
    /// Observation IDs are opaque, case-sensitive identities. They are not normalized:
    /// callers must use the same canonical ID in every representation of a record.
    pub fn new(
        observation_id: impl Into<String>,
        observation: ChvorinovObservation,
        evidence_class: CastingEvidenceClass,
        process_population_digest: [u8; 32],
        geometry_digest: [u8; 32],
        source_record_digest: [u8; 32],
    ) -> Result<Self, CastingEvidenceError> {
        let observation_id = observation_id.into();
        if observation_id.trim().is_empty()
            || observation_id.trim() != observation_id
            || observation_id.len() > 256
            || observation_id.chars().any(char::is_control)
        {
            return Err(CastingEvidenceError::InvalidObservationId);
        }
        if !observation.thermal_modulus_m.is_finite()
            || observation.thermal_modulus_m <= 0.0
            || !observation.solidification_time_s.is_finite()
            || observation.solidification_time_s <= 0.0
        {
            return Err(CastingEvidenceError::InvalidMeasurement {
                observation_id,
            });
        }
        for (field, digest) in [
            ("process_population_digest", process_population_digest),
            ("geometry_digest", geometry_digest),
            ("source_record_digest", source_record_digest),
        ] {
            if digest == [0; 32] {
                return Err(CastingEvidenceError::MissingEvidenceDigest { field });
            }
        }

        Ok(Self {
            observation_id,
            observation,
            evidence_class,
            process_population_digest,
            geometry_digest,
            source_record_digest,
        })
    }

    /// Return the stable observation identity.
    pub fn observation_id(&self) -> &str {
        &self.observation_id
    }

    /// Return the numeric observation after construction-time validation.
    pub fn observation(&self) -> ChvorinovObservation {
        self.observation
    }

    /// Return the declared source class.
    pub fn evidence_class(&self) -> CastingEvidenceClass {
        self.evidence_class
    }

    /// Return the digest of the declared applicable process population.
    pub fn process_population_digest(&self) -> [u8; 32] {
        self.process_population_digest
    }

    /// Return the exact geometry digest.
    pub fn geometry_digest(&self) -> [u8; 32] {
        self.geometry_digest
    }

    /// Return the digest of the immutable source record.
    pub fn source_record_digest(&self) -> [u8; 32] {
        self.source_record_digest
    }

    fn digest(&self) -> [u8; 32] {
        let mut hasher = blake3::Hasher::new();
        hasher.update(b"symthaea-casting-observation-record-v1");
        update_len_prefixed(&mut hasher, self.observation_id.as_bytes());
        hasher.update(&self.observation.thermal_modulus_m.to_bits().to_le_bytes());
        hasher.update(&self.observation.solidification_time_s.to_bits().to_le_bytes());
        hasher.update(&[self.evidence_class as u8]);
        hasher.update(&self.process_population_digest);
        hasher.update(&self.geometry_digest);
        hasher.update(&self.source_record_digest);
        *hasher.finalize().as_bytes()
    }
}

/// Why a casting split manifest could not be constructed or verified.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CastingEvidenceError {
    /// Observation ID is empty, has outer whitespace, is too long, or contains controls.
    InvalidObservationId,
    /// Numeric observation values are not finite and strictly positive.
    InvalidMeasurement {
        /// ID of the observation that failed validation.
        observation_id: String,
    },
    /// Required source/applicability digest is all zeros.
    MissingEvidenceDigest {
        /// Name of the missing digest field.
        field: &'static str,
    },
    /// A required partition contains no observations.
    EmptyPartition {
        /// Empty partition.
        partition: CastingDataPartition,
    },
    /// Training partition contains too few records for the casting model contract.
    InsufficientTrainingRecords {
        /// Number of supplied training records.
        actual: usize,
        /// Required minimum.
        minimum: usize,
    },
    /// Miscoverage probability is not finite and strictly between zero and one.
    InvalidMiscoverage,
    /// Same observation ID appears multiple times, including across partitions.
    DuplicateObservationId {
        /// Repeated identity.
        observation_id: String,
        /// First partition in which this identity appeared.
        first_partition: CastingDataPartition,
        /// Partition in which it appeared again.
        repeated_partition: CastingDataPartition,
    },
    /// Same source record digest was reused under one or more observation IDs.
    DuplicateSourceRecord {
        /// First partition in which the source digest appeared.
        first_partition: CastingDataPartition,
        /// Partition in which the source digest appeared again.
        repeated_partition: CastingDataPartition,
    },
    /// Records claim incompatible process-population applicability.
    MixedProcessPopulation {
        /// First partition that established the population digest.
        first_partition: CastingDataPartition,
        /// Partition containing the conflicting digest.
        conflicting_partition: CastingDataPartition,
    },
    /// Calibration set contains more than one evidence class.
    MixedCalibrationEvidenceClasses,
    /// Holdout set contains more than one evidence class.
    MixedHoldoutEvidenceClasses,
    /// Calibration and holdout use different evidence classes.
    CalibrationHoldoutEvidenceMismatch {
        /// Evidence class of the calibration set.
        calibration: CastingEvidenceClass,
        /// Evidence class of the holdout set.
        holdout: CastingEvidenceClass,
    },
    /// Training values/order do not match the observations that fitted the model.
    TrainingDataModelMismatch,
    /// Calibration values/order do not match the observations used by the calibrator.
    CalibrationDataMismatch,
    /// The conformal calibrator was created from a different fitted model.
    ConformalCalibratorModelMismatch,
    /// The conformal calibrator sample count does not match the declared calibration partition.
    CalibrationSampleCountMismatch {
        /// Number of observations bound by the calibrator.
        calibrator_count: usize,
        /// Number of records in the declared calibration partition.
        partition_count: usize,
    },
    /// Provided records do not reproduce the manifest's digest.
    ManifestDigestMismatch,
}

impl fmt::Display for CastingEvidenceError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidObservationId => f.write_str(
                "casting observation ID must be non-empty, trimmed, at most 256 bytes, and contain no control characters",
            ),
            Self::InvalidMeasurement { observation_id } => write!(
                f,
                "casting observation {observation_id} must contain finite positive values"
            ),
            Self::MissingEvidenceDigest { field } => {
                write!(f, "casting observation requires a non-zero {field}")
            }
            Self::EmptyPartition { partition } => {
                write!(f, "casting benchmark partition {partition:?} is empty")
            }
            Self::InsufficientTrainingRecords { actual, minimum } => write!(
                f,
                "casting benchmark needs at least {minimum} training records; received {actual}"
            ),
            Self::InvalidMiscoverage => {
                f.write_str("casting benchmark miscoverage must be finite and strictly between 0 and 1")
            }
            Self::DuplicateObservationId {
                observation_id,
                first_partition,
                repeated_partition,
            } => write!(
                f,
                "casting observation ID {observation_id} occurs in both {first_partition:?} and {repeated_partition:?}"
            ),
            Self::DuplicateSourceRecord {
                first_partition,
                repeated_partition,
            } => write!(
                f,
                "casting source record digest is reused in {first_partition:?} and {repeated_partition:?}"
            ),
            Self::MixedProcessPopulation {
                first_partition,
                conflicting_partition,
            } => write!(
                f,
                "casting process-population digest differs between {first_partition:?} and {conflicting_partition:?}"
            ),
            Self::MixedCalibrationEvidenceClasses => {
                f.write_str("conformal calibration must use one declared evidence class")
            }
            Self::MixedHoldoutEvidenceClasses => {
                f.write_str("casting holdout must use one declared evidence class")
            }
            Self::CalibrationHoldoutEvidenceMismatch {
                calibration,
                holdout,
            } => write!(
                f,
                "casting calibration evidence class {calibration:?} does not match holdout class {holdout:?}"
            ),
            Self::TrainingDataModelMismatch => {
                f.write_str("casting training records do not reproduce the fitted model's ordered training-data digest")
            }
            Self::CalibrationDataMismatch => {
                f.write_str("casting calibration records do not reproduce the conformal calibrator's ordered calibration-data digest")
            }
            Self::ConformalCalibratorModelMismatch => {
                f.write_str("casting conformal calibrator is bound to a different fitted model")
            }
            Self::CalibrationSampleCountMismatch {
                calibrator_count,
                partition_count,
            } => write!(
                f,
                "casting conformal calibrator binds {calibrator_count} observations but the partition has {partition_count} records"
            ),
            Self::ManifestDigestMismatch => {
                f.write_str("casting benchmark inputs do not reproduce the manifest digest")
            }
        }
    }
}

impl Error for CastingEvidenceError {}

