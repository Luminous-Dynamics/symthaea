    fn broken_coordinate_chain_fails() {
        let mut p = surrogate();
        p.coordinate_system = CoordinateSystem::Symthaea12;
        let mut chain = two_hop_chain();
        chain[1].from = CoordinateSystem::DesikanKilliany68;
        p.coordinate_transforms = chain;
        assert_eq!(
            p.validate(),
            Err(ProvenanceError::TransformChainSourceMismatch {
                index: 1,
                expected: CoordinateSystem::Glasser360,
                found: CoordinateSystem::DesikanKilliany68
            })
        );
    }

    #[test]
    fn transforms_validate_identity_version_digest_and_deserialization() {
        let valid = CoordinateTransformProvenance {
            from: CoordinateSystem::FsAverage5,
            to: CoordinateSystem::Glasser360,
            transform_id: "fsaverage5-to-glasser360".into(),
            transform_version: "1".into(),
            source_digest: SHA_A.into(),
        };
        let checked = valid.clone().validate().unwrap();
        assert_eq!(checked.from(), CoordinateSystem::FsAverage5);
        assert_eq!(checked.to(), CoordinateSystem::Glasser360);

        let bad = CoordinateTransformProvenance {
            to: CoordinateSystem::FsAverage5,
            ..valid
        };
        let json = serde_json::to_string(&bad).unwrap();
        assert!(serde_json::from_str::<ValidatedCoordinateTransform>(&json).is_err());
    }

