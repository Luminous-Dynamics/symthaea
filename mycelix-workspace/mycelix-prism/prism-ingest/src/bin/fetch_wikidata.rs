//! Fetches structured facts from Wikidata SPARQL endpoint and generates
//! a Rust source file with a const array of claims.
//!
//! Usage: cargo run --bin fetch_wikidata
//! Output: prism-ingest/src/wikidata_claims.rs

use std::collections::HashSet;
use std::fmt::Write as FmtWrite;
use std::io::Write;

const ENDPOINT: &str = "https://query.wikidata.org/sparql";

/// A category of SPARQL query with metadata for composing sentences.
struct QuerySpec {
    name: &'static str,
    sparql: &'static str,
    tags: &'static [&'static str],
    /// Function that composes a natural English sentence from result bindings.
    compose: fn(&serde_json::Value) -> Option<String>,
}

fn main() {
    let queries = build_queries();
    let client = reqwest::blocking::Client::builder()
        .user_agent("PrismIngest/0.1 (https://luminousdynamics.org; tristan.stoltz@evolvingresonantcocreationism.com)")
        .timeout(std::time::Duration::from_secs(90))
        .build()
        .expect("Failed to build HTTP client");

    let mut all_claims: Vec<(String, &[&str], &[&str])> = Vec::new();
    let mut seen = HashSet::new();

    for spec in &queries {
        eprintln!("Fetching: {} ...", spec.name);
        match fetch_query(&client, spec.sparql) {
            Ok(results) => {
                let mut count = 0;
                for binding in &results {
                    if let Some(sentence) = (spec.compose)(binding) {
                        let key = sentence.to_lowercase();
                        // Dedup on first 60 chars to collapse multi-field variants
                        // e.g. "Go is a programming language created in 2009 that follows the X paradigm"
                        // Find a valid char boundary at or before 60
                        let end = {
                            let max = key.len().min(60);
                            let mut i = max;
                            while i > 0 && !key.is_char_boundary(i) {
                                i -= 1;
                            }
                            i
                        };
                        let dedup_key = key[..end].to_string();
                        if key.len() > 20 && seen.insert(dedup_key) {
                            all_claims.push((sentence, spec.tags, &["Wikidata"]));
                            count += 1;
                        }
                    }
                }
                eprintln!("  -> {} claims from {}", count, spec.name);
            }
            Err(e) => {
                eprintln!("  ERROR fetching {}: {}", spec.name, e);
            }
        }
        // Be polite to Wikidata — generous delay to avoid 429s
        std::thread::sleep(std::time::Duration::from_millis(3000));
    }

    eprintln!("\nTotal claims: {}", all_claims.len());

    // Generate Rust source
    let mut output = String::new();
    writeln!(
        output,
        "//! Wikidata-sourced claims, auto-generated by `cargo run --bin fetch_wikidata`."
    )
    .unwrap();
    writeln!(
        output,
        "//! DO NOT EDIT — regenerate with the fetch_wikidata binary."
    )
    .unwrap();
    writeln!(output, "//!").unwrap();
    writeln!(output, "//! Generated: {}", chrono_now()).unwrap();
    writeln!(output).unwrap();
    writeln!(output, "use crate::RawClaim;").unwrap();
    writeln!(output, "use prism_common::EmpiricalLevel::*;").unwrap();
    writeln!(output).unwrap();
    writeln!(output, "pub fn wikidata_claims() -> Vec<RawClaim> {{").unwrap();
    writeln!(
        output,
        "    RAW.iter().map(|(content, e, sources, tags)| RawClaim {{"
    )
    .unwrap();
    writeln!(output, "        content: content.to_string(),").unwrap();
    writeln!(output, "        empirical_level: *e,").unwrap();
    writeln!(
        output,
        "        sources: sources.iter().map(|s| s.to_string()).collect(),"
    )
    .unwrap();
    writeln!(
        output,
        "        tags: tags.iter().map(|s| s.to_string()).collect(),"
    )
    .unwrap();
    writeln!(output, "    }}).collect()").unwrap();
    writeln!(output, "}}").unwrap();
    writeln!(output).unwrap();
    writeln!(
        output,
        "const RAW: &[(&str, prism_common::EmpiricalLevel, &[&str], &[&str])] = &["
    )
    .unwrap();

    for (sentence, tags, sources) in &all_claims {
        let escaped = sentence.replace('\\', "\\\\").replace('"', "\\\"");
        let tags_str = tags
            .iter()
            .map(|t| format!("\"{}\"", t))
            .collect::<Vec<_>>()
            .join(", ");
        let sources_str = sources
            .iter()
            .map(|s| format!("\"{}\"", s))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            output,
            "    (\"{}\", E4, &[{}], &[{}]),",
            escaped, sources_str, tags_str
        )
        .unwrap();
    }

    writeln!(output, "];").unwrap();

    let out_path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("src")
        .join("wikidata_claims.rs");
    let mut file = std::fs::File::create(&out_path).expect("Failed to create output file");
    file.write_all(output.as_bytes())
        .expect("Failed to write output");
    eprintln!(
        "Wrote {} claims to {}",
        all_claims.len(),
        out_path.display()
    );
}

fn chrono_now() -> String {
    // Simple timestamp without chrono dependency
    let output = std::process::Command::new("date")
        .arg("+%Y-%m-%d %H:%M:%S UTC")
        .output();
    match output {
        Ok(o) => String::from_utf8_lossy(&o.stdout).trim().to_string(),
        Err(_) => "unknown".to_string(),
    }
}

fn fetch_query(
    client: &reqwest::blocking::Client,
    sparql: &str,
) -> Result<Vec<serde_json::Value>, String> {
    let max_retries = 3;
    for attempt in 0..max_retries {
        let resp = client
            .get(ENDPOINT)
            .query(&[("query", sparql), ("format", "json")])
            .send()
            .map_err(|e| format!("HTTP error: {}", e))?;

        if resp.status() == reqwest::StatusCode::TOO_MANY_REQUESTS {
            if attempt < max_retries - 1 {
                let wait = 60; // Wikidata usually says retry in ~45s
                eprintln!(
                    "    Rate-limited, waiting {}s (attempt {}/{})...",
                    wait,
                    attempt + 1,
                    max_retries
                );
                std::thread::sleep(std::time::Duration::from_secs(wait));
                continue;
            }
            return Err("Rate-limited after max retries".to_string());
        }

        if !resp.status().is_success() {
            return Err(format!(
                "HTTP {}: {}",
                resp.status(),
                resp.text().unwrap_or_default()
            ));
        }

        let body: serde_json::Value = resp
            .json()
            .map_err(|e| format!("JSON parse error: {}", e))?;
        let bindings = body["results"]["bindings"]
            .as_array()
            .ok_or("No results.bindings array")?
            .clone();
        return Ok(bindings);
    }
    Err("Exhausted retries".to_string())
}

fn get_str<'a>(binding: &'a serde_json::Value, key: &str) -> Option<&'a str> {
    binding.get(key)?.get("value")?.as_str()
}

