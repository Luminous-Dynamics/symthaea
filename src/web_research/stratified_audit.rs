//! Stratified simple-random audit plans for selective adjudication.
//!
//! A custodian supplies independently generated uniform random priorities.
//! Within each pre-label stratum, selecting the n smallest unique priorities
//! implements simple random sampling without replacement, conditional on the
//! priorities being independent uniform draws. This module does not generate
//! entropy, authenticate the custodian, or expose hidden outcomes.
//!
//! The resulting first- and second-order inclusion probabilities are exact
//! for the declared design. They can support design-based Horvitz-Thompson
//! variance estimation; arbitrary/adaptive sampling designs need their own
//! joint-inclusion contract.

use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, HashSet};

pub const STRATIFIED_AUDIT_DESIGN_VERSION: &str = "symthaea-stratified-audit-srswor-v1";

/// One candidate in the complete, frozen, pre-label cohort.
///
/// random_priority must be supplied by an independent custodian using
/// independently uniform 128-bit draws. It is not generated by this module.
#[derive(Debug, Clone)]
pub struct AuditCandidate {
    pub record_id: String,
    pub stratum_id: String,
    pub random_priority: u128,
}

/// Fixed audit quota for one pre-label stratum.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AuditStratumQuota {
    pub stratum_id: String,
    pub sample_size: usize,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AuditStratumPlan {
    pub stratum_id: String,
    pub population_size: usize,
    pub sample_size: usize,
    pub sampling_fraction: f64,
    /// First-order inclusion probability n_h / N_h for every unit in stratum h.
    pub first_order_inclusion_probability: f64,
    /// Joint inclusion probability for two distinct units in this stratum:
    /// n_h(n_h-1) / (N_h(N_h-1)).
    pub distinct_pair_joint_inclusion_probability: f64,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AuditSelection {
    pub record_id: String,
    pub stratum_id: String,
    pub selected_for_adjudication: bool,
    pub inclusion_probability: f64,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct StratifiedAuditPlan {
    pub design_version: String,
    pub design_id: String,
    /// Reference to the externally frozen randomization manifest, including
    /// priority generation, cohort identity, stratum assignment and quotas.
    pub randomization_manifest_ref: String,
    pub population_size: usize,
    pub audit_sample_size: usize,
    pub strata: Vec<AuditStratumPlan>,
    /// Complete cohort, not just selected records, with each unit's inclusion
    /// probability. Entries are sorted by (stratum_id, record_id).
    pub selections: Vec<AuditSelection>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum StratifiedAuditError {
    EmptyDesignId,
    EmptyRandomizationManifestReference,
    EmptyCohort,
    EmptyRecordId,
    EmptyStratumId,
    DuplicateRecordId(String),
    DuplicatePriorityWithinStratum { stratum_id: String, priority: u128 },
    MissingQuota(String),
    DuplicateQuota(String),
    QuotaForUnknownStratum(String),
    InvalidQuota { stratum_id: String, sample_size: usize, population_size: usize },
}

impl std::fmt::Display for StratifiedAuditError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::EmptyDesignId => write!(formatter, "audit design ID must not be empty"),
            Self::EmptyRandomizationManifestReference => {
                write!(formatter, "randomization manifest reference must not be empty")
            }
            Self::EmptyCohort => write!(formatter, "audit cohort must not be empty"),
            Self::EmptyRecordId => write!(formatter, "record IDs must not be empty"),
            Self::EmptyStratumId => write!(formatter, "pre-label stratum IDs must not be empty"),
            Self::DuplicateRecordId(id) => write!(formatter, "duplicate record ID: {id}"),
            Self::DuplicatePriorityWithinStratum { stratum_id, priority } => write!(
                formatter,
                "duplicate random priority {priority} in stratum {stratum_id}"
            ),
            Self::MissingQuota(stratum) => {
                write!(formatter, "missing positive audit quota for stratum {stratum}")
            }
            Self::DuplicateQuota(stratum) => {
                write!(formatter, "duplicate audit quota for stratum {stratum}")
            }
            Self::QuotaForUnknownStratum(stratum) => {
                write!(formatter, "audit quota references unknown stratum {stratum}")
            }
            Self::InvalidQuota { stratum_id, sample_size, population_size } => write!(
                formatter,
                concat!(
                    "invalid audit quota {sample_size} for stratum {stratum_id} ",
                    "with population {population_size}"
                )
            ),
        }
    }
}

impl std::error::Error for StratifiedAuditError {}

/// Construct a reproducible stratified SRSWOR audit plan from custodian-supplied
/// random priorities. The output includes all candidate records and their
/// first-order inclusion probabilities, so the plan can be joined to the
/// propensity-aware evaluator without dropping pending/nonselected cases.
///
/// The independent-random-priority assumption and the frozen pre-label stratum
/// assignment must be audited outside this function.
pub fn build_stratified_random_audit_plan(
    candidates: &[AuditCandidate],
    quotas: &[AuditStratumQuota],
    design_id: impl Into<String>,
    randomization_manifest_ref: impl Into<String>,
) -> Result<StratifiedAuditPlan, StratifiedAuditError> {
    let design_id = design_id.into();
    let randomization_manifest_ref = randomization_manifest_ref.into();
    if design_id.trim().is_empty() {
        return Err(StratifiedAuditError::EmptyDesignId);
    }
    if randomization_manifest_ref.trim().is_empty() {
        return Err(StratifiedAuditError::EmptyRandomizationManifestReference);
    }
    if candidates.is_empty() {
        return Err(StratifiedAuditError::EmptyCohort);
    }

    let mut record_ids = HashSet::with_capacity(candidates.len());
    let mut grouped = BTreeMap::<String, Vec<&AuditCandidate>>::new();
    let mut priorities = BTreeMap::<String, HashSet<u128>>::new();

    for candidate in candidates {
        if candidate.record_id.trim().is_empty() {
            return Err(StratifiedAuditError::EmptyRecordId);
        }
        if candidate.stratum_id.trim().is_empty() {
            return Err(StratifiedAuditError::EmptyStratumId);
        }
        if !record_ids.insert(candidate.record_id.as_str()) {
            return Err(StratifiedAuditError::DuplicateRecordId(
                candidate.record_id.clone(),
            ));
        }
        if !priorities
            .entry(candidate.stratum_id.clone())
            .or_default()
            .insert(candidate.random_priority)
        {
            return Err(StratifiedAuditError::DuplicatePriorityWithinStratum {
                stratum_id: candidate.stratum_id.clone(),
                priority: candidate.random_priority,
            });
        }
        grouped
            .entry(candidate.stratum_id.clone())
            .or_default()
            .push(candidate);
    }

    let mut quota_by_stratum = BTreeMap::<String, usize>::new();
    for quota in quotas {
        if quota.stratum_id.trim().is_empty() {
            return Err(StratifiedAuditError::EmptyStratumId);
        }
        if quota_by_stratum
            .insert(quota.stratum_id.clone(), quota.sample_size)
            .is_some()
        {
            return Err(StratifiedAuditError::DuplicateQuota(
                quota.stratum_id.clone(),
            ));
        }
    }

    for quota_stratum in quota_by_stratum.keys() {
        if !grouped.contains_key(quota_stratum) {
            return Err(StratifiedAuditError::QuotaForUnknownStratum(
                quota_stratum.clone(),
            ));
        }
    }

    let mut strata = Vec::with_capacity(grouped.len());
    let mut selections = Vec::with_capacity(candidates.len());
    let mut audit_sample_size = 0usize;

    for (stratum_id, mut members) in grouped {
        let population_size = members.len();
        let sample_size = *quota_by_stratum
            .get(&stratum_id)
            .ok_or_else(|| StratifiedAuditError::MissingQuota(stratum_id.clone()))?;
        if sample_size == 0 || sample_size > population_size {
            return Err(StratifiedAuditError::InvalidQuota {
                stratum_id,
                sample_size,
                population_size,
            });
        }

        // Unique random priorities make this deterministic without an
        // arbitrary record-ID tie break inside the random selection.
        members.sort_by_key(|candidate| candidate.random_priority);
        let inclusion_probability = sample_size as f64 / population_size as f64;
        let distinct_pair_probability = if population_size < 2 || sample_size < 2 {
            0.0
        } else {
            (sample_size as f64 * (sample_size - 1) as f64)
                / (population_size as f64 * (population_size - 1) as f64)
        };

        for (index, member) in members.iter().enumerate() {
            selections.push(AuditSelection {
                record_id: member.record_id.clone(),
                stratum_id: stratum_id.clone(),
                selected_for_adjudication: index < sample_size,
                inclusion_probability,
            });
        }

        strata.push(AuditStratumPlan {
            stratum_id,
            population_size,
            sample_size,
            sampling_fraction: inclusion_probability,
            first_order_inclusion_probability: inclusion_probability,
            distinct_pair_joint_inclusion_probability: distinct_pair_probability,
        });
        audit_sample_size += sample_size;
    }

    // A quota for every nonempty stratum is mandatory; strata cannot silently
    // disappear from the probability sample.
    for stratum_id in quota_by_stratum.keys() {
        if !strata.iter().any(|stratum| &stratum.stratum_id == stratum_id) {
            return Err(StratifiedAuditError::QuotaForUnknownStratum(
                stratum_id.clone(),
            ));
        }
    }

    selections.sort_by(|left, right| {
        left.stratum_id
            .cmp(&right.stratum_id)
            .then_with(|| left.record_id.cmp(&right.record_id))
    });

    Ok(StratifiedAuditPlan {
        design_version: STRATIFIED_AUDIT_DESIGN_VERSION.to_owned(),
        design_id,
        randomization_manifest_ref,
        population_size: candidates.len(),
        audit_sample_size,
        strata,
        selections,
    })
}

impl StratifiedAuditPlan {
    /// Exact second-order inclusion probability under independent random
    /// selection across strata and simple random sampling without replacement
    /// within each stratum.
    pub fn joint_inclusion_probability(
        &self,
        left_record_id: &str,
        right_record_id: &str,
    ) -> Option<f64> {
        let left = self
            .selections
            .iter()
            .find(|selection| selection.record_id == left_record_id)?;
        let right = self
            .selections
            .iter()
            .find(|selection| selection.record_id == right_record_id)?;

        if left_record_id == right_record_id {
            return Some(left.inclusion_probability);
        }
        if left.stratum_id != right.stratum_id {
            return Some(left.inclusion_probability * right.inclusion_probability);
        }

        self.strata
            .iter()
            .find(|stratum| stratum.stratum_id == left.stratum_id)
            .map(|stratum| stratum.distinct_pair_joint_inclusion_probability)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn candidates() -> Vec<AuditCandidate> {
        vec![
            AuditCandidate {
                record_id: "a1".to_owned(),
                stratum_id: "domain-a".to_owned(),
                random_priority: 40,
            },
            AuditCandidate {
                record_id: "a2".to_owned(),
                stratum_id: "domain-a".to_owned(),
                random_priority: 10,
            },
            AuditCandidate {
                record_id: "a3".to_owned(),
                stratum_id: "domain-a".to_owned(),
                random_priority: 30,
            },
            AuditCandidate {
                record_id: "a4".to_owned(),
                stratum_id: "domain-a".to_owned(),
                random_priority: 20,
            },
            AuditCandidate {
                record_id: "b1".to_owned(),
                stratum_id: "domain-b".to_owned(),
                random_priority: 90,
            },
            AuditCandidate {
                record_id: "b2".to_owned(),
                stratum_id: "domain-b".to_owned(),
                random_priority: 70,
            },
            AuditCandidate {
                record_id: "b3".to_owned(),
                stratum_id: "domain-b".to_owned(),
                random_priority: 80,
            },
        ]
    }

    fn quotas() -> Vec<AuditStratumQuota> {
        vec![
            AuditStratumQuota { stratum_id: "domain-a".to_owned(), sample_size: 2 },
            AuditStratumQuota { stratum_id: "domain-b".to_owned(), sample_size: 1 },
        ]
    }

    fn build() -> StratifiedAuditPlan {
        build_stratified_random_audit_plan(
            &candidates(),
            &quotas(),
            "audit-design-v1",
            "custody://randomization-manifest/one",
        )
        .unwrap()
    }

    #[test]
    fn selects_exact_quotas_and_assigns_positive_first_order_probabilities() {
        let plan = build();
        assert_eq!(plan.population_size, 7);
        assert_eq!(plan.audit_sample_size, 3);
        let selected_a = plan
            .selections
            .iter()
            .filter(|row| row.stratum_id == "domain-a" && row.selected_for_adjudication)
            .count();
        let selected_b = plan
            .selections
            .iter()
            .filter(|row| row.stratum_id == "domain-b" && row.selected_for_adjudication)
            .count();
        assert_eq!(selected_a, 2);
        assert_eq!(selected_b, 1);
        assert!(plan.selections.iter().all(|row| row.inclusion_probability > 0.0));
        assert_eq!(
            plan.selections
                .iter()
                .find(|row| row.record_id == "a1")
                .unwrap()
                .inclusion_probability,
            0.5
        );
        assert!((plan.selections
            .iter()
            .find(|row| row.record_id == "b1")
            .unwrap()
            .inclusion_probability
            - 1.0 / 3.0)
            .abs()
            < 1e-12);
    }

    #[test]
    fn within_stratum_joint_probabilities_match_srs_without_replacement() {
        let plan = build();
        assert_eq!(plan.joint_inclusion_probability("a1", "a1"), Some(0.5));
        assert!((plan.joint_inclusion_probability("a1", "a2").unwrap() - 1.0 / 6.0).abs() < 1e-12);
        assert_eq!(plan.joint_inclusion_probability("b1", "b2"), Some(0.0));
        assert_eq!(plan.joint_inclusion_probability("missing", "a1"), None);
    }

    #[test]
    fn cross_stratum_joint_probability_is_the_product_under_independent_strata() {
        let plan = build();
        assert!((plan.joint_inclusion_probability("a1", "b1").unwrap() - 1.0 / 6.0).abs() < 1e-12);
    }

    #[test]
    fn selected_units_are_exactly_the_lowest_random_priorities_in_each_stratum() {
        let plan = build();
        let selected: HashSet<&str> = plan
            .selections
            .iter()
            .filter(|row| row.selected_for_adjudication)
            .map(|row| row.record_id.as_str())
            .collect();
        assert_eq!(
            selected,
            HashSet::from(["a2", "a4", "b2"])
        );
    }

    #[test]
    fn census_stratum_has_unit_first_and_second_order_probabilities() {
        let mut input = candidates();
        input.retain(|candidate| candidate.stratum_id == "domain-b");
        let quota = vec![AuditStratumQuota {
            stratum_id: "domain-b".to_owned(),
            sample_size: 3,
        }];
        let plan = build_stratified_random_audit_plan(
            &input,
            &quota,
            "census-audit-v1",
            "custody://randomization-manifest/census",
        )
        .unwrap();
        assert!(plan.selections.iter().all(|row| {
            row.selected_for_adjudication && row.inclusion_probability == 1.0
        }));
        assert_eq!(plan.joint_inclusion_probability("b1", "b2"), Some(1.0));
    }

    #[test]
    fn duplicate_record_ids_are_rejected() {
        let mut input = candidates();
        input[1].record_id = input[0].record_id.clone();
        assert_eq!(
            build_stratified_random_audit_plan(
                &input,
                &quotas(),
                "audit-design-v1",
                "custody://randomization-manifest/one",
            )
            .unwrap_err(),
            StratifiedAuditError::DuplicateRecordId("a1".to_owned())
        );
    }

    #[test]
    fn output_is_invariant_to_input_record_and_quota_order() {
        let original = build();
        let mut reordered_candidates = candidates();
        reordered_candidates.reverse();
        let mut reordered_quotas = quotas();
        reordered_quotas.reverse();
        let reordered = build_stratified_random_audit_plan(
            &reordered_candidates,
            &reordered_quotas,
            "audit-design-v1",
            "custody://randomization-manifest/one",
        )
        .unwrap();
        assert_eq!(original, reordered);
    }

    #[test]
    fn tied_random_priorities_fail_instead_of_using_identifier_as_a_tiebreak() {
        let mut input = candidates();
        input[0].random_priority = input[1].random_priority;
        assert!(matches!(
            build_stratified_random_audit_plan(
                &input,
                &quotas(),
                "audit-design-v1",
                "custody://randomization-manifest/one",
            ),
            Err(StratifiedAuditError::DuplicatePriorityWithinStratum { .. })
        ));
    }

    #[test]
    fn missing_duplicate_and_unknown_quotas_fail_closed() {
        let input = candidates();
        let missing = vec![AuditStratumQuota { stratum_id: "domain-a".to_owned(), sample_size: 2 }];
        assert_eq!(
            build_stratified_random_audit_plan(
                &input,
                &missing,
                "audit-design-v1",
                "custody://randomization-manifest/one",
            )
            .unwrap_err(),
            StratifiedAuditError::MissingQuota("domain-b".to_owned())
        );

        let duplicate = vec![
            AuditStratumQuota { stratum_id: "domain-a".to_owned(), sample_size: 2 },
            AuditStratumQuota { stratum_id: "domain-a".to_owned(), sample_size: 1 },
            AuditStratumQuota { stratum_id: "domain-b".to_owned(), sample_size: 1 },
        ];
        assert!(matches!(
            build_stratified_random_audit_plan(
                &input,
                &duplicate,
                "audit-design-v1",
                "custody://randomization-manifest/one",
            ),
            Err(StratifiedAuditError::DuplicateQuota(_))
        ));

        let unknown = vec![
            AuditStratumQuota { stratum_id: "domain-a".to_owned(), sample_size: 2 },
            AuditStratumQuota { stratum_id: "domain-b".to_owned(), sample_size: 1 },
            AuditStratumQuota { stratum_id: "unknown".to_owned(), sample_size: 1 },
        ];
        assert!(matches!(
            build_stratified_random_audit_plan(
                &input,
                &unknown,
                "audit-design-v1",
                "custody://randomization-manifest/one",
            ),
            Err(StratifiedAuditError::QuotaForUnknownStratum(_))
        ));
    }

    #[test]
    fn zero_and_over_population_quotas_are_rejected() {
        for sample_size in [0, 5] {
            let quota = vec![
                AuditStratumQuota { stratum_id: "domain-a".to_owned(), sample_size },
                AuditStratumQuota { stratum_id: "domain-b".to_owned(), sample_size: 1 },
            ];
            assert!(matches!(
                build_stratified_random_audit_plan(
                    &candidates(),
                    &quota,
                    "audit-design-v1",
                    "custody://randomization-manifest/one",
                ),
                Err(StratifiedAuditError::InvalidQuota { .. })
            ));
        }
    }

    #[test]
    fn invalid_design_identity_and_empty_cohort_are_rejected() {
        assert_eq!(
            build_stratified_random_audit_plan(
                &candidates(),
                &quotas(),
                "",
                "custody://randomization-manifest/one",
            )
            .unwrap_err(),
            StratifiedAuditError::EmptyDesignId
        );
        assert_eq!(
            build_stratified_random_audit_plan(
                &candidates(),
                &quotas(),
                "audit-design-v1",
                "",
            )
            .unwrap_err(),
            StratifiedAuditError::EmptyRandomizationManifestReference
        );
        assert_eq!(
            build_stratified_random_audit_plan(
                &[],
                &[],
                "audit-design-v1",
                "custody://randomization-manifest/one",
            )
            .unwrap_err(),
            StratifiedAuditError::EmptyCohort
        );
    }
}
