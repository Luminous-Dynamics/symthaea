select_backend() {
    case "$BACKEND" in
        cpu)
            BROCA_MAMBA_BACKEND=cpu broca_resolve_runtime
            CARGO_FEATURE_ARGS=()
            NIX_SHELL_ATTR="."
            ;;
        gpu)
