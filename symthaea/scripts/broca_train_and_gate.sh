            { lines[NR] = $0 }
            END {
                if (n <= 0 || NR == 0) {
                    exit
                }
                if (n >= NR) {
                    for (i = 1; i <= NR; i++) {
                        print lines[i]
                    }
                    exit
                }
                if (n == 1) {
                    print lines[1]
                    exit
                }
                step = 997
                while (gcd(step, NR) != 1) {
                    step += 2
                }
                for (i = 0; i < n; i++) {
                    idx = ((i * step) % NR) + 1
                    print lines[idx]
                }
            }
            function gcd(a, b, t) {
                while (b != 0) {
                    t = a % b
                    a = b
                    b = t
                }
                return a
            }
