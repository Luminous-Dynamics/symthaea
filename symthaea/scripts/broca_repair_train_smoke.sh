# End-to-end repair learning smoke:
#   forced repair benchmark -> repair lessons -> Broca repair JSONL -> short train.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

OUT_DIR="${BROCA_REPAIR_SMOKE_OUT_DIR:-/tmp/symthaea-broca-repair-smoke}"
mkdir -p "$OUT_DIR"

export CODING_BACKEND_LANE=repair
export CODING_BACKEND_OUT_DIR="$OUT_DIR/coding"
export CODING_BACKEND_REPAIR_LESSONS="$OUT_DIR/repair-lessons.jsonl"
export CODING_BACKEND_BROCA_REPAIR_TRAINING="$OUT_DIR/broca-repair-training.jsonl"

echo "[broca-repair-smoke] collecting repair lessons"
scripts/coding_backend_regression.sh

echo "[broca-repair-smoke] training Broca on repair lessons"
BROCA_SMOKE_OUT_DIR="$OUT_DIR/broca" \
BROCA_SMOKE_TRAIN_DATA="$CODING_BACKEND_BROCA_REPAIR_TRAINING" \
BROCA_SMOKE_PAIRS="${BROCA_REPAIR_SMOKE_PAIRS:-6}" \
BROCA_SMOKE_EPOCHS="${BROCA_REPAIR_SMOKE_EPOCHS:-1}" \
BROCA_SMOKE_NEGATIVE_SAMPLES="${BROCA_REPAIR_SMOKE_NEGATIVE_SAMPLES:-64}" \
BROCA_SMOKE_BACKEND="${BROCA_REPAIR_SMOKE_BACKEND:-cpu}" \
BROCA_SMOKE_USE_NIX="${BROCA_REPAIR_SMOKE_USE_NIX:-0}" \
BROCA_SMOKE_BASELINE="${BROCA_REPAIR_SMOKE_BASELINE:-0}" \
BROCA_SMOKE_CANONICAL="${BROCA_REPAIR_SMOKE_CANONICAL:-0}" \
BROCA_SMOKE_CODE_SHEAF_EVAL="${BROCA_REPAIR_SMOKE_CODE_SHEAF_EVAL:-0}" \
BROCA_SMOKE_EVAL_LANE="${BROCA_REPAIR_SMOKE_EVAL_LANE:-fast}" \
BROCA_SMOKE_EVAL_LIMIT="${BROCA_REPAIR_SMOKE_EVAL_LIMIT:-8}" \
BROCA_SMOKE_MAX_GEN_TOKENS="${BROCA_REPAIR_SMOKE_MAX_GEN_TOKENS:-8}" \
BROCA_SMOKE_SELECT="${BROCA_REPAIR_SMOKE_SELECT:-0}" \
BROCA_SMOKE_CODING_REPORT="${BROCA_REPAIR_SMOKE_CODING_REPORT:-$OUT_DIR/coding/benchmark-coding-backends-repair.json}" \
BROCA_SMOKE_REPAIR_MEMORY_AB_SUMMARY="${BROCA_REPAIR_SMOKE_REPAIR_MEMORY_AB_SUMMARY:-}" \
BROCA_SMOKE_REQUIRE_CODING_GATE="${BROCA_REPAIR_SMOKE_REQUIRE_CODING_GATE:-0}" \
BROCA_SMOKE_REQUIRE_CODE_SIGNAL="${BROCA_REPAIR_SMOKE_REQUIRE_CODE_SIGNAL:-0}" \
BROCA_SMOKE_REQUIRE_CODING_EVAL_GATE="${BROCA_REPAIR_SMOKE_REQUIRE_CODING_EVAL_GATE:-0}" \
BROCA_SMOKE_REQUIRE_REPAIR_MEMORY_GATE="${BROCA_REPAIR_SMOKE_REQUIRE_REPAIR_MEMORY_GATE:-0}" \
BROCA_SMOKE_REQUIRE_TRAINED_IMPROVEMENT="${BROCA_REPAIR_SMOKE_REQUIRE_TRAINED_IMPROVEMENT:-0}" \
BROCA_SMOKE_MIN_CODING_SCORE="${BROCA_REPAIR_SMOKE_MIN_CODING_SCORE:-0}" \
BROCA_SMOKE_MIN_CODING_QUALITY_PASS_RATE="${BROCA_REPAIR_SMOKE_MIN_CODING_QUALITY_PASS_RATE:-0}" \
BROCA_SMOKE_MIN_REPAIR_MEMORY_HITS="${BROCA_REPAIR_SMOKE_MIN_REPAIR_MEMORY_HITS:-0}" \
BROCA_SMOKE_MIN_REPAIR_MEMORY_SUCCESS_RATE="${BROCA_REPAIR_SMOKE_MIN_REPAIR_MEMORY_SUCCESS_RATE:-0}" \
BROCA_SMOKE_MAX_REPAIR_MEMORY_HURT_TASKS="${BROCA_REPAIR_SMOKE_MAX_REPAIR_MEMORY_HURT_TASKS:-0}" \
scripts/broca_train_smoke.sh

echo "[broca-repair-smoke] PASS"
echo "  repair lessons:       $CODING_BACKEND_REPAIR_LESSONS"
echo "  broca repair training: $CODING_BACKEND_BROCA_REPAIR_TRAINING"
