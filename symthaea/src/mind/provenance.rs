#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_user_input_is_grounded() {
        let tag = ProvenanceTag::user_input(100);
        assert!(tag.is_grounded);
        assert!(tag.is_externally_grounded());
        assert_eq!(tag.attribution_confidence, 1.0);
        assert_eq!(tag.source, InformationSource::UserInput);
    }

    #[test]
    fn test_simulated_is_not_grounded() {
        let tag = ProvenanceTag::simulated(200);
        assert!(!tag.is_grounded);
        assert!(!tag.is_externally_grounded());
        assert_eq!(tag.source, InformationSource::Simulated);
    }

    #[test]
    fn test_merge_decays_confidence() {
        let a = ProvenanceTag::user_input(100);
        let b = ProvenanceTag::from_knowledge(100, 0.9);
        let merged = a.merge(&b);

        assert_eq!(merged.source, InformationSource::UserInput);
        assert!(merged.attribution_confidence < 1.0);
        assert!(merged.attribution_confidence <= PROVENANCE_MERGE_DECAY);
        assert!(merged.is_grounded); // either source grounded → merged is grounded
    }

    #[test]
    fn test_merge_collects_contributing_sources() {
        let a = ProvenanceTag::from_reasoning(100, vec![InformationSource::KnowledgeGraph]);
        let b = ProvenanceTag::from_episodic(100, 0.8);
        let merged = a.merge(&b);

        assert!(
            merged
                .contributing_sources
                .contains(&InformationSource::EpisodicMemory)
        );
        assert!(
            merged
                .contributing_sources
                .contains(&InformationSource::KnowledgeGraph)
        );
    }

    #[test]
    fn test_default_is_unknown_and_ungrounded() {
        let tag = ProvenanceTag::default();
        assert_eq!(tag.source, InformationSource::Unknown);
        assert!(!tag.is_grounded);
        assert_eq!(tag.attribution_confidence, 0.0);
    }

    #[test]
    fn test_serde_roundtrip() {
        let tag = ProvenanceTag::from_reasoning(
            42,
            vec![
                InformationSource::KnowledgeGraph,
                InformationSource::EpisodicMemory,
            ],
        );
        let json = serde_json::to_string(&tag).unwrap();
        let restored: ProvenanceTag = serde_json::from_str(&json).unwrap();
        assert_eq!(restored.source, tag.source);
        assert_eq!(
            restored.contributing_sources.len(),
            tag.contributing_sources.len()
        );
        assert_eq!(restored.produced_at_cycle, 42);
    }

    #[test]
    fn test_information_source_display() {
        assert_eq!(InformationSource::UserInput.as_str(), "user_input");
        assert_eq!(InformationSource::Simulated.as_str(), "simulated");
        assert_eq!(InformationSource::Unknown.as_str(), "unknown");
    }

    #[test]
    fn test_broca_provenance_inherits_input() {
        let input = ProvenanceTag::user_input(100);
        let broca = ProvenanceTag::from_broca(101, Some(&input));
        assert_eq!(broca.source, InformationSource::BrocaGeneration);
        assert!(
            broca
                .contributing_sources
                .contains(&InformationSource::UserInput)
        );
        assert!(broca.attribution_confidence < 1.0); // decayed
    }

    #[test]
    fn test_confidence_always_bounded() {
        let tag = ProvenanceTag::from_knowledge(100, 5.0); // out of range
        assert!(tag.attribution_confidence <= 1.0);
        assert!(tag.attribution_confidence >= 0.0);

        let tag2 = ProvenanceTag::from_knowledge(100, -1.0); // out of range
        assert!(tag2.attribution_confidence >= 0.0);
    }
}
