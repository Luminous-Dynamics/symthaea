/// Bridge between NixOS causal graph and symthaea-core's CausalMind.
pub struct CausalMindBridge;

impl CausalMindBridge {
    /// Seed a CausalMind with NixOS causal patterns.
    pub fn seed_from_patterns(mind: &mut symthaea_core::hdc::causal_mind::CausalMind) {
        for (cause, effect, _relationship) in
            crate::mind::causal_graph::NixOSCausalPatterns::known_patterns()
        {
            mind.add_causal_link(cause, effect, 0.8);
        }
    }

    /// Sync discovered causal edges into the CausalMind.
    pub fn sync_edges(
        mind: &mut symthaea_core::hdc::causal_mind::CausalMind,
        edges: &[CausalEdge],
    ) {
        for edge in edges {
            mind.add_causal_link(&edge.from, &edge.to, edge.confidence);
        }
    }

    /// Seed a CausalMind with edges derived from NixOS option schemas.
    pub fn seed_from_schemas(
        mind: &mut symthaea_core::hdc::causal_mind::CausalMind,
        schemas: &[crate::parser::option_schema::NixOptionSchema],
    ) {
        // Build a temporary causal graph and bootstrap from schemas
        let mut graph = crate::mind::causal_graph::NixCausalGraph::new(42);
        graph.bootstrap_from_schemas(schemas);
        // The structural edges are in the graph; predict side effects
        // to enumerate them and sync into CausalMind
        for schema in schemas {
            if schema.is_enable_option() {
                let effects = graph.predict_side_effects(&schema.name);
                for effect in effects {
                    mind.add_causal_link(
                        &schema.name,
                        &effect.affected_variable,
                        effect.confidence,
                    );
                }
            }
        }
    }

    /// Query the CausalMind for causal explanations.
    pub fn query_why(
        mind: &symthaea_core::hdc::causal_mind::CausalMind,
        symptom: &str,
    ) -> Vec<(String, f64)> {
        mind.query_why(symptom)
            .into_iter()
            .map(|e| (e.explanation.clone(), e.strength))
            .collect()
    }

    /// Query the CausalMind for predicted effects.
    pub fn query_what_if(
        mind: &symthaea_core::hdc::causal_mind::CausalMind,
        change: &str,
    ) -> Vec<(String, f64)> {
        mind.query_what_if(change)
            .into_iter()
            .map(|p| (p.prediction.clone(), p.probability))
            .collect()
    }
}

