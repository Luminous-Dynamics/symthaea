/// Bridge between the NixOS mind and the Symthaea actor system.
pub struct NixActorBridge {
    codebook: NixCodebook,
    surprise_threshold: f64,
}

impl NixActorBridge {
    /// Create a new actor bridge.
    pub fn new() -> Self {
        Self {
            codebook: NixCodebook::new(),
            surprise_threshold: 0.3,
        }
    }

    /// Set the surprise threshold for generating alert messages.
    pub fn with_surprise_threshold(mut self, threshold: f64) -> Self {
        self.surprise_threshold = threshold;
        self
    }

    /// Take a snapshot of the Nix mind's current state.
    pub fn snapshot(&self, engine: &NixActiveInference) -> NixActorState {
        let wm = engine.world_model();
        let hierarchy = wm.prediction_hierarchy();

        NixActorState {
            system_state: wm.system_state().clone(),
            free_energy: wm.free_energy(),
            phi: 0.0,
            confidence: 0.0,
            episode_count: engine.episode_count(),
            learned_actions: wm.learned_action_count(),
            total_observations: wm.total_observations(),
            failure_count: engine.episodic_memory().failure_count(),
            is_surprised: hierarchy.is_surprised(),
        }
    }

    /// Generate actor messages from a system observation.
    pub fn observe_system(&mut self, engine: &mut NixActiveInference) -> Vec<NixActorMessage> {
        let mut messages = Vec::new();

        if let Ok(snapshot) = crate::observe::SystemObserver::snapshot() {
            let mut encoder = crate::encoding::SystemStateEncoder::new(&mut self.codebook);
            let state_hv = encoder.encode_snapshot(&snapshot);

            engine.observe_state(state_hv.clone());

            let mut meta = HashMap::new();
            meta.insert("services".into(), snapshot.services.len().to_string());
            if let Some(r#gen) = snapshot.generation {
                meta.insert("generation".into(), r#gen.to_string());
            }

            messages.push(NixActorMessage {
                kind: NixMessageKind::StateObservation,
                content: state_hv,
                summary: format!(
                    "System snapshot: {} services, r#gen {:?}",
                    snapshot.services.len(),
                    snapshot.generation,
                ),
                from_role: NixActorRoles::SENSOR,
                to_role: NixActorRoles::PROCESSOR,
                priority: 0.5,
                metadata: meta,
            });

            let fe = engine.world_model().free_energy();
            if fe > self.surprise_threshold {
                messages.push(NixActorMessage {
                    kind: NixMessageKind::SurpriseAlert,
                    content: engine.world_model().system_state().clone(),
                    summary: format!("High prediction error: FE={fe:.3}"),
                    from_role: NixActorRoles::EVALUATOR,
                    to_role: NixActorRoles::COORDINATOR,
                    priority: 0.9,
                    metadata: HashMap::new(),
                });
            }
        }

        messages
    }

    /// Generate messages from a user input event.
    pub fn process_input(
        &self,
        engine: &mut NixActiveInference,
        input: &str,
    ) -> (ActionPlan, Vec<NixActorMessage>) {
        let plan = engine.process_input(input);
        let mut messages = Vec::new();

        let goal_hv = engine.goal_inference().current_goal();
        let mut goal_meta = HashMap::new();
        goal_meta.insert("input".into(), input.to_string());
        goal_meta.insert("confidence".into(), format!("{:.3}", plan.goal.confidence));

        messages.push(NixActorMessage {
            kind: NixMessageKind::GoalUpdate,
            content: goal_hv,
            summary: format!(
                "Goal: {} (conf={:.2})",
                plan.goal.description, plan.goal.confidence
            ),
            from_role: NixActorRoles::SENSOR,
            to_role: NixActorRoles::PROCESSOR,
            priority: 0.8,
            metadata: goal_meta,
        });

        if let Some(best) = plan.actions.first() {
            let mut plan_meta = HashMap::new();
            plan_meta.insert("action".into(), format!("{:?}", best.action));
            plan_meta.insert("efe".into(), format!("{:.3}", best.expected_free_energy));
            plan_meta.insert("pragmatic".into(), format!("{:.3}", best.pragmatic_value));
            plan_meta.insert("epistemic".into(), format!("{:.3}", best.epistemic_value));
            plan_meta.insert(
                "needs_clarification".into(),
                plan.needs_clarification.to_string(),
            );

            messages.push(NixActorMessage {
                kind: NixMessageKind::ActionPlan,
                content: engine.world_model().system_state().clone(),
                summary: format!(
                    "Plan: {:?} (EFE={:.3}, {} candidates)",
                    best.action,
                    best.expected_free_energy,
                    plan.actions.len(),
                ),
                from_role: NixActorRoles::PROCESSOR,
                to_role: NixActorRoles::DECIDER,
                priority: 0.7,
                metadata: plan_meta,
            });
        }

        (plan, messages)
    }

    /// Generate a message for an action outcome (success/failure).
    pub fn report_outcome(
        &self,
        engine: &mut NixActiveInference,
        action: &str,
        outcome: EpisodeOutcome,
        state_after: ContinuousHV,
    ) -> Vec<NixActorMessage> {
        let mut messages = Vec::new();

        let valence = match &outcome {
            EpisodeOutcome::Success => 1.0,
            EpisodeOutcome::PartialSuccess(_) => 0.3,
            EpisodeOutcome::Failure(_) => -1.0,
            EpisodeOutcome::RolledBack(_) => -0.5,
        };

        // Learn from the outcome
        let state_before = engine.world_model().system_state().clone();
        let action_cat = ActionCategory::from_command(action);
        engine.learn_from_outcome(
            &state_before,
            action_cat,
            &state_after,
            outcome.clone(),
            0.5,
        );

        // Outcome message: Effector → Memory
        let mut meta = HashMap::new();
        meta.insert("action".into(), action.to_string());
        meta.insert("valence".into(), format!("{valence:.2}"));
        let outcome_str = match &outcome {
            EpisodeOutcome::Success => "success".to_string(),
            EpisodeOutcome::Failure(r) => format!("failure: {r}"),
            EpisodeOutcome::PartialSuccess(r) => format!("partial: {r}"),
            EpisodeOutcome::RolledBack(r) => format!("rollback: {r}"),
        };
        meta.insert("outcome".into(), outcome_str.clone());

        messages.push(NixActorMessage {
            kind: NixMessageKind::ActionOutcome,
            content: state_after,
            summary: format!("Outcome of '{action}': {outcome_str}"),
            from_role: NixActorRoles::EFFECTOR,
            to_role: NixActorRoles::MEMORY,
            priority: 0.6,
            metadata: meta,
        });

        messages
    }

    /// Generate messages from causal discovery.
    pub fn report_causal_edges(&self, edges: &[CausalEdge]) -> Vec<NixActorMessage> {
        if edges.is_empty() {
            return Vec::new();
        }

        let summary = format!(
            "Discovered {} causal edges (strongest: {} → {} @ {:.2})",
            edges.len(),
            edges.first().map(|e| e.from.as_str()).unwrap_or("?"),
            edges.first().map(|e| e.to.as_str()).unwrap_or("?"),
            edges.first().map(|e| e.confidence).unwrap_or(0.0),
        );

        let dim = 128;
        let content = ContinuousHV::random(dim, 42);

        let mut meta = HashMap::new();
        meta.insert("edge_count".into(), edges.len().to_string());
        for (i, edge) in edges.iter().take(10).enumerate() {
            meta.insert(
                format!("edge_{i}"),
                format!("{} → {} ({:.2})", edge.from, edge.to, edge.confidence),
            );
        }

        vec![NixActorMessage {
            kind: NixMessageKind::CausalInsight,
            content,
            summary,
            from_role: NixActorRoles::PROCESSOR,
            to_role: NixActorRoles::MEMORY,
            priority: 0.4,
            metadata: meta,
        }]
    }
}

impl Default for NixActorBridge {
    fn default() -> Self {
        Self::new()
    }
}

