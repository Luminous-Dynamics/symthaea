/// Complete snapshot of the Nix mind's state.
#[derive(Debug, Clone)]
pub struct NixActorState {
    /// Current system state vector.
    pub system_state: ContinuousHV,
    /// Current free energy (prediction error from goal).
    pub free_energy: f64,
    /// Current consciousness metrics.
    pub phi: f64,
    /// Confidence in current goal interpretation.
    pub confidence: f64,
    /// Number of episodes in memory.
    pub episode_count: usize,
    /// Number of learned action transitions.
    pub learned_actions: usize,
    /// Total system observations.
    pub total_observations: usize,
    /// Recent failure count.
    pub failure_count: usize,
    /// Whether the prediction hierarchy is surprised.
    pub is_surprised: bool,
}

/// Recommended actor roles for NixOS subsystems.
pub struct NixActorRoles;

impl NixActorRoles {
    pub const SENSOR: &'static str = "nix.sensor";
    pub const PROCESSOR: &'static str = "nix.processor";
    pub const DECIDER: &'static str = "nix.decider";
    pub const EFFECTOR: &'static str = "nix.effector";
    pub const MEMORY: &'static str = "nix.memory";
    pub const EVALUATOR: &'static str = "nix.evaluator";
    pub const COORDINATOR: &'static str = "nix.coordinator";

    /// All role IDs, for batch spawning.
    pub fn all() -> &'static [&'static str] {
        &[
            Self::SENSOR,
            Self::PROCESSOR,
            Self::DECIDER,
            Self::EFFECTOR,
            Self::MEMORY,
            Self::EVALUATOR,
            Self::COORDINATOR,
        ]
    }
}

