//! Actor Bridge — NixOS State → Symthaea Actor Messages
//!
//! Translates NixOS system state and mind output into a form the main Symthaea
//! actor system can consume. Since symthaea-nix cannot depend on the main
//! symthaea crate (which depends on us), this module defines:
//!
//! - `NixActorState`: a self-contained snapshot of the Nix mind's state
//! - `NixActorMessage`: domain-specific messages the actor system can route
//! - `NixActorBridge`: the bridge that produces these from the Nix mind
//!
//! The main crate's actor system instantiates actors and wires them using these
//! types as the interchange format.

use std::collections::HashMap;
use symthaea_core::hdc::ContinuousHV;

use crate::encoding::NixCodebook;
use crate::mind::{
    ActionCategory, ActionPlan, CausalEdge, EpisodeOutcome, NixActiveInference, SystemEpisode,
};

// =============================================================================
// ACTOR MESSAGE TYPES
// =============================================================================

/// NixOS-specific message types for the actor system.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NixMessageKind {
    /// System state observation (Sensor → Processor).
    StateObservation,
    /// Action plan generated by active inference (Processor → Decider).
    ActionPlan,
    /// Action outcome feedback (Effector → Memory).
    ActionOutcome,
    /// Causal insight discovered (Processor → Memory).
    CausalInsight,
    /// Free energy alarm (Evaluator → Coordinator).
    SurpriseAlert,
    /// Request for episodic memory recall (Decider → Memory).
    MemoryRecall,
    /// Episodic memory response (Memory → Decider).
    MemoryResponse,
    /// Goal state update from user input (Sensor → Processor).
    GoalUpdate,
}

/// A message produced by the NixOS actor bridge for the main actor system.
#[derive(Debug, Clone)]
pub struct NixActorMessage {
    /// What kind of message this is.
    pub kind: NixMessageKind,
    /// HDC-encoded content vector.
    pub content: ContinuousHV,
    /// Human-readable summary.
    pub summary: String,
    /// Suggested sender role name.
    pub from_role: &'static str,
    /// Suggested receiver role name.
    pub to_role: &'static str,
    /// Priority (higher = process first).
    pub priority: f32,
    /// Arbitrary metadata.
    pub metadata: HashMap<String, String>,
}

