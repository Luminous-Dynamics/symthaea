/// Trait for bridging NixOS episodic memory into the main Symthaea hippocampus.
///
/// The main crate implements this trait to wire `NixEpisodicMemory` episodes
/// into the `HippocampusActor`.
pub trait HippocampusBridge: Send + Sync {
    /// Store a NixOS episode as a hippocampal memory trace.
    fn store_episode(&self, episode: &SystemEpisode) -> Result<u64, String>;

    /// Recall episodes similar to a query state.
    fn recall_similar(&self, query: &ContinuousHV, top_k: usize) -> Vec<SystemEpisode>;

    /// Trigger memory consolidation.
    fn consolidate(&self) -> usize;
}

