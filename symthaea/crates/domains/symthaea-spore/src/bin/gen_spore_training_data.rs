// ============================================================================
// Main
// ============================================================================

fn main() {
    let vocab_set: HashSet<&str> = WORD_VOCAB.iter().copied().collect();

    let categories = build_categories();

    let mut all_pairs: Vec<(Vec<f32>, String)> = Vec::new();
    let mut rng = Rng::new(42);
    let mut validation_errors: Vec<String> = Vec::new();

    for (cat_idx, cat) in categories.iter().enumerate() {
        // Generate multiple variations per template
        let repeats = 8; // ~30 templates x 8 = ~240 per category x 10 categories = ~2400

        for _ in 0..repeats {
            for template in &cat.templates {
                // Validate all words in template
                let text = template.join(" ");
                for word in template.iter() {
                    let w = word.to_lowercase();
                    let trimmed = w.trim_matches(|c: char| !c.is_alphanumeric());
                    if trimmed.is_empty() {
                        continue;
                    }
                    // Single char handled by ASCII path in tokenizer
                    if trimmed.len() == 1 {
                        let ch = trimmed.as_bytes()[0];
                        if (0x20..=0x7E).contains(&ch) {
                            continue;
                        }
                    }
                    if !vocab_set.contains(trimmed) {
                        validation_errors.push(format!(
                            "Word '{}' not in WORD_VOCAB (category {}, text: {})",
                            trimmed, cat_idx, text
                        ));
                    }
                }

                // Generate channels with jitter
                let mut channels = Vec::with_capacity(12);
                for &(lo, hi) in &cat.channel_ranges {
                    let val = lo + rng.next_f32() * (hi - lo);
                    channels.push(val);
                }

                all_pairs.push((channels, text));
            }
        }
    }

    // Check for validation errors
    if !validation_errors.is_empty() {
        let unique: HashSet<String> = validation_errors.into_iter().collect();
        eprintln!(
            "VALIDATION ERRORS: {} unique out-of-vocab words found:",
            unique.len()
        );
        for err in &unique {
            eprintln!("  {}", err);
        }
        std::process::exit(1);
    }

    // Shuffle
    rng.shuffle(&mut all_pairs);

    eprintln!("Generated {} total pairs", all_pairs.len());

    // Split 80/20
    let split = (all_pairs.len() as f64 * 0.8) as usize;
    let (train, eval) = all_pairs.split_at(split);

    eprintln!("  Train: {} pairs", train.len());
    eprintln!("  Eval:  {} pairs", eval.len());

    // Write train
    let train_path = "data/train-spore-vocab.jsonl";
    let eval_path = "data/eval-spore-vocab.jsonl";

    // Ensure data/ exists
    std::fs::create_dir_all("data").expect("create data/");

    write_jsonl(train_path, train);
    write_jsonl(eval_path, eval);

    eprintln!("Written:");
    eprintln!("  {}", train_path);
    eprintln!("  {}", eval_path);

    // Verify UNK rate
    let mut total_words = 0usize;
    let mut unk_words = 0usize;
    for (_, text) in &all_pairs {
        for word in text.split_whitespace() {
            let lower = word.to_lowercase();
            let trimmed = lower.trim_matches(|c: char| !c.is_alphanumeric());
            total_words += 1;
            if trimmed.is_empty() {
                continue;
            }
            if trimmed.len() == 1 {
                let ch = trimmed.as_bytes()[0];
                if (0x20..=0x7E).contains(&ch) {
                    continue;
                }
            }
            if !vocab_set.contains(trimmed) {
                unk_words += 1;
            }
        }
    }
    eprintln!(
        "UNK rate: {:.1}% ({}/{} words)",
        100.0 * unk_words as f64 / total_words.max(1) as f64,
        unk_words,
        total_words,
    );
}

fn write_jsonl(path: &str, pairs: &[(Vec<f32>, String)]) {
    let mut file = std::fs::File::create(path).expect("create file");
    for (channels, text) in pairs {
        // Format: {"channels": [...], "target_text": "..."}
        let ch_str: Vec<String> = channels.iter().map(|c| format!("{:.4}", c)).collect();
        let line = format!(
            "{{\"channels\": [{}], \"target_text\": \"{}\"}}\n",
            ch_str.join(", "),
            text.replace('"', "\\\"")
        );
        file.write_all(line.as_bytes()).expect("write");
    }
}
